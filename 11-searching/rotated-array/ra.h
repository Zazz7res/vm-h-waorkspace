#ifndef RA_H
#define RA_H

/*
 * ===================================================================
 * 旋转数组查找 Rotated Array Search —— 这一节的"菜单"
 * ===================================================================
 * 这个文件里【只有声明】。真正的代码和"为什么这么写"在 ra.c。
 *
 * -------------------------------------------------------------------
 * 一、什么叫"旋转数组"？
 * -------------------------------------------------------------------
 * 把一份升序数组，从中间某处**剪一刀，两段左右对调**：
 *
 *      原始升序：  0  1  2  3  4  5  6
 *      在 3 处剪开：[0 1 2] [3 4 5 6]
 *      对调拼接：  3  4  5  6  0  1  2      ← 这就是"旋转了 3 次"
 *
 *      下标：      0  1  2  3  4  5  6
 *      值：        3  4  5  6  0  1  2
 *                       升序段1  ↑  升段2
 *                                |
 *                          这里有个"断崖"（唯一的下降点）
 *
 * 一句话记住它的结构特征：
 *   ★ **整个数组由两段各自升序的段拼成，而且后一段的每个值都 ≤ 前一段的每个值。**
 *   ★ 所以**有且只有一个下降点**（不旋转时 0 个；有重复值时可能有相等的相邻点）。
 *   ★ 那个下降点的**右边第一个下标**，就是全数组**最小值**的位置，叫**旋转点 / pivot**。
 *
 * -------------------------------------------------------------------
 * 二、为什么它值得单开一节？（普通二分为什么不灵了）
 * -------------------------------------------------------------------
 * 二分查找的全部底气来自一句话：**"a[mid] 和目标比完，能安全扔掉一半"**。
 * 在旋转数组里，a[mid] 两边的走势不一致（一边升、一边也可能藏着断崖），
 * 于是脑子里第一版的"标准二分"直接套上去就会漏答案。
 *
 * 本节要解决的核心分歧只有一个问题：
 *     **拿到 mid 之后，我凭什么判断该往哪半边扔？**
 * 答案：先判断 **mid 落在哪一段**（左升段还是右升段），
 *       再在**确定的那一段**里用普通二分。判断手段就是本节所有代码的骨架。
 *
 * -------------------------------------------------------------------
 * 三、判据为什么是「a[mid] vs a[right]」而不是「a[mid] vs a[left]」
 * -------------------------------------------------------------------
 * 这是本节**最容易被写错、也最值得亲手撞一次**的地方（ra_demo_why_left_fails 专门演）。
 * 以"找最小值"为例，正确写法是：
 *
 *      if (a[mid] > a[right])  left = mid + 1;   // 断崖在 mid 右边，mid 自己肯定不是最小
 *      else                    right = mid;      // 断崖在 mid 左边或没有，最小值 ≤ mid
 *
 * 直觉解释：把 a[right] 当成"当前窗口里最后一个值"。
 *   · a[mid] 比它还大 → mid 落在**前一段（大值段）**，最小值必然在它右边；
 *   · a[mid] 不比它大 → mid 已经**在尾段（小值段）**或者整段无断崖，最小值就在 ≤ mid 的位置。
 *
 * 而和 a[left] 比会输掉信息：**a[mid] > a[left] 这一件事在两种完全不同的局面下都会成立** ——
 * 要么"整个窗口根本没断崖，最小值就在左边"，要么"断崖还在右边没走到"。
 * 一个条件对应两种结论 ⇒ 这个条件不够用，这就是它不成立的根本原因。
 *
 * -------------------------------------------------------------------
 * 四、查找目标值的两种写法（本节都实现，并互相验收）
 * -------------------------------------------------------------------
 * 【写法 A：一次二分 + 判半区】
 *   每一步先确定"mid 所在的半边是不是有序的"，再看目标值有没有落进那个有序区间：
 *      if (a[left] <= a[mid])  → 左半 [left..mid] 有序
 *             目标在 [a[left], a[mid]) 内 → 往左扔；否则往右扔
 *      else                    → 右半 [mid..right] 有序（因为断崖在左边）
 *             目标在 (a[mid], a[right]] 内 → 往右扔；否则往左扔
 *   注意左半分支用的是 `a[left] <= a[mid]`（带等号）：无重复值时 `==` 只在 left==mid 出现，
 *   那时区间只剩一个元素，带不带等号都不影响正确性，但**有重复值时等号就是致命的**（见第五点）。
 *
 * 【写法 B：先找旋转点，再"虚拟下标"二分】
 *   既然旋转数组 = 升序数组循环挪了一段，那就不如**根本不挪**：
 *   在脑子里把它当回升序数组，二分时把虚拟下标换算成真实下标：
 *        真实下标 = (虚拟 mid + pivot) % n
 *   于是**一份标准二分代码复用到底**，只是每次读数组前套一层 %n。
 *   这个思路极其有用：任何"环形有序"的问题（轮转过的排班表、环形缓冲区里的有序数据）都能套。
 *
 * 两种写法复杂度都是 O(log n)，返回值必须完全一致 —— main.c 第 4 幕就是拿它俩对拍。
 *
 * -------------------------------------------------------------------
 * 五、有重复元素时会发生什么（复杂度会塌）
 * -------------------------------------------------------------------
 * 数组 `1 0 1 1 1`：a[left] == a[mid] == 1。此时**无法判断 mid 在哪一段**，
 * 因为"左边有序"和"右边有序"两种情况都能产生一模一样的三个数。
 * 唯一安全的做法是**扔掉一个重复的端点**再试：
 *      if (a[mid] == a[left])  left++;
 *      if (a[mid] == a[right]) right--;
 * 每扔一次只损失一个元素 ⇒ 最坏情况（全数组都是同一个值、而目标不在里面）
 * 要仍扔 n 次，**退化到 O(n)**。这不是代码写得烂，是**问题本身的信息量不够**，
 * 所以 LeetCode 154（找最小值）和 81（找目标）的"含重复"版本考的就是这一句结论。
 *
 * -------------------------------------------------------------------
 * 六、这一节顺手能解决的同族问题
 * -------------------------------------------------------------------
 * · 旋转了几次？→ 就是问最小值下标（ra_rotations）。
 * · 判断一个数组是不是"旋转过的升序数组"→ 数下降点个数（ra_is_rotated_sorted）。
 * · 旋转数组里第 k 小的值 → a[(pivot + k - 1) % n]，一次二分 + O(1)（main.c 第 8 幕）。
 *   —— 这一条正好和 11-searching/kth-smallest 接上：那节要 O(n) 的问题，这里因为"已知有序"只要 O(log n)。
 *
 * -------------------------------------------------------------------
 * 七、约定
 * -------------------------------------------------------------------
 * · 元素类型全部 int；下标全部 int；数组下标合法范围 [0, n-1]。
 * · 所有函数都要对 n<=0、NULL、越界 target 免疫：返回 -1 / 0 而不是崩。
 *   （这是本节的教学要求之一：边界处理要"看得见"，所以每个函数开头都有那几行 if。）
 * · steps_out：非空时把**循环轮数**写进去。这一节的核心卖点就是
 *   "每多一半就只多一轮"，所以要把轮数打成数字给你看，尤其是重复值退化那一幕。
 * · 本节不 malloc（全是栈上小数组），所以没有 free 责任；ASan 只用来证明没越界。
 */

/* 本节示例数组长度上限；main.c 里的示例都 ≤ 16，给到 64 留余量 */
#define RA_MAX_N 64

/* ---------- 0. 看清一个数组 ---------- */
/* label 为 NULL 时只打内容。会顺手标出断崖位置和最小值下标，方便对着图看 */
void ra_dump(const char *label, const int a[], int n);

/* ---------- 1. 找旋转点（= 最小值位置）---------- */
/*
 * 返回最小值所在下标；n<=0 返回 -1。
 * 写法：闭区间收缩成 [left,right) 的味道 —— `while (left < right)` + `right = mid`，
 *       这是"找第一个满足条件的位置"那套模板，**绝不能写成 right = mid - 1**（会把答案跳过去）。
 * steps_out：可 NULL，回填循环轮数。
 */
int ra_min_index(const int a[], int n, int *steps_out);

/* 只要值不只要下标：内部还是 ra_min_index（n<=0 返回 0，别问为什么，问就是边界） */
int ra_min_value(const int a[], int n);

/* 最大值下标 = 旋转点左边那个（(pivot + n - 1) % n）。注意"未旋转"时它就在最后 */
int ra_max_index(const int a[], int n);

/* 旋转了几次 = 最小值下标（把升序数组右移 pivot 格就得到当前样子） */
int ra_rotations(const int a[], int n);

/* ---------- 2. 无重复：查找目标值 ---------- */
/*
 * 写法 A：一次二分 + 判半区。
 * verbose 非 0 时每一步打一行：left/right/mid/a[mid]/判据/往哪扔。
 * steps_out：可 NULL，回填轮数。
 * 返回下标，找不到 -1。要求数组确实是"旋转过的严格升序"，否则结果无意义。
 */
int ra_search(const int a[], int n, int target, int verbose, int *steps_out);

/* 写法 B：先求 pivot，再用 (虚拟下标 + pivot) % n 复用标准二分。返回下标，找不到 -1 */
int ra_search_by_offset(const int a[], int n, int target, int verbose);

/* ---------- 3. 有重复：只能退化 ---------- */
/* 见顶部第五点。返回**某一个**合法下标（重复值时不保证是第一个），找不到 -1 */
int ra_search_dup(const int a[], int n, int target, int verbose, int *steps_out);

/* ---------- 4. 对照组 / 验收工具 ---------- */
/* 线性查找：O(n) 的"笨办法"，用来给上面所有二分做对拍验收 */
int ra_search_linear(const int a[], int n, int target);

/* 是不是"旋转过的非降数组"：数下降点，>1 个就不是。返回 1 是 / 0 否 */
int ra_is_rotated_sorted(const int a[], int n);

/* 严格升序版（用于 ra_search 的前置检查）：既要不降、又要没有相等相邻 */
int ra_is_strictly_rotated_asc(const int a[], int n);

/* ---------- 5. 本节招牌演示 ---------- */
/*
 * 亲手演一遍"拿 a[mid] 和 a[left] 比"为什么会错：
 * 给两个数组，a[left] < a[mid] 在两边都成立，但最小值一个在左、一个在右 ——
 * 一个条件推出两种结论，说明这个条件根本不足以决策。然后再跑正确判据对照。
 */
void ra_demo_why_left_fails(void);

/*
 * 反例专用：用"a[mid] vs a[left]"写出来的找最小值函数（**故意写错**）。
 * 只在 main.c 第 2 幕调用一次，用来说明错在哪；不要拿它当答案。
 */
int ra_min_index_wrong(const int a[], int n);

/* ---------- 6. 同族应用 ---------- */
/* 旋转数组里第 k 小（k 从 1 开始）。返回**下标**；k 非法返回 -1 */
int ra_kth_smallest_index(const int a[], int n, int k);

#endif /* RA_H */
