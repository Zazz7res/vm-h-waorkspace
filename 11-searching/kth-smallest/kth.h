#ifndef KTH_H
#define KTH_H

/*
 * ===================================================================
 * 第 K 小 / 顺序统计量 K-th Smallest —— 这一节的"菜单"
 * ===================================================================
 * 这个文件里【只有声明】。真正的代码和"为什么这么写"在 kth.c。
 *
 * -------------------------------------------------------------------
 * 一、问题到底在问什么（先把"第 k 小"这个词钉死）
 * -------------------------------------------------------------------
 * 给 n 个数，把它们**按位置**从小到大排好后，取第 k 个（本节 k 从 **1** 开始数）。
 *
 *      a = 7 2 9 1 5 3 8        排序后 1 2 3 5 7 8 9
 *      第 1 小 = 1，第 3 小 = 3，第 7 小 = 9 = 最大值
 *
 * ★ 重复值怎么算？**按位置算，不去重。** 这就是"顺序统计量"的标准语义：
 *      a = 5 5 5 9              第 2 小 = 5，第 3 小 = 5，第 4 小 = 9
 *   很多人第一反应是"第 2 小应该是 9"（把它想成"第二小的**不同**值"）——
 *   那是另一个问题（叫"第 k 个不同的值"），本节**不做**那个。
 *
 * ★ 边界：k < 1 或 k > n 一律返回失败。第 1 小 = 最小值，第 n 小 = 最大值 ——
 *   这两个极端是免费的验收点，每个函数都要能对上。
 *
 * -------------------------------------------------------------------
 * 二、五种方法，一张表看清谁在什么场景赢
 * -------------------------------------------------------------------
 *  ① 排序后取下标    O(n log n)   改动：副本        最简单；一次排序后还能回答所有 k
 *  ② 大小为 k 的大顶堆 O(n log k)  改动：只用 k 格内存 ★ **数据流/内存装不下** 的唯一解
 *  ③ 快速选择        平均 O(n)，最坏 O(n²)  改动：**打乱原数组**  一次性查询的王者
 *  ④ 值域计数        O(n + R)     改动：额外 R 格   值域小（分数、年龄、字符）时是线性且无脑
 *  ⑤ 值域二分答案    O(n log R)   改动：**完全不碰数据** 数据只读/在磁盘上/流式时的解
 *
 * （R = 值域宽度 = max - min + 1）
 *
 * 记住三句话：
 *   ★ 想知道**所有**排名 → 老老实实排序（①），其它方法回答单个 k 才划算。
 *   ★ 只想知道**一个** k → ③ 快选，平均线性，常数也小。
 *   ★ 数据**不能改 / 装不进内存** → ② 或 ⑤。
 *
 * -------------------------------------------------------------------
 * 三、快速选择为什么平均是 O(n)（这一节最重要的推导）
 * -------------------------------------------------------------------
 * partition 一趟要扫过当前区间的全部 m 个元素 ⇒ 花 m 次比较。
 * 如果每次 pivot 都落在正中，问题规模减半：
 *
 *      T(n) = T(n/2) + n
 *           = n + n/2 + n/4 + n/8 + …   <   2n
 *
 * 等比级数求和 **小于 2n** —— 这就是"平均线性"的来源。
 * 关键：**只递归一边**（快排要递归两边所以是 n log n，快选只跟着答案跑所以是 n）。
 * 这个"丢掉一边"的差别就是整节的灵魂。
 *
 * 反面：如果每次 pivot 都是当前区间的最小值，规模只减 1：
 *      T(n) = T(n-1) + n = n + (n-1) + … = O(n²)
 * 这就是第 5 幕要实测的现象 —— 拿「已排序数组 + 固定取首元素当 pivot」这条经典毒输入，
 * 把比较次数从几百次打到几千次给你看。**随机化 pivot 正是为杀掉这条毒输入而存在的。**
 * （理论上还有个"中位数的中位数"能保最坏 O(n)，但常数大到实战不如随机 pivot，本节只讲不实现，
 *  想深究见 README 的自检问题。）
 *
 * -------------------------------------------------------------------
 * 四、为什么是"大小为 k 的**大顶**堆"，不是小顶堆
 * -------------------------------------------------------------------
 * 我们要留住"目前最小的 k 个"，而淘汰对象永远是**这 k 个里最大的那个**（它最可能不是答案）。
 * 大顶堆的堆顶恰好就是"这 k 个里最大的" ⇒ 看一眼堆顶就知道该不该换、换谁。
 * 最后**堆顶**就是第 k 小（因为堆里装的就是最小的 k 个，而其中最大的正好排第 k）。
 *
 *      堆大小 = k，每个新元素最多一次 log k ⇒ O(n log k)；内存只要 k 格。
 *      当 k ≪ n（从 10 亿条日志里找最热的 10 条），n log k 几乎是线性的，而且能流式处理。
 *
 * 呼应 06-heap/binary-heap（堆本身怎么维护）和 06-heap/top-k（同一套思路的 Top-K 版）。
 *
 * -------------------------------------------------------------------
 * 五、值域上的两种"不比较大小排序"的做法
 * -------------------------------------------------------------------
 * ④ 计数：开一个 cnt[R]，扫一遍把所有值统计进去，然后从最小值往上累加，
 *    累到 ≥ k 的那个值就是答案。O(n + R)。前提：**R 不能爆炸**。
 * ⑤ 二分答案：不统计每个值，只回答一个**判据**问题 ——「≤ x 的数有几个？」（扫一遍 O(n)）。
 *    这个"个数关于 x 单调不减"，于是在值域 [min, max] 上二分，找**第一个让个数 ≥ k 的 x**。
 *    O(n log R)，不排序、不改数据、甚至不用把数据全读进内存（判据可流式扫）。
 *    —— 这是 11-searching/binary-search 里"二分答案"那一招的正牌应用场景。
 *
 * -------------------------------------------------------------------
 * 六、附加题：两个**有序**数组的第 k 小
 * -------------------------------------------------------------------
 * 归并到第 k 个是 O(k)；而"各切一刀"能在 O(log(min(m,n))) 内解决：
 * 在短数组里二分切点 i，长数组的切点 j = k - i 随之确定，只要验证
 *      a[i-1] <= b[j]  且  b[j-1] <= a[i]
 * 就说明"左半块刚好是 k 个最小的"，答案 = max(a[i-1], b[j-1])。
 * 这是二分查找最漂亮的一次实战，也是本节最后一个难点（kth_two_sorted）。
 *
 * -------------------------------------------------------------------
 * 七、约定
 * -------------------------------------------------------------------
 * · 元素类型全部 int；k 从 1 开始；非法输入返回 -1（或用 answer_out 回填、返回 0）。
 * · KTH_MAX_N = 64：所有示例数组在 main.c 的栈上，全节**不 malloc**，所以没有 free 责任。
 * · kth_quickselect 会**打乱传进来的数组**（就地 partition），所以 main.c 每次都传副本；
 *   这个"破坏性"在接口注释里必须写明 —— 它是快选便宜的原因（省了一次拷贝），也是它的代价。
 * · 比较次数用 long long 回填：n² 量级的计数会超过 int 的直觉范围，别在这里翻车。
 * · 随机 pivot 用的是**自写的 xorshift32**（固定种子），不是 rand()：
 *   为了让 README 里的数字每次跑都一样、可复现核对。教学代码最忌讳"输出对不上文档"。
 */

/* 本节示例数组长度上限 */
#define KTH_MAX_N 64

/* 计数法的值域上限：超过它就放弃此法（返回 0），换二分答案 */
#define KTH_COUNT_MAX_RANGE 256

/* 两有序数组各自的长度上限 */
#define KTH_MAX_M 32

/* ---------- 0. 看图工具 ---------- */
void kth_dump(const char *label, const int a[], int n);

/* ---------- 1. 方法①：排序 + 取下标 ---------- */
/*
 * 内部拷贝一份再插入排序（**故意用插入排序**：代码最短、且能顺手打印排序进度）。
 * cmp_out：可 NULL，回填比较次数（long long，别用 int 接）。
 * 返回第 k 小的值；k 非法返回 -1。
 */
int kth_by_sorting(const int a[], int n, int k, long long *cmp_out);

/* ---------- 2. 方法②：大小为 k 的大顶堆 ---------- */
/* verbose 非 0 时逐个元素打印堆的变化。返回第 k 小；k 非法返回 -1 */
int kth_by_heap(const int a[], int n, int k, int verbose);

/* ---------- 3. 方法③：快速选择 ---------- */
/*
 * ⚠ 就地打乱 a[]（Lomuto partition 必然改数组）。要保留原数组就先拷贝。
 * verbose 非 0 时打印每轮 partition 后的数组、pivot 落点、保留哪一边。
 * cmp_out：可 NULL，回填比较次数。k 非法返回 -1。
 */
int kth_quickselect(int a[], int n, int k, int verbose, long long *cmp_out);

/* 故意"每次取区间第一个元素当 pivot"的版本：配已排序输入 → 实测 O(n²) */
int kth_quickselect_bad_pivot(const int a[], int n, int k, long long *cmp_out);

/* ---------- 4. 方法④：值域计数 ---------- */
/* 返回 1 成功（答案写进 *answer_out）；返回 0 表示值域太宽，此法不适用 */
int kth_by_counting(const int a[], int n, int k, int *answer_out);

/* ---------- 5. 方法⑤：值域二分答案 ---------- */
/*
 * 判据：count_less_equal(x) = ≤ x 的元素个数（扫一遍 O(n)，关于 x 单调不减）。
 * 在 [min, max] 上二分"第一个使 count ≥ k 的 x"。完全不改动 a[]。
 * steps_out：可 NULL，回填值域上的二分轮数。
 */
int kth_by_value_binary_search(const int a[], int n, int k, int *steps_out);

/* ---------- 6. 附加题：两个有序数组的第 k 小 ---------- */
int kth_two_sorted(const int a[], int na, const int b[], int nb, int k);         /* O(log) 划分法 */
int kth_two_sorted_linear(const int a[], int na, const int b[], int nb, int k);  /* O(k) 归并，对拍用 */

/* ---------- 7. 衍生问题 ---------- */
/* 下中位数：第 (n+1)/2 小（n 为偶数时它是中间偏左那个，工程里常配对"上中位数"一起用） */
int kth_median_lower(const int a[], int n);
/* 上中位数：第 n/2 + 1 小 */
int kth_median_upper(const int a[], int n);

/* ---------- 8. 验收 ---------- */
/*
 * 把五种方法跑一遍并对拍：全部一致返回 1 并打印一行；有不一致返回 0 并打印差异。
 * （内部会拷贝数组喂给破坏性的快选，调用者的一手数据不受影响。）
 */
int kth_all_agree(const int a[], int n, int k, int verbose);

#endif /* KTH_H */
