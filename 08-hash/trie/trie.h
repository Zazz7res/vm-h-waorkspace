#ifndef TRIE_H
#define TRIE_H

/*
 * ===================================================================
 * 前缀树 Trie —— 这一节的"菜单"
 * ===================================================================
 * 这个文件里【只有声明】。真正的代码和"这行为什么存在"在 trie.c。
 *
 * -------------------------------------------------------------------
 * 一、Trie 解决的到底是什么问题：把"字符串"变成"一条路"
 * -------------------------------------------------------------------
 * 前面两节（拉链法 / 开放寻址）的哈希表，能问的问题只有一个：
 *
 *       "键 == card 的那条记录在哪？"          ← 整串精确查
 *
 * 为什么只能问这一个？因为哈希函数 h(key) 把整个字符串揉成一个【没有结构】的
 * 大整数（djb2：h = h*33 + c）。'c' 排在 'a' 前面、结尾是不是 'd'、有没有前缀
 * "ca"……这些【顺序信息】在乘加里全被搅碎了。信息碎了就拼不回来，于是这几类问题
 * 哈希表一个都答不了：
 *
 *       "以 ca 开头的词有哪些？"        （前缀查询）
 *       "输入 do，把所有补全列出来"      （自动补全）
 *       "把所有词按字典序输出"           （有序遍历）
 *       "以 ca 开头的词有几个？"         （前缀计数）
 *
 * 想问这些，哈希表只有一条路：把【每个键】都拿出来比一遍 —— O(n × L)。
 *
 * Trie 的做法是彻底换思路：**不揉，按字符一位一位往下分叉。**
 * 根节点代表"空前缀"，每往下走一步就多一个字符，所以
 * 【从根到某个节点的路径 = 这个节点代表的前缀】。
 *
 *          (root)  ""
 *            ├── c ............. "c"
 *            │    └── a ........ "ca"
 *            │         ├── r ... "car"  ← 完整单词（end_count > 0）
 *            │         │    └── d "card"← 完整单词
 *            │         └── t ... "cat"  ← 完整单词
 *            └── d ............. "d"
 *                 └── o ........ "do"   ← 完整单词
 *                      └── o ... "doo"
 *                           └── r "door"← 完整单词
 *
 * 于是"以 ca 开头的词有几个"变成了"走到 ca 那个节点，读它身上的一个计数器"：
 * 代价 = 走 2 步，和词表里有 5 个词还是 500 万个词【完全无关】。
 * 这就是本节最重要的一句话：**Trie 的快慢只看串长 L，不看词的个数 n。**
 *
 * -------------------------------------------------------------------
 * 二、两个计数器：这一节的教学重点
 * -------------------------------------------------------------------
 * 光有"路径"还不够 —— 怎么知道一条路径的末端是一个【真正的单词】，
 * 还是只是半个单词？又怎么知道"以 ca 开头的有几个"？答案是节点身上带两个 int：
 *
 *     pass_count —— 有多少个串【经过】这个节点（包括在这里结束的）
 *     end_count  —— 有多少个串【正好在这里结束】
 *
 * 记法：pass 是"流量"（路过我的车总数），end 是"站点"（在我这下车的）。
 * 必然有 end_count <= pass_count。看上面那棵树插 5 个词后的数字：
 *
 *     "ca"  节点：pass=3  end=0   ← 3 个串经过它（car/card/cat），但 ca 本身不是词
 *     "car" 节点：pass=2  end=1   ← card 经过它，car 在它这里结束
 *     "do"  节点：pass=2  end=1   ← door 经过它，do 在它这里结束
 *
 * 有了这两个数，两件事直接变成 O(1)：
 *     ① "以 ca 开头的串有几个" = ca.pass_count = 3        ← 不用遍历子树！
 *     ② "ca 本身是不是一个词"   = ca.end_count > 0 ? 不是  ← 不用看它有没有孩子！
 * 没有 pass_count 的话，第 ① 件事必须把子树里所有单词数一遍（O(子树大小)），
 * 第 ② 件事还会犯经典错误："有孩子就说明不是单词" —— 错，car 有孩子 d，它仍是单词。
 *
 * -------------------------------------------------------------------
 * 三、代价：空间换时间，换掉了什么（本节会把它算成真实字节数打印出来）
 * -------------------------------------------------------------------
 * 每个节点固定开 26 个指针，`26 × 8 = 208` 字节，再加两个 int（4 + 4）= 216 字节。
 * 而英语词表里绝大多数节点只有 1~2 个真实孩子 —— 剩下 24 个格子全是 NULL。
 * 本节会打印 sizeof(TrieNode)、节点总数、以及"26 个槽位里到底用了几个"，
 * 让你直观看到"费"在哪：Trie 是**用最直白的内存浪费换来 O(L) 的前缀能力**。
 *
 * 对比一下两节哈希表：
 *     哈希表：空间 O(n + m)，一个元素 ≈ 24 字节节点 + 键副本；能力 = 只能整串精确查。
 *     Trie  ：空间 O(所有串的总字符数 × 26)，一个字符 ≈ 216 字节；能力 = 前缀/补全/有序。
 * 一句话：**哈希表省内存但只会"问等于"，Trie 费内存但会"问开头"。**
 *
 * -------------------------------------------------------------------
 * 四、本节的三条规矩（和整个仓库一致）
 * -------------------------------------------------------------------
 *     1) 键允许 char *（字符串检索本来就是这一节的目的）；
 *        存的【值】一律 int —— 本节的"值"就是那两个计数器，不引入 void *。
 *     2) 禁止 void * 泛型、禁止函数指针比较器。
 *     3) 目录自包含：只 include 本目录的 trie.h 和标准库。
 *
 * 字符集只支持小写 'a'~'z'，串长上限 TRIE_WORD_MAX。
 * 这不是偷懒，是把"下标换算"的死风险挡在门口：child 数组只有 26 格，
 * 拿 'A' 算 idx 得到 -26，拿 '{' 算得到 29 —— 越界读写，编译器不会拦你，ASan 会。
 * trie_insert / trie_delete 都做了校验，第 8 幕会把非法输入真的喂进去看它被拒绝。
 */

/* 字符集大小：child[] 的长度。想支持大写/数字就得加大它，代价是每节点更多空格子。 */
#define TRIE_ALPHABET 26

/*
 * 一个词最长多少个字符（含结尾 '\0' 之前，最多 31 个字符）。
 * 为什么要写死？因为自动补全和打印树都要用【定长路径缓冲区】，
 * 缓冲区定长 = 可以放在栈上、不用 malloc、不会泄漏；但必须先有上界，
 * 才能理直气壮地拒绝超长输入（而不是把数组写爆）。
 */
#define TRIE_WORD_MAX 32

/*
 * Trie 的节点 —— 本节全部数据结构就这一个 typedef。
 *
 *   child[26]  —— 26 条"岔路"，格子编号就是字母：child[0]='a'、child[2]='c'……
 *                  NULL 表示"没有这个孩子"，也就是这条前缀到此为止。
 *                  ⚠ 它是【指针数组】，和 07-graph 的邻接表同构：数组负责跳转，
 *                    格子里的地址才是节点本体（散落在堆上）。
 *   end_count  —— 有几个串【正好在这个节点结束】。> 0 就说明这个前缀本身是个完整单词。
 *                  为什么是计数而不是 bool？因为要支持重复插入（词频）：
 *                  同一个词插 2 遍，end_count = 2，删一遍后还剩 1 —— 词还在。
 *                  用 bool 的话，删第一次就得把词误删掉。
 *   pass_count —— 有几个串【经过这个节点】（包含在它这里结束的那些）。
 *                  它就是"以这个节点代表的字符串为前缀的词数"，
 *                  删除时一路 -1，减到 0 才允许把这个节点真正 free 掉。
 *
 * 内存布局（64 位平台）：26 个指针占 208 字节，两个 int 占 8 字节，共 216 字节。
 * 第 1 幕会用 sizeof / offsetof 把这三个数字实测打印出来，不用猜。
 */
typedef struct TrieNode {
    struct TrieNode *child[26];
    int end_count;
    int pass_count;
} TrieNode;

/*
 * 造一个空节点：26 个指针全 NULL，两个计数器全 0。
 * 为什么要单独一个函数而不是就地 malloc？
 *   因为"清零"是正确性的一部分：malloc 回来的内存是垃圾值，
 *   child[] 里残留一个随机地址，插入时就会当成"这个孩子已经存在"钻进去 → 直接段错误。
 *   本函数用 calloc 一次搞定清零，也保证失败时返回 NULL 让调用方判空。
 */
TrieNode *trie_node_new(void);

/*
 * 插入一个串（可重复插入，重复只会让计数器变大，不会多出节点）。
 *
 * 为什么参数是 TrieNode **root 而不是 TrieNode *root？
 *   因为空树的根本身就是"要被创建出来"的那个指针 —— 它是调用者变量里的指针，
 *   只有拿到它的地址才能改到外面（00-c-foundation/pointer-basics 的第 2 课）。
 *   传 TrieNode *root 的话，函数里 malloc 了根，外面 root 还是 NULL：
 *   树建好了，但没人知道入口在哪 → 整棵树立刻泄漏。
 * 返回值：1 = 成功；0 = 输入非法被拒（NULL / 空串 / 非小写字母 / 超长）。
 */
int trie_insert(TrieNode **root, const char *word);

/*
 * 整串精确查：word 这个词在不在树里？返回 end_count（0 = 不存在，>0 = 存在且插了那么多次）。
 * 为什么不返回 bool？因为"插了几遍"是有用信息，而且 0 在这里天然就是"不存在"，
 * 不会和哈希表那种"值 0 和查不到混淆"的坑撞车（哈希表的值可以是任意 int，这里不是）。
 */
int trie_search(const TrieNode *root, const char *word);

/* 前缀查询：有没有任何串以 prefix 开头？返回 1 / 0。只看路径能不能走完。 */
int trie_starts_with(const TrieNode *root, const char *prefix);

/*
 * 前缀计数：以 prefix 开头的串有几个 = 走到 prefix 末端节点后直接读 pass_count。
 * 这是 Trie 最漂亮的一招：代价 O(L)，和子树大小无关 —— 子树里有多少个词都一样快。
 * 没有 pass_count 就得 DFS 整棵子树数 end_count，那是 O(子树节点数)。
 * 返回 0 表示没有这个前缀。
 */
int trie_count_prefix(const TrieNode *root, const char *prefix);

/*
 * 走一遍路径并数"走了几步"，用来把 O(L) 这件事跑成可见的数字。
 * 返回 1 = 路径走通（这个前缀存在），0 = 中途断了；steps_out 是走过的字符数。
 * steps_out 可以传 NULL（"我不关心步数"）—— 输出参数允许拒绝，这是仓库惯例。
 */
int trie_walk_counted(const TrieNode *root, const char *s, int *steps_out);

/*
 * 删除一个串（只删一遍）。返回 1 = 删掉了，0 = 本来就没有（或输入非法）。
 *
 * 为什么删除比插入难写？三件事必须同时做对：
 *   1) 沿途每个节点的 pass_count 都要 -1（包括终点自己）；
 *   2) 终点的 end_count -1；
 *   3) 沿途 pass_count 减到 0 且 end_count == 0 的节点必须【真的 free 掉】，
 *      否则内存白占着 —— 树不会自己缩，词表反复增删就变成无限膨胀。
 * 判据为什么是"pass==0 且 end==0"，不是"end==0"？
 *   因为删掉 "car" 以后，"car" 那个节点 end_count 变 0，但 "card" 还从它身上过，
 *   pass_count = 1 > 0，节点必须留着。只看 end_count 会把 card 也一起删没。
 * 实现用递归（后序思想：先处理孩子，再决定自己去留），见 trie.c 第 6 节。
 */
int trie_delete(TrieNode **root, const char *word);

/*
 * 自动补全：把所有以 prefix 开头的完整单词写进调用者给的 out 数组，返回找到几个。
 *
 * 做法 = 先走到 prefix 末端节点，然后以它为根 DFS，沿 child[] 往下走；
 * 一路把走过的字符【就地】写进一个定长路径缓冲区，回来时把长度退 1（回溯）。
 * 为什么必须递归：树的深度事先不知道，用循环就得自己造一个栈存"待处理的节点+深度"，
 *   等于把函数调用栈重写一遍，代码量翻倍还容易错。
 * 为什么缓冲区是"就地写死"而不是全局变量：全局状态会让这个函数【不可重入】
 *   （两次调用互相踩缓冲区）、也没法并发，而且 free 责任变成隐形的。
 *   本函数把缓冲区放在【自己的栈帧】里，指针一路当参数传下去，函数一返回自动消失。
 * out 是 char[][TRIE_WORD_MAX]：调用者提供 max_words 行，每行固定 32 字节，
 *   所以 out 的真实字节数 = max_words × TRIE_WORD_MAX，一次也不用 malloc。
 * ⚠ 调用者保证 max_words <= out 的行数，否则就是越界写（本节接口按仓库风格用
 *   "调用者传缓冲区 + 传容量"，和 fgets/snprintf 是同一套规矩）。
 */
int trie_autocomplete(const TrieNode *root, const char *prefix,
                      char out[][TRIE_WORD_MAX], int max_words);

/*
 * 从根开始 DFS，把所有单词按【字典序】写进 out，返回个数。
 * 这就是哈希表做不到的第二件事"有序遍历"：child[] 的下标天然就是字母顺序，
 * 从前往后扫 26 格，出来的顺序自动是字典序，一个比较都没做、一次排序都没跑。
 * （对比拉链法：桶顺序 = h(key) % m 的顺序，想有序必须显式排序。）
 */
int trie_dump_words(const TrieNode *root, char out[][TRIE_WORD_MAX], int max_words);

/* 节点总数（含根）。必须遍历整棵树 O(节点数) —— 用来算内存账单。 */
int trie_count_nodes(const TrieNode *root);

/* 有多少个【不同的】单词 = end_count > 0 的节点个数。同样是 O(节点数) 的全树遍历。 */
int trie_count_words(const TrieNode *root);

/*
 * 把整棵树按缩进打印出来：每行 = 一层，行首缩进 2×深度；
 * 节点名用单引号包住，end_count > 0 的节点在行首打一个 '*'；
 * 每行都带 pass= / end=，完整单词那一行还把从根走过的路径（也就是这个单词）打印出来。
 * 为什么值得专门写一个函数：不打印出来，"pass 是流量、end 是站点"就只是口号。
 * 它自己也是"递归 + 回溯路径缓冲区"的例子（和自动补全同一招，看 trie.c 第 8 节）。
 */
void trie_print_tree(const TrieNode *root);

/*
 * 空间账单：sizeof(TrieNode) × 节点数、child[] 的 26 个槽位到底用了几个、
 * 每个字符摊到多少字节。label 用来在一张图里对比多棵树。
 * 存在的意义：把"费内存"从形容词变成一个可以读数的量。
 */
void trie_print_stats(const TrieNode *root, const char *label);

/*
 * 递归释放整棵树。后序：先把 26 个孩子（连同各自的子树）全部 free 完，再 free 自己。
 * ⚠ 为什么必须后序、不能先 free 自己：见 trie.c 第 10 节的图解 —— 一句话是
 *   "free(node) 之后 node->child[] 这个数组就已经不属于你了，
 *    再去读它拿孙子地址，就是 use-after-free"。
 * 递归结束后 root 指针本身还在，但已经是悬空指针：调用方必须立刻置 NULL。
 */
void trie_free(TrieNode *node);

#endif /* TRIE_H */
