#ifndef CHAINING_H
#define CHAINING_H

/*
 * ===================================================================
 * 拉链法哈希表 hash-table-chaining —— 这一节的"菜单"
 * ===================================================================
 * 这个文件里【只有声明】。真正的代码和"这行为什么存在"在 chaining.c。
 *
 * -------------------------------------------------------------------
 * 一、哈希表到底在干什么？一句话：把"找东西"变成"找格子"。
 * -------------------------------------------------------------------
 * 前面几章你已经见过两种"存了再找"的极端：
 *   - 数组：知道**下标**就 O(1)，但下标是 0,1,2,3 这种连号整数，
 *     你要找"学号 2021305011 的同学"，数组开不下（要 20 亿个格子）。
 *   - 链表：什么值都能存，但找一次必须从头走到尾，O(n)。
 *
 * 哈希表的做法是**合谋**：先造一个函数，把"随便一个键"算成"一个连号下标"，
 * 然后就去数组里找 —— 于是两头的优点都有了：
 *
 *     key（任意整数/字符串）
 *        │
 *        ▼  哈希函数 h(key)：把键揉成一个很大的非负整数
 *      6126472581938472
 *        │
 *        ▼  取余 % capacity：把它压进"数组下标"的范围 0..capacity-1
 *        3
 *        │
 *        ▼  直接跳到 buckets[3]
 *   ┌────┬────┬────┬────┬ ... ┐
 *   │ 0  │ 1  │ 2  │ 3  │     │   ← 一次数组寻址，O(1)
 *   └────┴────┴────┴─▲──┴─────┘
 *                    │
 *              这里开始存东西
 *
 * **所以哈希表的两个核心部件，一个都不能少：**
 *   1. 哈希函数 h(key)：决定"同一个人是不是每次都进同一个格子"。
 *   2. 桶数组 buckets[]：提供 O(1) 的随机跳转。
 *
 * -------------------------------------------------------------------
 * 二、冲突（collision）是必然的，不是意外
 * -------------------------------------------------------------------
 * 键有无穷多种，格子只有 capacity 个。**鸽笼原理**决定了一定会有两个不同的键
 * 算出同一个下标 —— 这叫"冲突/碰撞"。处理冲突只有两大流派：
 *
 *   流派 A：拉链法（本章）—— 桶里不放"元素"，放"一条链表"。
 *           撞了就往那条链上挂一个节点。桶数组永远不满，链表长度决定性能。
 *
 *   ┌──────┐
 *   │  0   ├────► NULL                              ← 空桶：一个指针而已
 *   ├──────┤
 *   │  1   ├────►[key 9]──►[key 1]──►NULL           ← 撞在同一个桶，挂成一条链
 *   ├──────┤
 *   │  2   ├────► NULL
 *   ├──────┤
 *   │  3   ├────►[key 3]──►NULL                     ← 不撞就是一个节点，O(1)
 *   └──────┘
 *
 *   流派 B：开放寻址（下一节）—— 桶里直接放元素，撞了就在数组里往后找空位。
 *
 * 拉链法的好处：**实现简单、删除干净（就是删链表节点）、负载因子可以超过 1
 * 也不会坏**（链长一点而已）；代价：每个元素一次 malloc，指针跳转，缓存不友好。
 *
 * -------------------------------------------------------------------
 * 三、负载因子 load factor：整张表最重要的一根弦
 * -------------------------------------------------------------------
 *     load_factor = size / capacity   （装了多个元素 / 有几个桶）
 *
 * 它是"平均链长"的另一种写法（在键分布均匀的前提下）。
 * 链越长，"哈希表"就越像"链表"，O(1) 的招牌就越是假的。
 * 所以我们定一条规矩：**超过 0.75 就把桶数组翻倍，然后全部重新投桶（rehash）**。
 * 为什么是 0.75？这是工程上的经验值（Java HashMap 就是 0.75）：
 *   - 再低（比如 0.5）→ 桶数组浪费一半，扩容太频繁；
 *   - 再高（比如 0.9）→ 链变长，查找退化成 O(n)。
 * 本节会**把扩容前后每个元素落到哪个新桶全部打印出来** ——
 * rehash 不是"搬家一部分"，而是**全部重新投一次桶**，没有捷径。
 *
 * -------------------------------------------------------------------
 * 四、本节为什么写了两份表？（C 语言没有泛型）
 * -------------------------------------------------------------------
 * 仓库的规矩是：值一律 int，键允许 int 或 char *，**禁止 void * 和函数指针比较器**。
 * 于是 int 键和字符串键只能**各写一份**（下面两个 typedef）：
 *
 *   IntHT：键是 int，比较就是 ==，哈希就是原值本身（方便你手算验证每一步）。
 *   StrHT：键是 char *，比较必须 strcmp，哈希必须把字符串揉成整数（djb2）。
 *
 * 两份代码 90% 重复 —— 这不是写得烂，这就是 C 语言的代价。
 * 真实库里怎么绕开？三个办法你以后会见到：
 *   1) 宏模板（`#define` 生成代码，STB 库风格）；
 *   2) `void *` + 函数指针比较器（xtree / glib 风格）—— 本节明令禁止，
 *      因为 void * 会把类型检查全部丢掉，初学时 90% 的哈希表 bug 都出在这；
 *   3) C11 `_Generic`（几乎没人用在哈希表上）。
 * 先老老实实抄写两遍，你就明白"泛型"到底帮你省掉了什么、又藏起了什么。
 *
 * -------------------------------------------------------------------
 * 五、本节最大的一个坑：C 的 % 会返回负数（先记住，函数在下面）
 * -------------------------------------------------------------------
 * 数学里的"取模"结果一定在 0..m-1；但 **C 语言的 % 是"截断除法"的余数，
 * 它的符号跟着左边的操作数（被除数）走**。
 * 于是 `h(key) % capacity` 在 h(key) 是负数时，返回一个**负下标**，
 * 拿去访问 buckets[负数] 就是越界读写 —— 编译器不会拦你，ASan 会。
 *
 *   代码里 `ht_mod_pitfall()` 专门把这件事跑成真实数字打印出来（含 INT_MIN），
 *   `ht_index()` 是唯一被允许的写法。这一条请看 README 的图解。
 */

/* ---------- 0. 负数取余的坑：独立函数，main.c 第 1 幕直接调用 ---------- */

/* 把"负数取余"这个坑跑成真实输出打印出来（含 INT_MIN 这种极端值） */
void ht_mod_pitfall(void);

/*
 * 数学意义上的取模：结果永远落在 [0, m)。
 * 它是整节代码里唯一允许做"下标换算"的地方。
 * 单独拎出来是因为：**只要写 `key % cap` 就直接认为它安全，你就已经中招了。**
 */
int ht_mod(long value, int m);

/*
 * 无符号取模：结果永远在 [0, m)，而且**全程没有符号问题**。
 * 字符串表（djb2 用 unsigned long）更该走这条路，因为：
 *   把 unsigned long 塞回 long / int 是"收窄转换"，值太大时 C 标准说这是
 *   implementation-defined（gcc 按补码回绕，换个编译器可能给你另一个数）。
 *   与其依赖回绕规则，不如从头到尾都用无符号，最后 % 一下 —— 定义良好、必非负。
 */
unsigned long ht_mod_u(unsigned long value, unsigned long m);

/* ---------- 1. int 键：拉链法哈希表 ---------- */

/*
 * 桶里挂的链表节点。就地重写的极简版（第 02 章单链表的复用）：
 *   key   —— 用来判断"这一格是不是我要找的那个键"
 *   value —— 真正要存的东西（本节一律 int，仓库规矩）
 *   next  —— 同桶的下一个键；NULL 表示这条链到底了
 * ⚠ 为什么 key 也要存一份？因为链表上撞了桶，找到节点后**必须再核对一次 key**
 *   （哈希相等 ≠ 键相等，这就是"冲突"），不存 key 就无法确认命中。
 */
typedef struct HTNode {
    int key;
    int value;
    struct HTNode *next;
} HTNode;

/*
 * 整张表：
 *   buckets  —— 指针数组：buckets[i] 是第 i 条链的**头节点地址**（和邻接表同构！）
 *   capacity —— 桶数（数组长度），只在扩容时变
 *   size     —— 当前存了多少个键（不是桶数，两者别混）
 *   probes   —— 计数器：累计"走过的链表节点数"。
 *               为什么要它？因为用时间衡量 O(n) 会有噪声（CPU 频率、缓存都在抖），
 *               **数比较次数才是"退化成本"的真实数字**，可复现、可打印。
 *               代价：get/contains 不能再声明成 const（要写这个计数器）。
 */
typedef struct {
    HTNode **buckets;
    int capacity;
    int size;
    long probes;
} IntHT;

IntHT *ht_create(int capacity);            /* 建表：capacity 个桶，全 NULL；失败返回 NULL */
void   ht_free(IntHT *t);                  /* 收摊：逐桶逐节点 free，再 free 数组、再 free 表 */

int  ht_put(IntHT *t, int key, int value); /* 有则改值，无则插入；可能触发 rehash。返回 1 成功 */
int  ht_get(IntHT *t, int key, int *value_out); /* 命中返回 1 并写 value_out；否则返回 0 */
int  ht_contains(IntHT *t, int key);       /* 只问有没有，不取值 */
int  ht_delete(IntHT *t, int key);         /* 删掉一个键（哨兵写法）；返回 1 删掉了、0 本来就没有 */
int  ht_len(const IntHT *t);               /* 元素个数（顺便演示"接口后面藏什么"） */

double ht_load_factor(const IntHT *t);     /* size / capacity，本节的体温计 */

/* ---------- 2. 看：把抽象的"桶 + 链"打到屏幕上 ---------- */
void ht_print(const IntHT *t);             /* 逐桶打印链表：1 -> 9 -> NULL */
void ht_stats(const IntHT *t);             /* 空桶数 / 最长链 / 平均链长 / 探针数 */
void ht_rehash_plan(const IntHT *t, int new_capacity); /* 预测：扩容后每个键搬到哪个新桶 */

/* ---------- 3. 实测"退化成链表"要用的小工具 ---------- */
/*
 * 往表里灌 n 个键：base, base+step, base+2*step, ...
 * step=1  → 键均匀分布，链极短（健康哈希表）
 * step 取 2 的大幂（比如 4096）→ 无论桶数怎么翻倍，全部挤进同一个桶（病人）
 * 返回成功插入的个数。
 */
int ht_fill_arithmetic(IntHT *t, int n, int base, int step);
/* 逐个 get 一遍 n 个键，返回这一轮总共走了多少个链表节点（清零计数器后统计） */
long ht_probe_after_n_gets(IntHT *t, int n, int base, int step);

/* ---------- 4. 字符串键版本：djb2 哈希 + strcmp 比对 ---------- */

/*
 * 字符串键节点：和 HTNode 只有一个字段的差别 —— key 变成 char *。
 * ⚠ 这个指针**指向表自己 malloc 的副本**，不指向调用者的字符串。
 *   为什么必须复制？因为调用者的字符串可能是栈上的数组、函数返回就没了，
 *   表里存的指针会立刻变成悬空指针（第 00 章讲过的老bug）。
 */
typedef struct StrNode {
    char *key;
    int value;
    struct StrNode *next;
} StrNode;

typedef struct {
    StrNode **buckets;
    int capacity;
    int size;
    long probes;
} StrHT;

/*
 * djb2：把字符串揉成一个整数的经典一行流（Daniel J. Bernstein 发明）。
 *   h = 5381;  对每个字符 c：  h = h * 33 + c
 * 为什么是 33？ h*33 = (h<<5) + h，移位加，快；而且实测散列质量很好。
 * （Java 的 String.hashCode 用的是 h*31 + c，另一个常见系数，思路完全一样。）
 * 用 unsigned long：乘加必然溢出，**无符号溢出是"回绕"，C 标准里定义良好**；
 * 有符号溢出则是未定义行为 —— 哈希函数一定要用无符号算。
 */
unsigned long ht_hash_string(const char *s);

StrHT *sh_create(int capacity);
void   sh_free(StrHT *t);
int    sh_put(StrHT *t, const char *key, int value);      /* 键会被复制一份存进表 */
int    sh_get(StrHT *t, const char *key, int *value_out);
int    sh_contains(StrHT *t, const char *key);
int    sh_delete(StrHT *t, const char *key);
int    sh_len(const StrHT *t);
double sh_load_factor(const StrHT *t);
void   sh_print(const StrHT *t);

/*
 * 词频统计：把一段英文按字母切开（标点/数字/下划线都当分隔符），
 * 每遇到一个单词就让它的计数 +1。返回切出来的单词总数。
 * 这就是哈希表最常见的真实用途：键是任意长度的字符串，值是 int 计数器。
 */
int sh_count_words(StrHT *t, const char *text);

/*
 * 把表里的所有词按"次数降序、同次数按字典序升序"排序，打印前 max 名。
 * 排序用的是就地写的插入排序，比较规则【写死在函数里】（本节禁用函数指针比较器）。
 * 为什么要排序：哈希表的遍历顺序 = 桶顺序 = 哈希值顺序，跟词频和字典序都无关，
 * 想看出榜单就必须显式排一次。
 */
void   sh_print_top(const StrHT *t, int max);

#endif /* CHAINING_H */
