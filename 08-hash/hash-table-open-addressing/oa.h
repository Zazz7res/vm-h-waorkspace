#ifndef OA_H
#define OA_H

/*
 * ===================================================================
 * 开放寻址 + 线性探测 hash-table-open-addressing —— 这一节的"菜单"
 * ===================================================================
 * 这个文件里【只有声明】。真正的代码和"这行为什么存在"在 oa.c。
 *
 * -------------------------------------------------------------------
 * 一、和上一节（拉链法）的唯一区别：元素直接躺在桶数组里
 * -------------------------------------------------------------------
 * 拉链法是"数组 + 一堆链表"：撞了就在格子后面挂链，节点各在各的堆地址上。
 * 开放寻址是"就一个数组"：**所有元素都住在 slots[] 里**，撞了就在数组里往后挪一格。
 *
 *   拉链法（capacity = 8，存 12、20、28，三个都算到桶 4）
 *   ┌────┬────┬────┬────┬────┬────┬────┬────┐
 *   │    │    │    │    │ ▲  │    │    │    │
 *   └────┴────┴────┴────┴─┼──┴────┴────┴────┘
 *                        └─►[28]─►[20]─►[12]─►NULL     ← 3 次 malloc，3 个散落地址
 *
 *   开放寻址（capacity = 8，同样三个键）
 *   ┌────┬────┬────┬────┬────────┬────────┬────────┬────┐
 *   │    │    │    │    │ key 12 │ key 20 │ key 28 │    │  ← 全在数组里，一块连续内存
 *   └────┴────┴────┴────┴────────┴────────┴────────┴────┘
 *      下标 0  1    2    3    4 ▲h     5 ◄挤一格   6 ◄挤两格   7
 *
 * 一句话：**拉链法把冲突"垂直"挂成链，开放寻址把冲突"水平"排进数组。**
 *
 * -------------------------------------------------------------------
 * 二、于是产生两个必须解决的问题
 * -------------------------------------------------------------------
 * 问题 A：怎么知道"这里没人"？
 *   数组不像链表有 NULL 结尾，必须给每一格配一个**状态标记**当哨兵：
 *       SLOT_EMPTY = 0   这格从来没人住过（或者已经被腾空）
 *       SLOT_USED  = 1   这格正住着一个键值对
 *       SLOT_TOMB  = 2   这格住过、被删了 —— 这就是"墓碑"
 *   （另一种写法是用一个魔法 key 值当空标记，比如 key == INT_MIN。
 *     但那样 INT_MIN 就不能当合法键用了，而且删格子的坑一模一样。
 *     本节用状态数组，因为它能把"删除"这件事讲得更清楚。）
 *
 * 问题 B：删掉一个元素时，那一格该写什么？—— 本节的主角，见下面第三节。
 *
 * -------------------------------------------------------------------
 * 三、为什么删除绝对不能"直接清零"（本节的灵魂）
 * -------------------------------------------------------------------
 * 查找的规则是：**从 home 下标出发往后走，遇到 USED 且 key 相等 = 命中；
 *                遇到 EMPTY = 当场判定"不存在"；遇到 TOMB = 不停，继续走。**
 * 也就是说 EMPTY 是查找的"停止标志"。
 *
 * 那么把删掉的格子写成 EMPTY，就等于在探测路径上挖了一个坑：
 *
 *   插入 12（12%8=4 → 落 4）、插入 20（20%8=4 撞 → 落 5）
 *
 *   删掉 12 之后，如果 slots[4] 直接清零（=EMPTY）：
 *   ┌────┬────┬────┬────┬─────────┬────────┬────┐
 *   │ .. │ .. │ .. │ .. │ EMPTY ✗ │ key 20 │ .. │
 *   └────┴────┴────┴────┴─────────┴────────┴────┘
 *     get(20)：从 4 开始 → 4 是 EMPTY → **规则说"不存在"** → 于是停下了
 *     可是 20 明明就住在 5！数据还在那儿，程序却说没有。
 *     这就叫**探测链被剪断（probe chain broken）**。
 *
 *   正确做法：slots[4] 写成 TOMB（墓碑）——
 *     "这里曾经有东西，别在这里停下"。
 *     get(20)：4 是 TOMB → 继续 → 5 是 USED 且 key==20 → 命中 ✅
 *
 * 墓碑的代价（也是它必须被管理的原因）：
 *   - 它不占 size，但**它挡路**：查找要越过它，链越拖越长；
 *   - 所以**装载率的分子必须是"USED + 墓碑"**，而不是 size；
 *   - 好消息：墓碑可以在重新插入时被**回收**（占住它的格子还能用）；
 *   - 坏消息：只回收不彻底 —— 反复"插入又删除"会让墓碑堆满整张表，
 *     这时必须做一次 rehash 把墓碑蒸发掉（本节会实测到这一幕）。
 *
 * -------------------------------------------------------------------
 * 四、缓存友好：这一节相对拉链法的真正优势
 * -------------------------------------------------------------------
 * 本节一格是 `struct { int key; int value; int state; }` = **12 字节**（三个 int，无padding）。
 * 一条 64 字节的缓存线能装 64/12 = 5 格。线性探测是"往后挪一格"，
 * 于是连续几次探测往往落在**同一条缓存线**里，CPU 预取天然命中。
 * 拉链法每走一步是一次指针跳转，跳向一个当初 malloc 在别处的地址 ——
 * 每一跳都可能缓存未命中。第 7 幕把这些换算成真实数字打印出来对比。
 *
 * 代价也要说清楚：开放寻址的连续探测会形成"一次读一整块却发现都不是"的
 * 聚集（primary clustering），装载率一高步数暴涨，所以本节的阈值定得比
 * 拉链法保守得多：**0.5**（拉链法用 0.75）。
 *
 * -------------------------------------------------------------------
 * 五、接口一览（值一律 int，键是 int；本节不写字符串版）
 * -------------------------------------------------------------------
 * 和上一节同理，因为禁用 void * 和函数指针比较器，字符串版只能另写一份；
 * 上一节已经写过一份字符串表了，本节就专注把"线性探测 + 墓碑"这一件事讲透。
 * 想做字符串版：把 key 换成 char *、== 换成 strcmp、再加一层 free(key) 即可 ——
 * 但**线性探测里"复制键"的搬家成本比拉链法高**（搬家就是 memcpy 指针，很便宜，
 * 这点倒差不多），真正麻烦的是删除时要把键的内存也还掉。留给练习。
 */

/* 一格的状态。三个值必须互不相等，EMPTY 必须是 0（calloc 之后天然全 EMPTY） */
enum {
    SLOT_EMPTY = 0,   /* 空：查找走到这里就【停】，判定"键不存在" */
    SLOT_USED  = 1,   /* 住着键值对 */
    SLOT_TOMB  = 2    /* 墓碑：住过、已删。查找走到这里【不停】，插入时可以被回收 */
};

/* 删除策略。本仓库的规矩：默认必须是正确的 OA_DEL_TOMBSTONE，
 * 错误演示 OA_DEL_ZERO 只在命令行 --bug 时才打开。 */
enum {
    OA_DEL_TOMBSTONE = 0,  /* ✅ 正确：留墓碑 */
    OA_DEL_ZERO      = 1   /* ❌ 错误演示：直接清成 EMPTY，会剪断探测链 */
};

/*
 * 一格。三个 int 而不是"两个 int + 一个 char"，就是为了把 sizeof 凑成 12：
 * 少一个字节都能让"一条缓存线装几格"这个数字变，注释里的算术必须和实测一致。
 */
typedef struct {
    int key;
    int value;
    int state;    /* SLOT_EMPTY / SLOT_USED / SLOT_TOMB */
} Slot;

/*
 * 整张表。四个计数字段是本节的重点，务必分清：
 *   capacity —— 格子总数（数组长度）
 *   size     —— 真正住着元素的格子数（USED）
 *   tombs    —— 墓碑数（TOMB）
 *   used     —— size + tombs，**装载率的分子**：挡路的格子有多少
 * probes     —— 计数器：累计探测过多少格。用步数而不是掐表，数字可复现。
 * del_mode   —— 删除策略（默认墓碑；--bug 时切成清零，专门用来演示断链）
 */
typedef struct {
    Slot *slots;
    int capacity;
    int size;
    int tombs;
    int used;
    long probes;
    int del_mode;
} OATable;

OATable *oa_create(int capacity);            /* calloc 一个 capacity 格的数组，全 EMPTY */
void     oa_free(OATable *t);                /* 一次 free 数组 + 一次 free 结构体（就两级，比拉链法好收摊） */

int  oa_put(OATable *t, int key, int value); /* 有则改值，无则插入；可能触发扩容/清理 */
int  oa_get(OATable *t, int key, int *value_out);
int  oa_contains(OATable *t, int key);
int  oa_delete(OATable *t, int key);         /* 按 del_mode 决定留墓碑还是清零 */
int  oa_len(const OATable *t);               /* == size，不含墓碑 */
int  oa_tomb_count(const OATable *t);
double oa_load_factor(const OATable *t);     /* used / capacity（注意分子含墓碑！） */
double oa_real_load(const OATable *t);       /* size / capacity（真正的数据密度，用来做对比） */

void oa_set_delete_mode(OATable *t, int mode);
const char *oa_mode_name(int mode);          /* 打印用 */

/* ---------- 看：把"格子 + 探测路径"打到屏幕上 ---------- */
void oa_print(const OATable *t);             /* 横向画数组，每格标 U/T/· 和 key */
void oa_print_probe_path(const OATable *t, int key); /* 打印 "下标: 4 -> 5（命中/未命中）" */
void oa_stats(const OATable *t);             /* USED/墓碑/空格、两个装载率、平均探测步数 */

/* ---------- 扩容与重新放置 ---------- */
/*
 * 搬家到 new_capacity。两个用途：
 *   1) 桶数翻倍（真扩容）；
 *   2) **同容量重排**：只把墓碑蒸发掉、元素重放一遍。
 * 后者是开放寻址特有的招式 —— 拉链法没有这个需求（它没有"挡路"这回事）。
 * 返回搬走的元素个数。
 */
int  oa_rehash(OATable *t, int new_capacity);
/* 打印"每个元素的新家在哪"的预测：注意它只是 home 下标，真实落点取决于数组占用 */
void oa_rehash_plan(const OATable *t, int new_capacity);

/*
 * 把查找 key 时经过的下标序列抄进 path_out，返回步数；found_out 写 1/0。
 * 这是本节最重要的观测工具：探测序列是"开放寻址"这四个字的实体。
 * ⚠ 为什么把序列抄出来而不是在函数里直接打印？
 *   因为调用方有时想换种排版（比如同一行打印两个键的对比）。
 *   数据与呈现分开，这个小决定让 main.c 干净很多。
 */
int  oa_probe_path(const OATable *t, int key, int *path_out, int path_max, int *found_out);

/* ---------- 实测退化的灌数据工具 ---------- */
int  oa_fill_arithmetic(OATable *t, int n, int base, int step);
long oa_probe_after_n_gets(OATable *t, int n, int base, int step);

#endif /* OA_H */
