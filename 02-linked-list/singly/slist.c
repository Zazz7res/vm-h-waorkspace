#include <stdio.h>
#include <stdlib.h>
#include "slist.h"

/*
 * ===================================================================
 * 0. slist_make_node：造一个节点
 * ===================================================================
 * 链表里每个节点都是"单独租的一间小屋"，散落在堆上各处，靠 next 纸条串成一串。
 * 它们【不需要挨着】，这正是链表和数组的根本区别：
 *
 *   数组：  ┌───┬───┬───┬───┐   一整块连续内存，下标 = 起点 + i×4 字节，一步到位
 *   数组    │ 1 │ 2 │ 3 │ 4 │
 *           └───┴───┴───┴───┘
 *
 *   链表：  ┌───┬───┐        ┌───┬───┐            ┌───┬───┐
 *   堆上    │ 1 │ ●─┼───┐    │ 3 │ ●─┼──┐         │ 2 │ ∅ │
 *           └───┴───┘   │    └───┴───┘  │         └───┴───┘
 *                       └───────────────┼───────────────┘
 *                     （地址完全可能一个比一个大、一个比一个小，乱序摆放，靠指针连线）
 *
 * 好处：插一个节点只要 malloc 一小块 + 改两根线，不用搬家。
 * 代价：想拿第 100 个元素，必须从第 1 个开始顺着数 100 次。
 *
 * 为什么单独抽一个函数出来？
 *   因为"申请完忘了判 NULL"这种错，写五遍就会漏五遍。集中一处，只判一次。
 */
Node *slist_make_node(int val)
{
    Node *n = malloc(sizeof(Node));   /* 一个节点 = 一个 int + 一个指针，大小交给 sizeof 算，别手写 12/16 */
    if (n == NULL) {
        return NULL;                  /* 堆不够时 malloc 返回 NULL；调用方看到 NULL 就知道失败了 */
    }
    n->val  = val;
    n->next = NULL;                   /* ⚠ 一定先置空。忘置空 = next 里是垃圾值，一往下走就段错误 */
    return n;
}

/*
 * ===================================================================
 * 1. slist_push_front：头插，O(1)
 * ===================================================================
 * 干的事就三下：新节点的 next 指向老的头，然后把 head 换成新节点。
 *
 *   前：  head ──► [1|●] ──► [2|●] ──► NULL
 *
 *   第①步  n->next = *head：
 *         [9|●] ──┐
 *                 ↓
 *          head ──► [1|●] ──► [2|●] ──► NULL
 *
 *   第②步  *head = n：head 这根线挪到新节点上
 *          head ──► [9|●] ──► [1|●] ──► [2|●] ──► NULL
 *
 * 为什么第①步必须在第②步之前？
 *   因为一旦先做 *head = n，老链表的入口地址就被覆盖丢了，[1|●] 那一串全体失联，
 *   既拿不到也释放不了 —— 这是链表最经典的"断链事故"。
 *   跟 pointer-basics 里 swap 必须先存 temp 是同一个道理：
 *   【写覆盖之前，先把要保的值抄一份】。
 *
 * 为什么参数是 Node **head：
 *   第②步要改的是外面的 head 变量本身（它的值要变成新节点地址）。
 *   传 Node *head 只能改到拷贝，改不到外面 —— 见下面 slist_push_front_bad 的反面教材。
 */
int slist_push_front(Node **head, int val)
{
    Node *n = slist_make_node(val);
    if (n == NULL) {
        return 0;                       /* 造节点失败，明确告诉调用者"没插上" */
    }

    n->next = *head;                    /* ① 新节点先牵住老链表（顺序绝不能反！） */
    *head = n;                          /* ② 再把头指针挪到新节点上（*head = 往外面那个变量里写） */
    return 1;
}

/*
 * ===================================================================
 * 1b. slist_push_front_bad：故意写错的版本（反面教材）
 * ===================================================================
 * 唯一区别：参数写成 Node *head，只有一层指针。
 * 函数里head 被改成新节点，看起来一切正常，打印出来也是 "9 -> 1 -> 2 -> NULL"；
 * 但那只是【函数内部这份拷贝】的变化，调用者的 head 纹丝不动，
 * 于是外面看到还是 "1 -> 2 -> NULL"，新节点变成谁也找不到的孤儿 —— 内存泄漏。
 *
 *   main:   head ──┐
 *                  │ 传参＝拷贝地址数值
 *   函数内: head' ─┘   →  head' = n;   改的是 head'，跟 main 的 head 无关
 *
 * 这就是 swap_by_value 的链表版。跑 main.c 第 1 幕能亲眼看到"里面变了外面没变"。
 *
 * ⚠ 这里最后手动 free 那个孤儿节点，否则 ASan 会报泄漏 ——
 *   也就是说这个函数不只是"没用"，它还在真实地漏内存。正式代码绝不能用这种写法。
 */
void slist_push_front_bad(Node *head, int val)
{
    Node *n = slist_make_node(val);
    if (n == NULL) {
        return;
    }

    n->next = head;      /* 这行没问题：新节点确实牵住了老链表 */
    head = n;            /* ❌ 错在这一行：改的是形参 head 这份拷贝 */

    printf("      [函数内部] 我插入后链表看起来是: ");
    slist_print(head);   /* 这里打印出来确实包含新节点 —— 骗过了写代码的人 */

    /* 收尾擦屁股：把刚造出来的孤儿摘下来还掉，不然它永远没人能 free 它 */
    Node *orphan = head;
    head = head->next;   /* 先把链还原（虽然外面根本没进来看这条链） */
    free(orphan);
    orphan = NULL;
}

/*
 * ===================================================================
 * 2. slist_push_back：尾插，O(n)
 * ===================================================================
 * 链表只有"入口"没有"出口"，想插到最后必须先走到最后一个节点：
 *
 *   head ──► [1|●] ──► [2|●] ──► NULL
 *              cur       cur
 *        while (cur->next != NULL) cur = cur->next;   ← 走到 next == NULL 的那个节点就是尾巴
 *
 *   然后两步：cur->next = n; （尾巴牵住新节点，新节点 next 已经是 NULL，刚好当新尾巴）
 *
 * 边界情况：
 *   · 空表：*head == NULL，循环一次都不走，直接 *head = n。所以要么特判，
 *     要么像下面这样先判空 —— 不然 cur->next 就是解引用空指针，当场段错误。
 *   · 只有一个节点：cur 就是那个节点，正常走。
 *
 * 工程上的建议：如果程序里"尾插"很频繁，就多存一个 tail 指针（下一节双向链表、
 * 以及循环单链表的"只存 tail"写法都是这个思路），把 O(n) 降回 O(1)。
 */
int slist_push_back(Node **head, int val)
{
    Node *n = slist_make_node(val);
    if (n == NULL) {
        return 0;
    }

    if (*head == NULL) {          /* 空表：新节点就是头 */
        *head = n;
        return 1;
    }

    Node *cur = *head;
    while (cur->next != NULL) {   /* 走到最后一个节点（不是走到 NULL！条件写在到达时停） */
        cur = cur->next;
    }
    cur->next = n;                /* 尾巴牵上；n->next 造节点时已是 NULL，天然成为新尾巴 */
    return 1;
}

/*
 * ===================================================================
 * 3. slist_insert_at：插到第 k 个位置（下标从 0 开始）
 * ===================================================================
 * "插到第 k 个位置"= 插完之后，新节点的下标是 k。
 * 所以要把新节点挂到【第 k-1 个节点】后面 —— 链表只能往后牵线，不能往前。
 *
 *   k=0        : 插在最前面 = 头插（第 k-1 个不存在，要特判）
 *   k=1        : prev 走到第 0 个节点，插在它后面
 *   k=length   : prev 走到最后一个节点，插在它后面 = 尾插
 *   k>length   : 非法，越界（不特判就会在 cur==NULL 时解引用 → 崩）
 *   k<0        : 非法
 *
 * 图解 k=1，链表 [1] [2] [3]，插 99：
 *        prev 停在下标 0 的节点
 *         head ──► [1|●]      [2|●] ──► [3|●] ──► NULL
 *                    │            ▲
 *                    │  ①  n->next = prev->next
 *                  ┌─┘          │
 *                  │            │
 *                [99|●] ────────┘   ②  prev->next = n
 *
 * 顺序仍然是"先接右边，再接左边"：先 n->next = prev->next，再 prev->next = n。
 * 反过来的话 prev->next 里的老地址就被冲掉了，后面那半条链直接断线。
 */
int slist_insert_at(Node **head, int k, int val)
{
    if (k < 0) {
        printf("      [错误] 插入位置 k=%d 不能为负\n", k);
        return 0;
    }

    if (k == 0) {                     /* 插在最前面，交给头插（不用遍历，O(1)） */
        return slist_push_front(head, val);
    }

    /* 先走 k-1 步，让 prev 停在下标 k-1 的节点上；走不到说明 k 超范围 */
    Node *prev = *head;
    for (int step = 0; step < k - 1; step++) {
        if (prev == NULL) {           /* 已经走出链表外面了，说明 k 太大 */
            int len = slist_length(*head);
            printf("      [错误] k=%d 越界：当前长度 %d，可插范围是 0 ~ %d\n", k, len, len);
            return 0;
        }
        prev = prev->next;
    }
    if (prev == NULL) {               /* 上面循环走完后 prev 也可能是 NULL（k 正好比长度大 1） */
        int len = slist_length(*head);
        printf("      [错误] k=%d 越界：当前长度 %d，可插范围是 0 ~ %d\n", k, len, len);
        return 0;
    }

    Node *n = slist_make_node(val);
    if (n == NULL) {
        return 0;
    }

    n->next = prev->next;             /* ① 新节点先接住后半条链 */
    prev->next = n;                   /* ② 前驱再改口接新节点 */
    return 1;
}

/*
 * ===================================================================
 * 4. slist_find / slist_get_at：两种找法
 * ===================================================================
 * slist_find    ：按值找 —— 只能从头一个个比，O(n)。返回【节点地址】，
 *                 这样调用者能拿到地址接着用（比如直接删它）。
 * slist_get_at  ：按下标找 —— 数组是 O(1)，链表是 O(n)，
 *                 这一条最能体现链表"随机访问"的代价。
 *
 * 约定：val_out 是"输出参数"（pointer-basics 里的 _out 后缀约定），
 *       传 NULL 表示"我只想知道存不存在，不想要值"。
 */
Node *slist_find(Node *head, int val)
{
    Node *cur = head;
    while (cur != NULL) {                 /* ⚠ 先判 cur 不是 NULL，才能碰 cur->val */
        if (cur->val == val) {
            return cur;                   /* 找到第一个就返回（重复值只返回最靠前的） */
        }
        cur = cur->next;
    }
    return NULL;                          /* 走到尽头也没找到，用 NULL 表示"没有" */
}

int slist_get_at(Node *head, int k, int *val_out)
{
    if (k < 0) {
        return 0;
    }
    Node *cur = head;
    for (int i = 0; i < k && cur != NULL; i++) {
        cur = cur->next;                  /* 走 k 步 */
    }
    if (cur == NULL) {
        return 0;                         /* 下标越界 */
    }
    if (val_out != NULL) {
        *val_out = cur->val;              /* 往调用者给的格子里写结果 */
    }
    return 1;
}

/*
 * ===================================================================
 * 5. slist_remove_val：按值删除 —— 本节最大的考点
 * ===================================================================
 * ---------------------------------------------------------------------
 * 先看"难点到底在哪"：删头节点 和 删中间节点，代码是两套！
 * ---------------------------------------------------------------------
 * 单链表要摘掉一个节点，必须改【它前一个节点】的 next。
 * 可是节点自己不知道自己的前驱是谁（next 是单向的，没有 prev）。
 * 于是只能从 head 出发，用 prev/cur 两个指针一起走，走到 cur 命中为止。
 *
 * 问题来了：删头节点时，根本没有"前驱节点"，该改的不是谁的 next，而是 head 这个变量本身！
 *
 *   删中间：  prev ──► [A|●] ──► [B|●] ──► [C|●]        只要 prev->next = cur->next  ✔
 *                        prev       cur    （要删的）
 *
 *   删头：    head ──► [B|●] ──► [C|●]                  得写 head = head->next     ✘ 另一种代码
 *                    head
 *
 * 所以"土办法"必须写成：
 *     if (要删的是头) { 特判改 head }
 *     else            { 循环找前驱，改前驱的 next }
 * 两套分支、两处指针修改，写漏一个就是 bug（下面 slist_remove_val_two_cases 就是这个土办法，
 * 我们保留它专门用来对比）。
 *
 * ---------------------------------------------------------------------
 * 正确姿势：先造一个"假头"哨兵 dummy，把两种情况合成一种
 * ---------------------------------------------------------------------
 * dummy 是一个【不存有效数据、临时挂在链条最前面】的节点，它的 next 指向真正的头。
 * 这么一来，原来的头节点就有了前驱（就是 dummy），
 * 于是"任何一个节点"都有前驱 —— 特判彻底消失，只剩一套代码。
 *
 *   插入 dummy 之前：  head ──► [1|●] ──► [2|●] ──► [3|●] ──► NULL
 *
 *   插入 dummy 之后：  head ──► [dummy|●] ──► [1|●] ──► [2|●] ──► [3|●] ──► NULL
 *                              （栈上的临时节点，不算进链表长度）
 *
 *   要删 1：prev=dummy, cur=[1]  →  prev->next = cur->next   ← 和删 2、删 3 一模一样的这一行
 *
 *   最后别忘了把 dummy 的 next（也就是可能被改过的真正头节点）写回 *head：
 *   head ──► [2|●] ──► [3|●] ──► NULL，dummy 随函数返回自动消失（它是栈变量，没 malloc，不用 free）
 *
 * 这种技巧在链表里到处都是：带哨兵的链表、双链表的空表统一处理、
 * 下一节 circular-doubly 里那个"常驻哨兵"更是把这套写法用到底。
 *
 * ---------------------------------------------------------------------
 * 边界情况清单（本函数全部覆盖）
 * ---------------------------------------------------------------------
 *   · 空表（*head == NULL）      → dummy.next = NULL，while 条件第一次就不成立 → 返回 0
 *   · 只有一个节点，且正好要删它  → prev=dummy 命中，prev->next=NULL，*head 被写回 NULL ✔
 *   · 删头（val == (*head)->val） → 走通用分支，不用特判 ✔
 *   · 值不存在                    → cur 走到 NULL，返回 0，链表保持不变 ✔
 *   · 有重复值                    → 只删最靠前的一个
 *   · head 本身是 NULL 指针（比如别人传了个 NULL 进来） → 挡在门口，防止 *head 崩
 */
int slist_remove_val(Node **head, int val)
{
    if (head == NULL) {
        return 0;                       /* 连"头指针在哪"都没告诉我，没法干活 */
    }

    Node dummy;                         /* ★ 哨兵：栈上一个普通结构体变量，不 malloc、不 free */
    dummy.val = 0;                      /*   这个字段没有任何意义，纯粹是结构体长这样得有 */
    dummy.next = *head;                 /*   它牵住真正的头，于是"头节点也有前驱"了 */

    Node *prev = &dummy;                /* prev 永远站在 cur 前面一个，负责改口 */
    Node *cur = dummy.next;             /* cur 是被考察的节点 */

    while (cur != NULL && cur->val != val) {   /* 两个条件的顺序不能换：
                                                * 先确认 cur 合法，再读 cur->val，
                                                * 否则会解引用空指针 */
        prev = cur;
        cur = cur->next;
    }

    if (cur == NULL) {
        return 0;                       /* 找遍了没有。链表一根线都没动过，安全返回 */
    }

    prev->next = cur->next;             /* ★ 唯一的一处"摘节点"：让前驱跨过 cur 直接牵后面 */
    free(cur);                          /* 摘下来的节点必须还，不还就是泄漏 */
    cur = NULL;                         /* 顺手置空，防止后面误用这个野指针 */

    *head = dummy.next;                 /* ★ 关键收尾：如果刚删的正好是头，dummy.next 已经是新的头，
                                         *   在这里统一写回外面的 head，所以外面永远不用特判 */
    return 1;
}

/*
 * ===================================================================
 * 5b. slist_remove_val_two_cases：同一件事的土办法（保留用来对比）
 * ===================================================================
 * 没有哨兵，就得老老实实分两种情况：
 *   情况一：要删的就是头节点 → 没有前驱，只能改 head 本身
 *   情况二：要删的是后面的   → 循环找前驱，改前驱的 next
 * 功能上和 slist_remove_val 完全一样（main.c 里会交替调用，验证两者行为一致），
 * 但代码长、分支多、容易写错。读一读就知道哨兵香在哪。
 */
int slist_remove_val_two_cases(Node **head, int val)
{
    if (head == NULL || *head == NULL) {
        return 0;                       /* 空表，直接失败 */
    }

    /* ------- 情况一：删头节点。没有前驱，改的是 head 这个变量 ------- */
    if ((*head)->val == val) {          /* ⚠ 要先判 *head 非空，才能读 ->val */
        Node *old_head = *head;
        *head = old_head->next;         /* 把头指针往后挪一格 */
        free(old_head);
        return 1;
    }

    /* ------- 情况二：删中间/尾部。prev 从头开始追，cur 追着一个节点 ------- */
    Node *prev = *head;
    Node *cur = (*head)->next;
    while (cur != NULL && cur->val != val) {
        prev = cur;
        cur = cur->next;
    }
    if (cur == NULL) {
        return 0;
    }
    prev->next = cur->next;
    free(cur);
    return 1;
}

/*
 * ===================================================================
 * 6. slist_length：数个数，O(n)
 * ===================================================================
 * 注意：这个信息【链表自己不知道】，每次问都要从头数一遍。
 * 想 O(1) 知道长度，就得自己维护一个 size 计数器（双向链表那节就这么干）。
 * 数的时候千万不要改链表本身 —— 所以参数是一层指针 Node *head 就够了，
 * 我这里只是路过看两眼，一个节点都不动，也就不需要 *。
 */
int slist_length(Node *head)
{
    int count = 0;
    Node *cur = head;
    while (cur != NULL) {
        count++;
        cur = cur->next;
    }
    return count;
}

/*
 * ===================================================================
 * 7a. slist_reverse_iter：反转（迭代版）—— 面试必考
 * ===================================================================
 * 目标：把所有 next 箭头掉个头。
 *
 *   前：  NULL  [1|●] ──► [2|●] ──► [3|●] ──► NULL
 *   后：  NULL ◄──[|1] ◄──[|2] ◄──[|3]   head 指向 3
 *
 * 三个指针配合干活：prev（已反转部分的头）、cur（正在处理的节点）、nxt（cur 的下一个，提前存住）
 *
 *   每一轮做同一件事：把 cur 的箭头掰向 prev，然后整条"窗口"往前滚一格。
 *
 *   第 1 轮  prev=NULL  cur=[1]
 *          ① nxt = cur->next      → nxt 记住 [2]      ★必须先存！
 *          ② cur->next = prev     → [1] 指向 NULL
 *          ③ prev = cur           → prev 变成 [1]
 *          ④ cur = nxt            → cur 变成 [2]
 *          画面： NULL ◄[1]   prev=[1]   cur=[2] ──► [3] ──► NULL
 *
 *   第 2 轮  同样四步，[2] 掰向 [1] ……
 *   第 3 轮  cur=[3]：nxt=NULL，[3] 掰向 [2]，prev=[3]，cur=NULL
 *   循环结束（cur==NULL 说明全部处理完），prev 就是新的头。
 *
 * ★★★ 为什么 nxt = cur->next 必须写在 cur->next = prev 之前？★★★
 *   因为第②步要【覆盖】cur->next 这个格子里的值。
 *   一旦写了，"下一个节点在哪"这条信息就永久消失了 —— 后面那半条链再没人牵住，
 *   全体失联：既走不到，也 free 不掉（内存泄漏），程序还"看起来正常"地跑到某天崩掉。
 *   所以必须先把这个值抄到 nxt 里存着。
 *   这跟 pointer-basics 里 swap 必须先 `int temp = *a;` 是一模一样的道理：
 *   —— 覆盖之前，先把旧值存住。整本指针教科书其实就这一句话。
 *
 * 边界情况：
 *   · 空表：cur = NULL，循环一次不走，*head = prev = NULL ✔
 *   · 单节点：走一轮，[1]->next 指向 NULL（本来就是 NULL），prev=[1]，结果不变 ✔
 *   · 反转两次等于没反转（main.c 里验证）
 */
void slist_reverse_iter(Node **head)
{
    if (head == NULL) {
        return;
    }

    Node *prev = NULL;          /* 已经掰好的那一小段，prev 是它的头 */
    Node *cur = *head;          /* 现在轮到掰它 */
    Node *nxt = NULL;           /* 用来"提前抄住"下一个节点地址的小纸条 */

    while (cur != NULL) {
        nxt = cur->next;        /* ① 先抄住下一个（此刻 cur->next 还没被破坏） */
        cur->next = prev;       /* ② 把当前节点的箭头掰向已完成的段 */
        prev = cur;             /* ③ 已完成段往前扩一个 */
        cur = nxt;              /* ④ 窗口滚到下一个 */
    }

    *head = prev;               /* 循环退出时 cur==NULL，prev 正好是最后一个节点＝新头。
                                 * 这里改的是外面的 head，所以必须用二级指针 */
}

/*
 * ===================================================================
 * 7b. slist_reverse_recursive：反转（递归版）
 * ===================================================================
 * 递归的思维方式跟迭代完全不同，别硬背，抓住两句话：
 *   ① 相信递归：reverse(head->next) 能把【除头以外的部分】反转好，
 *      并返回那一小段的新头（原来的尾巴）。
 *   ② 我只负责把"老的头"接到反转好的那段【后面】。
 *
 *   reverse([1]→[2]→[3]→NULL)
 *     = 先 reverse([2]→[3]→NULL) 得到 新头=[3]，链条变成 [3]→[2]→NULL
 *       然后：head->[2] 就是 [3]→[2] 的尾巴，
 *             head->next->next = head;  → 让 [2] 反过来指 [1]
 *             head->next = NULL;        → [1] 变成新的尾巴
 *       结果：[3]→[2]→[1]→NULL，返回 [3]
 *
 *   图解第②步（递归回来时链条已经是 [3]→[2]，而我手上的 head 还是 [1]，[1]->next 仍指着 [2]）：
 *        [3] ──► [2] ──► NULL
 *                ▲  │
 *      head ──► [1]─┘
 *                （head->next 就是 [2]；head->next->next = head 让 [2] 回头指 [1]）
 *        再 head->next = NULL，[1] 成为尾巴 → [3]→[2]→[1]→NULL
 *
 * 边界：空表 / 单节点 → head == NULL || head->next == NULL 直接返回，这是递归的出口。
 *
 * ⚠ 现实中的坑：递归深度 = 链表长度。十万个节点就是十万层函数调用，
 *   栈会爆（stack overflow）。工程上反转链表一律用迭代版；递归版只用来练"理解递归"。
 */
static Node *reverse_rec(Node *head)
{
    if (head == NULL || head->next == NULL) {
        return head;            /* 出口：空表返回 NULL；单节点返回它自己（它已经是"反转好的"） */
    }

    Node *new_head = reverse_rec(head->next);   /* ① 相信递归：把后面整段反转好，拿到新头 */

    head->next->next = head;                    /* ② 原来紧跟我的那个节点，现在让它回头指我 */
    head->next = NULL;                          /* ③ 我成为这一段的尾巴 */

    return new_head;                            /* 新头一路往上返回，始终是最开始的那个尾巴 */
}

void slist_reverse_recursive(Node **head)
{
    if (head == NULL) {
        return;
    }
    *head = reverse_rec(*head);   /* 递归只能返回"新头是谁"，改外面的 head 还是得靠二级指针 */
}

/*
 * ===================================================================
 * 8. slist_middle：快慢指针找中间节点
 * ===================================================================
 * 笨办法：先数一遍长度 n，再走 n/2 步 —— 遍历两趟。
 * 聪明办法：两根指针同时从 head 出发，快的每次走 2 步，慢的每次走 1 步。
 * 快到终点时，慢的正好在中间。
 *
 * 为什么正好在中间？—— 一句话：【速度是一半，走的距离自然是一半】。
 *   设链表总长 n。快指针从 0 出发，每次 +2；慢指针每次 +1。
 *   两条腿同时迈步，走了 t 次之后：fast 在下标 2t，slow 在下标 t。
 *   快指针到达末尾（2t ≈ n）时，t ≈ n/2 —— 慢指针刚好停在正中间。
 *   不需要知道 n 是多少，一趟就走完了。
 *
 * 图解（n=5，下标 0..4）
 *   迈步次数 t │  slow 下标 │  fast 下标
 *        0     │     0      │     0      ← 出发
 *        1     │     1      │     2
 *        2     │     2      │     4      ← fast 到最后一个节点，fast->next == NULL，退出循环
 *   slow 停在 2 = 第 3 个 = 正中间 ✔（5 个里中间那个就是下标 2）
 *
 * 循环条件为什么写 fast != NULL && fast->next != NULL（顺序绝不能反）：
 *   · n 为奇数（5）：fast 最后落在下标 4（最后一个节点，非空），fast->next == NULL → 退出，
 *     slow 在下标 2（唯一的正中间）✔
 *   · n 为偶数（4）：迈步 t=1 → slow 1 / fast 2；t=2 → slow 2 / fast 4（越界＝NULL）→ 退出，
 *     slow 在下标 2，即"中间两个里偏右的那个"。想拿偏左那个（下标 1），
 *     就在循环里额外用一个变量记下 slow 移动前的位置（单链表没有 prev，只能自己记）。
 *   · n == 0：fast == NULL，第一个条件就不成立 → 返回 NULL，安全 ✔
 *   · 必须先判 fast != NULL 再判 fast->next：C 的 && 是短路的，左边假了右边就不算，
 *     反过来的话 fast 是 NULL 时会去读 NULL->next → 崩。
 *
 * 这招是链表题的万能钥匙：判环（Floyd）、找倒数第 k 个、合并有序链表时都能用。
 */
Node *slist_middle(Node *head)
{
    Node *slow = head;
    Node *fast = head;

    while (fast != NULL && fast->next != NULL) {
        slow = slow->next;          /* 慢的走 1 步 */
        fast = fast->next->next;    /* 快的走 2 步：注意只有 fast 和 fast->next 都非空时才安全 */
    }
    return slow;                    /* 奇数：唯一正中间；偶数：中间偏右那个 */
}

/*
 * ===================================================================
 * 9. slist_print：打成 1 -> 2 -> 3 -> NULL
 * ===================================================================
 * 链表没有"长度"这个概念，只能一直走到 next == NULL 为止，所以打印本身就是 O(n)。
 * 空表也要能打印（就一句 NULL），这正好是最省事的边界情况。
 */
void slist_print(Node *head)
{
    Node *cur = head;
    while (cur != NULL) {
        printf("%d -> ", cur->val);
        cur = cur->next;
    }
    printf("NULL\n");               /* 结尾一定把 NULL 打出来：它是链表"到此为止"的标志，
                                     * 也是所有链表 bug 的源头（忘了判它就要崩） */
}

/*
 * ===================================================================
 * 10. slist_free：全部释放
 * ===================================================================
 * 顺序问题！这是最容易写反的一处：
 *
 *   ✔ 正确：Node *nxt = cur->next; free(cur); cur = nxt;
 *      先把下一个地址抄到纸条上，再还掉当前这一间。
 *
 *   ❌ 错误：free(cur); cur = cur->next;
 *      free 之后 cur 指向的内存已经还给系统了，再读 cur->next 是"未定义行为"：
 *      可能读到垃圾、可能当场崩、也可能一切正常地跑 100 次，第 101 次崩。
 *      —— 又是那条铁律：【要覆盖/销毁一个格子之前，先把里面的值抄出来】。
 *
 * 为什么参数是 Node **head：除了释放节点，还要把外面的头指针置 NULL。
 * 否则外面的 head 还攥着一块已经还不存在的内存（悬空指针），
 * 后续再拿它去 print 就是访问已释放内存 —— ASan 会立刻举报。
 * 置 NULL 之后，误用会当场段错误，比"悄悄读到垃圾"好查一万倍。
 */
void slist_free(Node **head)
{
    if (head == NULL) {
        return;
    }

    Node *cur = *head;
    while (cur != NULL) {
        Node *nxt = cur->next;      /* ① 先抄住下一个 */
        free(cur);                  /* ② 再还掉当前 */
        cur = nxt;                  /* ③ 走到抄下来的那个地址 */
    }
    *head = NULL;                   /* ④ 把外面的头指针清空，杜绝悬空 */
}
