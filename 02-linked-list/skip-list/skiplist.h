#ifndef SKIPLIST_H
#define SKIPLIST_H

/*
 * ===================================================================
 * skiplist.h —— 跳表的「菜单」
 * ===================================================================
 * 这个文件只有声明，没有实现。先看菜单知道跳表能幹哪几件事，
 * 想知道「为什么这么写」再去翻 skiplist.c。
 *
 * ------------------------------------------------------------------
 * 先回答一个前置问题：有序单链表查找为什么一定是 O(n)？
 * ------------------------------------------------------------------
 * 单链表只有 next 一根线，站在任何节点上只能问一句「下一个是不是我要的」。
 * 就算数据是有序的，你也**没有**「跳过一半」的能力 —— 二分查找靠的是
 * `a[mid]` 这种 O(1) 随机访问，链表给不了。于是查找 13 只能这么走：
 *
 *   head ──► [1] ──► [3] ──► [5] ──► [7] ──► [9] ──► [11] ──► [13] ──► [15] ──► NULL
 *            ①      ②      ③      ④      ⑤       ⑥        ⑦   ← 比较 7 次才到
 *
 *   16 个节点，平均要走一半（约 8 步）；1000 个节点就要约 500 步。
 *   数据量翻倍，代价就翻倍 —— 这就是 O(n)，一格一格走的命。
 *
 * ------------------------------------------------------------------
 * 跳表干的事：给链表加第二层、第三层……索引，让它能「跳着走」
 * ------------------------------------------------------------------
 * 只在【部分节点】上挂额外的指针，形成上层"高速公路"。查找时先在高层大步跨，
 * 走不动了就下沉一层小步走，永远不回头：
 *
 *   第 2 层   HEAD ──────────────────────────────► [13] ──────────────► NIL
 *   第 1 层   HEAD ──────► [5] ─────────────────► [13] ──────► [15] ──► NIL
 *   第 0 层   HEAD ─► [1] ─► [3] ─► [5] ─► [7] ─► [9] ─► [11] ─► [13] ─► [15] ─► NIL
 *
 *   查 13：第 2 层一步跨到 13，命中。比较次数从 7 掉到 2。
 *   每上一层大约淘汰一半节点 ⇒ 层数 ≈ log2(n) ⇒ 查找 ≈ O(log n)。
 *
 * ------------------------------------------------------------------
 * 节点结构：本节最容易看错的地方，先在这里打个照面
 * ------------------------------------------------------------------
 *   typedef struct SkNode {
 *       int key;
 *       struct SkNode **forward;    ← 注意是「双星号」：既不是数组声明，也不是 (*p)[N]
 *   } SkNode;
 *
 * `forward` 指向的是一块「**指针的数组**」：数组里每一个格子装的都是一个
 * SkNode 指针，forward[l] 就是"第 l 层的下一个节点在哪"。
 * 它**不是**「数组的指针」（那种写法的类型长这样：struct SkNode *(*p)[8]，
 * 意思是 p 指向一整块、长度固定为 8 的数组）。
 *
 *   指针的数组：  forward[0], forward[1], forward[2] …   每个格子是一个指针  ← 本节用这个
 *   数组的指针：  (*p)[0], (*p)[1], …                     p 只是指向一整块数组
 *
 * 两者在"取第 l 个元素"时写法碰巧一样（都能写 forward[l]），所以极易看漏；
 * 差别在 sizeof 和 +1 走多远上。skiplist.c 里第 2 幕有实测对比，别错过。
 * 之所以用「指针的数组」而不是定长数组：每个节点的层数是随机决定的，
 * 有人 1 层有人 7 层，按 MAX_LEVEL 定长存会浪费大量内存。
 *
 * ------------------------------------------------------------------
 * 头/尾哨兵（head / nil）
 * ------------------------------------------------------------------
 *   head：key 不参与比较（放 INT_MIN），层数 = MAX_LEVEL，永远存在。
 *          有了它，"插在最前面"和"插在中间"就是同一行代码（单链表哨兵的老招）。
 *   nil ：key = INT_MAX，代表"这一层到此为止"，层数同样 = MAX_LEVEL，
 *          它的 forward[l] 自环指向自己。
 *          有了它，内层循环只写 `while (x->forward[l]->key < key)` 就够了，
 *          不用到处判 NULL —— 因为 NIL 的 key 比任何真 key 都大，循环自然停。
 *   ⚠ 代价：INT_MAX 这个值被哨兵借走了，真 key 不能再用它（见 README「常见的坑」）。
 */

#include <stdbool.h>   /* C11 标准库的 bool / true / false，纯粹为了代码像人话 */

/*
 * 跳表最多几层。16 层能撑住多大的表？
 *   第 l 层的节点期望个数 ≈ n / 2^l，层数期望 ≈ log2(n)。
 *   想用到第 15 层（一层索引到 1 个节点），n 得接近 2^15 = 32768。
 *   所以 16 层对十万级数据绰绰有余；写死上限是为了让"抛硬币"不会抛上天。
 */
#define SK_MAX_LEVEL 16

/*
 * ===================================================================
 * 节点：一个 key + 一串"各层后继"指针
 * ===================================================================
 * 注意 forward 的类型：struct SkNode ** —— 「指针的数组」退化后的首地址。
 * 长度不固定，等于该节点的层数 + 1，由 sk_make_node 现场 malloc。
 */
typedef struct SkNode {
    int             key;      /* 这个节点装的数据（本节元素类型统一是 int）*/
    struct SkNode **forward;  /* forward[l] = 第 l 层的下一个节点；不是「数组的指针」，见文件头 */
} SkNode;

/*
 * ===================================================================
 * 跳表本体
 * ===================================================================
 * 为什么把结构做成结构体而不是 SkNode **？
 *   和链表栈同一个理由：要改的不只是 head，还有 level / size / 计数器。
 *   把家当装进一个盒子，函数收 SkipList *s（盒子的地址），就能改到外面那份，
 *   省掉满屏的二级指针。
 */
typedef struct {
    SkNode *head;          /* 头哨兵，层数 = SK_MAX_LEVEL；s->head 本身永不变 */
    SkNode *nil;           /* 尾哨兵，key = INT_MAX，forward[l] 自环指自己 */
    int     level;         /* 当前**层数**（不是最高层号）：有效层是 0 .. level-1，至少 1 */
    int     size;          /* 真实节点个数（不含两个哨兵）*/
    long    cmp_count;     /* 累计"比较过一次 key"的次数。复杂度实测那一幕全靠它 */
    long    pointer_slots; /* 记账用：全表一共分配了多少个 forward 格子（用来实测"空间≈2n"）*/
    bool    trace;         /* true = insert/search/remove 顺手把「逐层下降的路径」打出来 */
} SkipList;

/* ---------- 生命周期 ---------- */

/*
 * 建一张空跳表。
 *   seed：随机种子。教材里**必须**传固定值，否则每次运行结构都不一样，
 *         README 里的 dump 图和运行输出就对不上了。
 *         真实系统里反而要传真随机（时间戳/随机设备）—— 理由见 skiplist.c 注释。
 * 内部会 srand(seed)，所以本文件里所有随机数都从这个种子出发，可完全复现。
 */
void sk_init(SkipList *s, unsigned int seed);

/*
 * 销毁：把每个节点的 forward 数组和节点本体都还回去，最后置 NULL。
 * ⚠ 每个节点是**两次 malloc**（节点本体一次 + forward 数组一次），
 *   所以也必须**两次 free**，少 free 一次 ASan 就报一次泄漏。
 */
void sk_destroy(SkipList *s);

/* ---------- 随机分层 ---------- */

/*
 * 抛硬币决定新节点该有几层：每次 50% 概率再升一层，上限 SK_MAX_LEVEL - 1。
 * 单独抽成函数，是为了让你能在 main.c 里连着调用它、把"层数分布"直接数出来。
 */
int sk_random_level(void);

/* ---------- 核心操作 ---------- */

/*
 * 插入：自动抛硬币决定层数。
 *   key 已存在时**不**插（有序结构里重复 key 会让 remove 只删掉一份，见反例二）。
 *   返回 true = 真插进去了；false = 已存在或内存不够。
 * 这是本节的核心：查找路径顺手就把每一层的「前驱」记在 update[] 里了，
 * 插入 = 在每一层把新节点塞进前驱和后继中间。
 */
bool sk_insert(SkipList *s, int key);

/*
 * 指定层数插入。正式代码不该用它（层数该随机），
 * 它是给反例一准备的开关：把 level 永远钉成 0，跳表立刻退化成有序单链表。
 */
bool sk_insert_pinned(SkipList *s, int key, int level);

/*
 * 允许重复 key 的插入 —— 反例二专用（模拟"忘了判已存在"的写法）。
 * 重复 key 会让 size 和"有几个不同的数"不一致，删的时候只能删掉一份。
 */
bool sk_insert_dup(SkipList *s, int key);

/*
 * 查找。返回 true = 找到。
 * 把 key 比较的次数累加进 s->cmp_count；s->trace 为真时逐步打印查找路径
 * （从最高层出发、每层走了哪几个节点、什么时候下沉），让你亲眼看到"跳"。
 */
bool sk_search(SkipList *s, int key);

/*
 * 删除。和插入完全对称：同样要先走出 update[]，再在每一层检查
 * 「这一层的前驱的后继是不是它」，是就摘掉。最后 free 两次 + 收缩 level。
 */
bool sk_remove(SkipList *s, int key);

/*
 * 范围查询：把所有 lo <= key <= hi 的值按顺序写进 out（最多 out_cap 个）。
 * 返回实际写入的个数。跳表做范围查询特别便宜：定位 lo 只要 O(log n)，
 * 之后沿第 0 层一路 next 到 hi 为止，**不用回到树里中序遍历**。
 */
int sk_range(const SkipList *s, int lo, int hi, int *out, int out_cap);

/* ---------- 可视化 ---------- */

/*
 * 本节最重要的可视化：把整个多层结构一层一行打印出来，
 * 从最高层往下，每层列出该层走过的 key，**空层也照样打印**（标成「(空)」），
 * 这样"索引层比底层稀疏"这件事一眼就能看出来。
 */
void sk_dump(const SkipList *s);

/*
 * 全表 forward 格子的总数，用来实测"空间期望 ≈ 2n"这句话。
 *
 * ⚠ 为什么不能"沿第 0 层走一遍，每个节点数到 NULL 为止"？
 *   因为 forward 数组的长度【恰好】是"层数 + 1"，里面**没有一个 NULL 做终止符**
 *   （malloc 了多少格就正好用多少格）。数到 NULL 会读到数组外面去 ——
 *   ASan 会当场报 heap-buffer-overflow。这是个非常典型的"指针的数组"陷阱：
 *   C 语言不会替数组记长度，长度信息只能由【造它的人】保管。
 *   所以这里改成记账：插入时 += (level + 1)，删除时 -= 它在几层上被摘掉。
 *   这两个数天生相等，因为"某节点被多少层指向"= "它自己有多少层"。
 */
long sk_total_forward_slots(const SkipList *s);

#endif /* SKIPLIST_H */
