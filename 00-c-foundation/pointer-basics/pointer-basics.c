#include <stdio.h>
#include <stdlib.h>
#include "pointer-basics.h"

/*
 * ===================================================================
 * 1. 值传递：函数拿到的是"复印件"
 * ===================================================================
 * 调用 swap_by_value(x, y) 时，C 语言把 x 和 y 的值【拷贝】一份给 a 和 b。
 * 从此 a、b 和 x、y 再无任何关系，在函数里怎么改都影响不到外面。
 *
 *   外面:  x = 3   y = 5
 *            │       │
 *   函数里: a = 3   b = 5   ← 只是值一样的两份独立拷贝
 *
 * 所以这个函数"看起来在交换"，实际上外面毫无变化。
 * 我们故意留着这个错误版本，让你亲眼看到失败长什么样。
 */
void swap_by_value(int a, int b)
{
    int temp = a;
    a = b;
    b = temp;
    /* 函数内确实交换成功了，但这个成功马上就会被销毁 */
    printf("      [函数内部] a=%d, b=%d   ← 这里看着是交换好了\n", a, b);
}

/*
 * ===================================================================
 * 2. 指针传递：函数拿到的是"门牌号"
 * ===================================================================
 * 调用 swap_by_pointer(&x, &y) 时，传的是 x、y 的【地址】。
 * 函数虽然也是拷贝了一份地址，但拷贝的地址指向的还是同一块内存！
 * 所以通过 *a 去改，就等于直接改到了外面的 x。
 *
 *   外面:  x = 3  位于地址 0x100
 *            ↑
 *   函数里: a = 0x100  ← 存的就是那个地址
 *          *a 就是 0x100 里装的东西，也就是 x 本身
 *
 * 记法：  a  是地址，   *a 是地址里装的值。
 */
void swap_by_pointer(int *a, int *b)
{
    int temp = *a;   /* 先把 a 指向的值抄下来，否则会被覆盖掉 */
    *a = *b;         /* 把 b 指向的值，写进 a 指向的内存 */
    *b = temp;       /* 把刚才抄下来的值，写进 b 指向的内存 */

    printf("      [函数内部] *a=%d, *b=%d\n", *a, *b);
}

/*
 * ===================================================================
 * 3. 指针当"输出参数"
 * ===================================================================
 * C 语言的函数只能 return 一个值。想同时得到"商"和"余数"怎么办？
 * 常规做法：商用 return 返回，余数让调用者提前给一个地址过来，我写进去。
 *
 * remainder_out 这个参数名后缀 _out 是个约定俗成的记号：
 *   "这个指针是给我用来往外写的"，不是给我读进来的。
 *
 * 传 NULL 是合法的，表示"我不关心余数"，所以要判空再写。
 */
int divide_with_remainder(int dividend, int divisor, int *remainder_out)
{
    if (divisor == 0) {
        /* 除数是 0，整数除法会直接让程序崩掉，必须自己挡住 */
        /* 这里用 printf 是为了让演示输出顺序整齐；正式项目里错误信息应该写 stderr */
        printf("      [错误] 除数不能为 0\n");
        if (remainder_out != NULL) {
            *remainder_out = 0;
        }
        return 0;
    }

    int quotient = dividend / divisor;

    if (remainder_out != NULL) {
        *remainder_out = dividend % divisor;   /* 星号 = 往那个地址里写 */
    }
    return quotient;
}

/*
 * ===================================================================
 * 4. 数组名会"退化"成指针
 * ===================================================================
 * 写 `int arr[]` 作参数时，编译器会偷偷改成 `int *arr`。
 * 所以函数里 sizeof(arr) 得到的是指针的大小（8），不是数组的大小！
 * 这就是为什么传数组一定要【同时传长度 n】。
 *
 * const 的意思是："我承诺只读不改这块内存"，写错了编译器会提醒你。
 *
 * 下面两行注释掉了逻辑重复的部分，重点是对比两种写法完全等价：
 *     arr[i]      ← 人话：第 i 个元素
 *     *(arr + i)  ← 机器视角：从起点往后走 i 格，再取那格的内容
 */
int sum_array(const int *arr, int n)
{
    int sum = 0;
    for (int i = 0; i < n; i++) {
        sum += *(arr + i);   /* 和 sum += arr[i]; 一模一样，只是写法不同 */
    }
    return sum;
}

/*
 * ===================================================================
 * 5. 在堆上申请数组
 * ===================================================================
 * 局部变量活在小格子（栈）里，函数一返回就没了，所以不能返回局部数组的地址。
 * 想要"函数造一个数组、外面接着用"，必须去堆上申请——堆内存不会自动回收，
 * 必须调用者用完后主动 free()，否则就是内存泄漏。
 *
 * malloc 的参数是"总共多少字节" = 元素个数 × 每个元素多大。
 * malloc 失败会返回 NULL，正式代码必须判空。
 */
int *make_array(int n, int fill_value)
{
    if (n <= 0) {
        return NULL;
    }

    /* sizeof(int) 让编译器去算平台上的真实大小，比手写 4 安全 */
    int *arr = malloc((size_t)n * sizeof(int));
    if (arr == NULL) {
        printf("      [错误] 内存申请失败，想要 %d 个 int\n", n);
        return NULL;
    }

    for (int i = 0; i < n; i++) {
        arr[i] = fill_value;
    }
    return arr;   /* 返回地址：外面拿到的就是这块堆内存的入口 */
}

/*
 * free 之后指针本身还在，但它指向的内存已经还给系统了，
 * 这种指针叫"悬空指针/野指针"，再拿去买菜就是未定义行为。
 * 好习惯：free 完立刻置 NULL（置 NULL 后再 free 一次是安全的空操作）。
 */
void free_array(int *arr)
{
    free(arr);   /* free(NULL) 是合法的空操作，所以这里不用额外判空 */
}
