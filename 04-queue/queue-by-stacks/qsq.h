#ifndef QSQ_H
#define QSQ_H

/*
 * ===================================================================
 * qsq.h —— 用两个栈拼出一个队列（TwoStackQueue）
 * ===================================================================
 * 栈：后进先出（LIFO）—— 最后压进去的最先出来。
 * 队列：先进先出（FIFO）—— 最早压进去的最先出来。
 * 两个规矩看起来正好相反，居然能用一个拼出另一个？能。关键动作只有一个字：**倒**。
 *
 * 【本节的全部秘密】
 *   准备两个栈，分工严格：
 *     in  栈：只负责**进队**。enqueue 永远压到这里，绝不从这里出队。
 *     out 栈：只负责**出队**。dequeue 永远从这里弹，绝不往这里压新来的。
 *
 *   要出队时，如果 out 栈是空的，就把 in 栈**整个**倒进 out 栈：
 *     in 栈底 → 栈顶   =   旧 → 新
 *     倒过去之后
 *     out 栈底 → 栈顶  =   新 → 旧     ← 顺序被反过来了！
 *   于是 out 栈的栈顶正好是**最早进队**的那个元素 —— 直接 pop 就是 FIFO。
 *
 *           in 栈（压入侧）                    out 栈（弹出侧）
 *            ┌──────┐  ← 栈顶（最新）           ┌──────┐  ← 栈顶（最旧！可以出队了）
 *            │  3   │                           │  1   │
 *            ├──────┤                           ├──────┤
 *            │  2   │      ── 整个倒过去 ──►    │  2   │
 *            ├──────┤                           ├──────┤
 *            │  1   │  ← 栈底（最旧）           │  3   │  ← 栈底（最新）
 *            └──────┘                           └──────┘
 *
 * 【为什么这样是 O(1) 均摊，而不是 O(n)】
 *   单次出队最坏确实要搬 n 个元素。但**每个一辈子只被搬一次**：
 *   元素进 in 栈 1 次 → 被倒进 out 栈 1 次 → 从 out 栈弹出 1 次，然后再也不会被搬动。
 *   所以 n 次操作总搬运 ≤ n 次，均摊下来每次操作 O(1)。
 *   main.c 第 6 幕用计数器把这句话**量**出来（搬运次数 == 出队次数）。
 *
 * 【反面教材】见 q_dequeue_naive：每次出队都把 in 倒进 out，取完一个再倒回 in。
 *   它对外的行为也是 FIFO，**结果完全正确**，但每个元素每次出队都被搬一遍 → 单次 O(n)。
 *   这就是"均摊"和"最坏"的区别所在，也是这道面试题真正想考的东西。
 *
 * ⚠ 一条不许违反的纪律（违反就当场错序，main.c 第 7 幕有现场）：
 *   **out 栈非空的时候，绝对不许把 in 栈倒进来。**
 *   因为 out 栈里躺着的是"更早的那批"，in 栈里是"更晚的那批"，
 *   一倒进来，晚的就被压到早的上面，晚的先出去 —— FIFO 立刻失效。
 *   所以代码里那个 `if (istk_empty(&q->out))` 判断不是优化，是**正确性要求**。
 *
 * ★ 本目录自包含：只 include 本目录的 istack.h 和标准库，不碰 03-stack/。
 */

#include <stdbool.h>
#include "istack.h"

/*
 * 两个栈 + 五个计数器。计数器不是装饰：本节一半的教学价值（均摊分析）全靠它们实测。
 * 元素类型一律 int —— 没有 void *，没有函数指针比较器。
 */
typedef struct {
    IntStack in;            /* 进队侧：所有新元素都压到这里 */
    IntStack out;           /* 出队侧：所有出队都从这里弹   */

    long enqueue_ops;       /* 入队调用了多少次（含失败的）*/
    long dequeue_ops;       /* 出队调用了多少次（含失败的）*/
    long dequeue_fail;      /* 其中多少次是"队列本来就空" */
    long pour_ops;          /* "整栈倒过去"这个动作发生了多少次 */
    long move_count;        /* ★ 搬运次数：一个元素从 in 挪到 out 记 1（均摊分析的主角）*/
    long max_one_pour;      /* 单次【倒栈】搬过的最大元素数 —— 一趟搬家的峰值 */
    long max_one_deq;       /* ★ 单次【出队】搬过的最大元素数：一次出队里所有倒栈之和。
                             *    正确版：这一次顶多倒一趟 = k 个；
                             *    反面版：倒过去 k 个 + 倒回来 k-1 个 = 2k-1 个。
                             *    两个字段必须分开：拿 max_one_pour 去说"最坏一次出队"，
                             *    在反面版上会说出 64（其实是 127）—— 计数器一说错，
                             *    整节的均摊论证就不可信了。 */
} TwoStackQueue;

/* ---------- 生命周期 ---------- */

/* 两个栈各自 init，计数器全清零。数组在结构体里，所以没有 malloc。 */
void q_init(TwoStackQueue *q);

/*
 * 销毁。这里没有堆内存要 free，但它必须存在，两个理由：
 *   ① 仓库规矩：有 init 就有 destroy，读代码的人不用先推断"这个类型有没有_malloc"；
 *   ② destroy 之后结构体必须处在一个"再用也不会读到旧数据"的状态 —— 这里就是再 init 一次。
 * main.c 结尾会把它 destroy 掉，ASan 报告里因此一个字都不该有。
 */
void q_destroy(TwoStackQueue *q);

/* ---------- 四个队列动作 ---------- */

/*
 * 入队：只往 in 栈压一根，O(1) 最坏（不是均摊，是**每次**都 O(1)）。
 * 返回 false 只有一种可能：in 栈满了（ISTK_CAP 定死 64）。
 */
bool q_enqueue(TwoStackQueue *q, int value);

/*
 * 出队：队头元素写到 *out。
 * 队列为空返回 false（此时 *out 一个字都不改，方便调用方打印"没取到"时不撒垃圾）。
 * 这一步里可能触发倒栈：所以最坏 O(n)、均摊 O(1)。
 */
bool q_dequeue(TwoStackQueue *q, int *out);

/*
 * 看队头但不拿走。
 * ★ 注意它的签名**不是 const** —— 因为如果 out 栈是空的，peek 也得真的把 in 栈倒过来，
 *   这是有副作用的操作。"看起来是只读的函数其实会改结构"是这一节最阴的一个坑，
 *   见 README 的「常见的坑」第 5 条（还有另一种绕法：直接看 in 栈的栈底，代价是破坏封装）。
 */
bool q_peek(TwoStackQueue *q, int *out);

/* 判空：两个栈都空才算空 —— 只判一个是最常见的写法错误。 */
bool q_empty(const TwoStackQueue *q);

/* 元素个数 = 两栈之和。 */
int q_size(const TwoStackQueue *q);

/* ---------- 反面教材（只在 --bug=naive 下调用，正常演示一次都不跑）---------- */

/*
 * 每次出队：先把 in 整栈倒进 out（搬 k 个），弹出栈顶（= 队头），再把 out 剩下的
 * **全部倒回 in**（再搬 k-1 个）。结果是对的，复杂度是灾难：单次出队 2k-1 次搬运，
 * n 次操作 O(n^2)。
 * 它和 q_dequeue 共用同一个 move_count，所以反例幕能拿同一个口径对比两者。
 */
bool q_dequeue_naive(TwoStackQueue *q, int *out);

/* ---------- 可视化 ---------- */

/*
 * 把两个栈**并排竖着**画出来：左边 in、右边 out，每格一个元素，栈顶画在最上面。
 * 这一节的全部理解都靠这张图，所以每个操作之后都要画一次。
 * op 传本次做了什么（可以为 NULL）。
 */
void q_dump(const TwoStackQueue *q, const char *op);

/* 只把计数器归零，不动队列内容（跑对比实验时用得上）。 */
void q_reset_counters(TwoStackQueue *q);

#endif /* QSQ_H */
