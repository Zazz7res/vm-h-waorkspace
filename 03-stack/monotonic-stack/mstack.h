#ifndef MSTACK_H
#define MSTACK_H

/*
 * ===================================================================
 * mstack.h —— 单调栈的「菜单」
 * ===================================================================
 * 先复习一下普通栈：栈只保证「后进先出」，里面可以随便放什么顺序的数。
 * 单调栈 = 普通栈 + 一条额外纪律：
 *
 *   ★ 栈里存的东西，从栈底到栈顶必须始终保持【单调】（一直递增 或 一直递减）。★
 *
 * 怎么维持这条纪律？靠 push 之前的「清理」动作：
 *   要维持递减栈，新元素如果比栈顶大，就把栈顶弹掉，一直弹到不破坏纪律为止，然后才压入。
 *   （也就是说：单调性是「弹」出来的，不是「查」出来的。）
 *
 * 为什么这样做值得？因为「弹」这个动作正好就是答案产生的瞬间：
 *   能被新元素弹出去的栈顶，说明「它右边第一个比它大的数」就是新元素 —— 顺手就把答案写了。
 *   于是很多「每个元素都要往两边看很远」的问题，一次遍历全解决。
 *
 * 两个必须搞懂的点（下面两个应用都会反复用到）：
 *   ① 栈里存的通常是【下标】而不是值。因为「下一个更大元素」「宽度」都要靠位置算，
 *      值可以用 nums[idx] 现取，下标丢了就再也找不回来。
 *   ② 复杂度为什么是 O(n) 而不是 O(n²)？
 *      外层 for 走 n 步，内层 while 看起来可能走很多步……
 *      但每个下标一生【最多入栈一次、出栈一次】，所以 while 的总执行次数 ≤ n。
 *      把两层循环的开销合起来数：push 共 n 次 + pop 共 ≤ n 次 = 2n 次 → O(n)。
 *      这叫「摊还」：单次可能弹很多个，全局加起来是有上限的。
 *      本文件的两个函数都自己数了 push/pop 次数，运行结果末尾会打印出来给你看。
 *
 * 递减栈 / 递增栈怎么选（背这张表）：
 *   求「右边第一个【更大】的」 → 栈里保持【递减】（新值大就弹小的）
 *   求「右边第一个【更小】的」 → 栈里保持【递增】（新值小就弹大的）
 *   求「左边第一个更大的」     → 还是递减栈，但从右往左扫（或者在弹的时候记录）
 *   接雨水（找左右两堵墙）     → 递减栈（墙必须一路变矮才可能夹出水槽）
 *   柱状图最大矩形             → 递增栈
 *
 * ⚠ 本目录完全自包含：下面这个 MiniStack 是就地重写的一份极小 int 栈，
 *   没有 #include 兄弟目录 03-stack/array-stack/astack.h ——
 *   Makefile 按目录独立编译，跨目录 include 会直接编译失败。
 *   单调栈本来就是「普通栈 + 一条纪律」，复制 20 行最省事，也最不容易被别处的改动牵连。
 */

#include <stdbool.h>

/*
 * MiniStack —— 极小 int 栈（存下标用）
 *   和 array-stack 的差别：没有 auto_grow、没有教学打印，只留单调栈用得上的 5 件事。
 *   固定容量：两个 demo 都能提前算出「最多 n 个元素」（栈里最多同时装 n 个下标），
 *   所以一开始就 malloc(n) 一次到位，绝对不会再出现「栈满」这个失败分支。
 */
typedef struct {
    int *data;      /* 连续内存，存 int（这里存的是下标）*/
    int  capacity;  /* 总格子数 */
    int  top;       /* 栈顶元素的【下标】；空栈 = -1（流派 A，和 array-stack 保持一致）*/
} MiniStack;

void  mini_init(MiniStack *s, int capacity);              /* 一次 malloc，不会失败到需要扩容 */
void  mini_destroy(MiniStack *s);                         /* free 并复位，防悬空 */
bool  mini_push(MiniStack *s, int value);                 /* 满了返回 false（demo 里不会发生）*/
bool  mini_pop(MiniStack *s, int *out_value);             /* 空了返回 false */
bool  mini_peek(const MiniStack *s, int *out_value);      /* 只看栈顶 */
bool  mini_is_empty(const MiniStack *s);
int   mini_size(const MiniStack *s);
void  mini_print_with_values(const MiniStack *s, const int *nums, const char *label);
                                                          /* 把栈里的下标连同对应的值一起打出来 */

/*
 * ---------- 应用 ① 下一个更大元素（Next Greater Element）----------
 *
 * 给定 nums[0..n-1]，为每个位置 i 求：i 右边【第一个严格比 nums[i] 大】的数是多少，
 * 右边找不到就填 -1。
 *
 *   nums_out  指向调用者准备好的 int 数组（长度至少 n），函数把答案写进去
 *   过程中每一步都会打印：当前处理谁、弹了谁、谁的答案被确定了、栈现在长什么样
 *
 * 复杂度：外层 n 步 + 内层总共 ≤ n 次弹出 = O(n)；空间 O(n)（栈最多 n 个下标）。
 *         对比暴力法「每个 i 往右扫到找到大的」= O(n²)。
 */
void mstack_next_greater(const int *nums, int n, int *ans_out);

/*
 * 静默版：同样的算法，但【不打印过程】，只把「入栈次数 / 出栈次数」通过输出参数带回来。
 * 为什么要有这个版本？因为第 4 幕要和暴力法【数操作次数】做对比，
 * 如果一边算一边刷屏，读者根本看不清在比什么。
 * 两个版本共用 mstack.c 里同一个 nge_core（verbose 开关决定打不打印），
 * 这样保证「演示的逻辑」和「计数的逻辑」绝对是一致的，不会出现两套代码。
 */
void mstack_next_greater_counted(const int *nums, int n, int *ans_out,
                                 int *push_count_out, int *pop_count_out);

/*
 * ---------- 应用 ② 柱状图接雨水（简单版）----------
 *
 * 给定每根柱子的高度 height[0..n-1]（柱宽都是 1，间距 0），求雨后每根柱子上方能积多少水。
 * 用单调栈（递减栈）逐层结算：
 *   遇到一根比栈顶高的柱子，说明栈顶那根矮柱子被「左墙」和「右墙」夹住了 → 可以蓄水。
 *   水槽宽度 = i - 左墙下标 - 1，高度 = min(左墙高, 右墙高) - 槽底高。
 *
 * 打印内容：每次结算的左右墙、宽度、这一层多深、落到哪几根柱子上，
 *           最后给出每根柱子的水量条形图 + 总量。
 *
 * 复杂度：同样 O(n)（每个下标进出栈各一次），空间 O(n)。
 */
void mstack_trapping_rain_water(const int *height, int n);

#endif /* MSTACK_H */
