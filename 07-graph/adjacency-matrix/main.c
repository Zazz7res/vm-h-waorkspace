#include <stdio.h>
#include "gmatrix.h"

/*
 * main.c —— 邻接矩阵分幕演示
 *
 * 每一幕只做一件事，把结果原样打出来。
 * 建议一边看输出、一边对照 README.md 的「内存布局图解」那一节。
 */

/* 小工具：打印一行分隔线，让输出好读（每个 main.c 都自带一份，叶子目录互不引用） */
static void section(const char *title)
{
    printf("\n----------------------------------------\n");
    printf("%s\n", title);
    printf("----------------------------------------\n");
}

int main(void)
{
    /* ============================================================
       第 1 幕：把共用示例图 G 建成一张表，并整张打印出来
       ============================================================
       G：8 个顶点 0..7，7 条边，故意不连通
         分量一 0-1, 1-2, 2-0, 2-3
         分量二 4-5, 5-6, 6-4
         孤立点 7
       */
    section("1. 建图：把示例图 G 填进二维数组");

    GMatrix g;                     /* 栈上一个结构体就是整张图，不用 malloc、不用 free */
    gmatrix_sample(&g);
    printf("  顶点数 v = %d，边数 e = %d\n", g.v, g.e);
    printf("  结构体本身占 %zu 字节（其中 64 格 × %zu 字节 = 256 字节的矩阵，再加 v、e 两个 int）\n",
           sizeof(GMatrix), sizeof(int));
    printf("\n");
    gmatrix_print(&g);
    printf("  看两个特征：① 沿对角线左右镜像对称（无向）② 第 7 行整行全 0（孤立点）\n");

    /* ============================================================
       第 2 幕：判边 —— 邻接矩阵唯一的、也是最大的卖点
       ============================================================ */
    section("2. 判边 has_edge：一次取下标，O(1)");

    printf("  (0,1) 有边吗？ %d   ← 1 表示有\n", gmatrix_has_edge(&g, 0, 1));
    printf("  (1,0) 有边吗？ %d   ← 无向图，反着问答案一样（对称性）\n",
           gmatrix_has_edge(&g, 1, 0));
    printf("  (0,3) 有边吗？ %d   ← 0 和 3 都认识 2，但它俩之间没有直连\n",
           gmatrix_has_edge(&g, 0, 3));
    printf("  (2,3) 有边吗？ %d\n", gmatrix_has_edge(&g, 2, 3));
    printf("  (4,7) 有边吗？ %d   ← 7 是孤立点，跟谁都没边\n",
           gmatrix_has_edge(&g, 4, 7));
    printf("  (0,0) 有边吗？ %d   ← 对角线，我们禁止自环\n",
           gmatrix_has_edge(&g, 0, 0));
    printf("  (7,99) 越界？ %d   ← 越界不读内存，直接答『没有』，防止读到垃圾\n",
           gmatrix_has_edge(&g, 7, 99));
    printf("  以上 7 次判断，每次都只是 edge[a][b] 一个下标，跟图里有几条边无关。\n");

    /* ============================================================
       第 3 幕：查度 + 用握手定理自检
       ============================================================ */
    section("3. 查度 degree：数一数这一行有几个 1");

    gmatrix_print_degrees(&g);
    printf("  顶点 3 的度 = %d（只连 2）\n", gmatrix_degree(&g, 3));
    printf("  顶点 2 的度 = %d（连 0、1、3，是本图度最大的点）\n", gmatrix_degree(&g, 2));
    printf("  顶点 7 的度 = %d（孤立点）\n", gmatrix_degree(&g, 7));

    /* ============================================================
       第 4 幕：加边 / 删边 / 以及三种"不该让你加成功"的情况
       ============================================================ */
    section("4. 改图：加边、删边、以及边界情况");

    printf("  加一条新边 (3,6)（把两个分量桥起来）→ 返回 %d\n", gmatrix_add_edge(&g, 3, 6));
    printf("    e 变成 %d；现在整张图连通了\n", g.e);
    printf("    对称验证：edge[3][6]=%d, edge[6][3]=%d（两格必须同时为 1）\n",
           gmatrix_has_edge(&g, 3, 6), gmatrix_has_edge(&g, 6, 3));

    printf("\n  再重复加一次 (3,6) → 返回 %d（已存在，e 不会变成 %d）\n",
           gmatrix_add_edge(&g, 3, 6), g.e + 1);

    printf("\n  下面三次是故意触发的错误，看代码怎么挡住：\n");
    gmatrix_add_edge(&g, 5, 5);      /* 自环 */
    gmatrix_add_edge(&g, 1, 100);    /* 越界 */
    gmatrix_remove_edge(&g, 0, 7);   /* 删一条本来就不存在的边 */
    printf("    删不存在的边 (0,7) → 返回 0，e 仍然是 %d（没被减成负数）\n", g.e);

    printf("\n  删掉刚加的 (3,6) → 返回 %d，e 回到 %d\n",
           gmatrix_remove_edge(&g, 3, 6), g.e - 1);
    printf("  删完再问一次 (3,6) 有边吗？ %d\n", gmatrix_has_edge(&g, 3, 6));
    printf("  删边在矩阵里就是『涂两格』，不需要顺着链表找前驱改 next —— 这点跟邻接表对比着看很提神\n");

    /* ============================================================
       第 5 幕：带权矩阵 —— 为什么"无边"要用 -1 而不是 0
       ============================================================ */
    section("5. 带权版：哨兵 -1，而不是 0");

    GWeighted wg;
    gw_init(&wg, 5);
    gw_add_edge(&wg, 0, 1, 7);    /* 正常权值 */
    gw_add_edge(&wg, 1, 2, 0);    /* ★ 权值为 0 的合法边：比如"这趟车免费" */
    gw_add_edge(&wg, 2, 3, 15);
    gw_add_edge(&wg, 3, 4, 120);
    gw_add_edge(&wg, 1, 4, 999);
    gw_print(&wg);

    printf("  关键对比：\n");
    printf("    w[0][1] = %3d  有边吗 %d   ← 权值 7，正常\n", gw_weight(&wg, 0, 1), gw_has_edge(&wg, 0, 1));
    printf("    w[1][2] = %3d  有边吗 %d   ← ★ 权值 0，仍然是『有边』！\n", gw_weight(&wg, 1, 2), gw_has_edge(&wg, 1, 2));
    printf("    w[0][4] = %3d  有边吗 %d   ← -1 才是『无边』\n", gw_weight(&wg, 0, 4), gw_has_edge(&wg, 0, 4));
    printf("  如果当初拿 0 当『无边』标记，第 2 行那条免费的路就会被读成『不存在』，\n");
    printf("  最短路会绕过它多跑 999 —— 逻辑没错、数据也没错，纯粹是标记选错了。\n");
    printf("\n  故意违规的三次尝试（应该全部被拒绝）：\n");
    gw_add_edge(&wg, 0, 3, GM_NO_EDGE);   /* 权值想用 -1：拒绝 */
    gw_add_edge(&wg, 2, 2, 5);            /* 自环：拒绝 */
    gw_add_edge(&wg, 0, 1, 50);           /* 平行边：矩阵表达不了，拒绝 */
    printf("  现在边数 e = %d（没有被上面三次污染）\n", wg.e);

    /* ============================================================
       第 6 幕：算账 —— 什么情况下邻接矩阵不能用
       ============================================================ */
    section("6. 算账：矩阵要花多少内存");

    printf("  【小图】我们的示例图 G：\n");
    gmatrix_space_report(8, 7);

    printf("  【稠密对照】V=8 但把每对不同点都连起来（E=28，满图）：\n");
    gmatrix_space_report(8, 28);
    printf("  → 浪费率降到 12.5%%，而且那 12.5%% 全是对角线 8 格（自己到自己，天生存不了信息）。\n");
    printf("    除了对角线，其余格子格格有用 —— 这时候矩阵几乎白送 O(1) 判边，稳赚。\n\n");

    printf("  【大图】社交网络规模：V=100000 人，E=200000 条好友关系\n");
    printf("  （注意：这里只算数字，不真的去申请内存，否则你的电脑会被吃垮）\n");
    gmatrix_space_report(100000, 200000);

    printf("  一句话结论：\n");
    printf("    稀疏图（E 远小于 V×V）→ 邻接矩阵要 40 GB，邻接表只要约 7 MB，差五千多倍；\n");
    printf("    稠密图（E 接近 V²/2）  → 矩阵几乎格格有用（浪费率只剩对角线）；而且邻接表\n");
    printf("      每条边还要多背 8 字节的 next 指针，规模一大反而比矩阵更费内存，\n");
    printf("      再加上矩阵白送 O(1) 判边 —— 稠密图就该用矩阵。\n");

    printf("\n=== 本节结束 ===\n");
    printf("记住三句话：\n");
    printf("  1) 邻接矩阵就是『把图摊平成 V×V 的表』，判边 O(1)，代价是空间只跟 V 有关。\n");
    printf("  2) 无向图加边/删边一定同时改 [a][b] 和 [b][a] 两格，漏一格 = 图断一半。\n");
    printf("  3) 带权矩阵里『无边』要用业务上永远不会出现的哨兵（-1），不能用 0。\n");
    return 0;
}
