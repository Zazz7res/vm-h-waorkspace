#ifndef GMATRIX_H
#define GMATRIX_H

/*
 * ===================================================================
 * 邻接矩阵 adjacency-matrix —— 这一节的"菜单"
 * ===================================================================
 * 这个文件里【只有声明，没有实现】。它只回答一个问题：
 *   "邻接矩阵一共能干哪几件事？每件事的输入输出长什么样？"
 * 真正的代码和"为什么这么写"都在 gmatrix.c 里。
 *
 * -------------------------------------------------------------------
 * 一、邻接矩阵到底是什么？
 * -------------------------------------------------------------------
 * 就是一张**二维表格**。行号和列号都是顶点编号，格子里写 0 或 1：
 *
 *      edge[i][j] = 1   →   顶点 i 到顶点 j **有**一条边
 *      edge[i][j] = 0   →   顶点 i 到顶点 j **没有**边
 *
 * 说白了：邻接矩阵就是"把图摊平成一张表"。判断两点有没有边，
 * 不用找、不用遍历，直接翻到那一格看一眼 —— 这就是它唯一的、
 * 也是最大的优点：**O(1) 判边**。
 *
 * -------------------------------------------------------------------
 * 二、为什么这一节的图是"硬编码固定示例图"？
 * -------------------------------------------------------------------
 * 我们全程用同一张无向图 G（8 个顶点 0..7，故意不连通）：
 *
 *   分量一：0-1, 1-2, 2-0, 2-3     （0、1、2 三个点成环，再挂一个 3）
 *   分量二：4-5, 5-6, 6-4          （另一个环）
 *   孤立点：7                       （谁也不连）
 *
 *   画出来（位置随便摆，连线才是重点）：
 *
 *        0 ───── 1                    4 ───── 5
 *         \     / \                    \     /
 *          \   /   \                    \   /
 *           2 ──────                    6        7  ← 孤零零一个点
 *            \
 *             3
 *
 *   边一共 7 条：(0,1) (1,2) (0,2) (2,3) (4,5) (5,6) (4,6)
 *
 * 用固定图的原因是：README 里贴的运行结果是**确定**的，你随时能自己
 * 跑一遍逐行核对；而且后面 bfs / dfs / 连通分量 三节用的是**同一张图**，
 * 可以前后对照："这张图的邻接矩阵"和"这张图的 BFS 顺序"其实是一回事。
 *
 * -------------------------------------------------------------------
 * 三、为什么结构体里是 int edge[8][8] 而不是动态分配？
 * -------------------------------------------------------------------
 * 为了让你先把注意力放在"图"上，而不是放在 malloc 上。
 * 数组长度是编译期就定死的 8（GM_MAX_V），所以：
 *   - 整个图就是一个结构体，可以直接放在 main 的栈上，不用 malloc，也不用 free；
 *   - 缺点很明确：顶点数超过 8 就装不下，而且**不管图多大都占 64 格**。
 * 这个"缺点"正是本节要算账的重点，见 gmatrix_space_report()。
 *
 * -------------------------------------------------------------------
 * 四、带权版：为什么"无边"要用 -1 而不是 0？
 * -------------------------------------------------------------------
 * 无权图只有"有边/无边"两种状态，用 0/1 足够。
 * 带权图的格子里要存**权值**（距离、价钱、时间……），这时"0"就不够用了：
 *
 *     假如边的权值可以是 0（比如"这趟班车免费"、"两点重合距离为 0"）
 *     那么 edge[i][j] == 0 到底是"没有边"，还是"有一条权值为 0 的边"？
 *     → 分不出来！程序就会把"免费的那条边"当成"不存在"。
 *
 * 所以带权版我们规定一个**不可能的权值**当哨兵（占位符）：
 *     GM_NO_EDGE = -1      // 只要承诺"真实权值不会是 -1"，这个方案就是无歧义的
 * 代码里到处是这种套路，比如字符串结尾的 '\0'、文件末尾的 EOF(-1)、
 * 数组里表示"没找到"的 -1 下标。核心思想一句话：
 *     **拿一个业务上永远不会出现的值，专门用来表示"无"。**
 */

/* 本节的图最多容纳 8 个顶点（正好够画我们的示例图 G）。 */
#define GM_MAX_V 8

/* 带权矩阵里"这两点之间没有边"的哨兵值。见上面第四节说明。 */
#define GM_NO_EDGE (-1)

/*
 * 无权图：格子里只有 0 和 1。
 *   v = 这张图实际用了几个顶点（0..v-1 是合法编号）
 *   e = 实际有几条边。无向图的一条边会同时写进 [i][j] 和 [j][i] 两格，
 *       但只算 1 条，所以 e 是"人类意义上的边数"，不是"格子数"。
 */
typedef struct {
    int edge[GM_MAX_V][GM_MAX_V];
    int v;
    int e;
} GMatrix;

/*
 * 带权图：格子里存权值，-1 表示没有边。
 * 结构和上面一模一样，只是"每个格子含义"变了 —— 这也说明：
 * 换表示法时改的是"读法"，不是"形状"。
 */
typedef struct {
    int w[GM_MAX_V][GM_MAX_V];
    int v;
    int e;
} GWeighted;

/* ---------- 1. 建图 / 改图 ---------- */
void gmatrix_init(GMatrix *g, int v);                       /* 全部格子清零，v 个顶点，0 条边 */
int  gmatrix_add_edge(GMatrix *g, int a, int b);            /* 加一条无向边：返回 1 成功 / 0 非法或已存在 */
int  gmatrix_remove_edge(GMatrix *g, int a, int b);         /* 删一条无向边：返回 1 删掉了 / 0 本来就没有 */

/* ---------- 2. 问问题（邻接矩阵的看家本领）---------- */
int  gmatrix_has_edge(const GMatrix *g, int a, int b);      /* 两点之间有没有边：O(1)，一次取下标 */
int  gmatrix_degree(const GMatrix *g, int u);               /* 顶点 u 的度 = 第 u 行里 1 的个数：O(V) */
void gmatrix_print_degrees(const GMatrix *g);               /* 把每个点的度打成一张表 */

/* ---------- 3. 看 ---------- */
void gmatrix_print(const GMatrix *g);                       /* 带行列号的表格，一眼看清整个图 */

/* ---------- 4. 本节专用：把"共用示例图 G"原样造出来 ---------- */
void gmatrix_sample(GMatrix *g);                            /* 8 个顶点 + 上面那 7 条边 */

/* ---------- 5. 算账：这才是"选表示法"的真正依据 ---------- */
void gmatrix_space_report(int v, int e);                    /* 打印：矩阵多少格、实际几条边、浪费率 */

/* ---------- 6. 带权版 ---------- */
void gw_init(GWeighted *g, int v);                                      /* 全部格子填 -1 */
int  gw_add_edge(GWeighted *g, int a, int b, int weight);               /* 加带权无向边；weight 不能是 -1 */
int  gw_has_edge(const GWeighted *g, int a, int b);                     /* 权值 != -1 就是有边 */
int  gw_weight(const GWeighted *g, int a, int b);                       /* 返回权值；无边返回 -1 */
void gw_print(const GWeighted *g);                                      /* 带权矩阵打印，-1 打成 "·" */

#endif /* GMATRIX_H */
