#ifndef GBFS_H
#define GBFS_H

/*
 * ===================================================================
 * 广度优先搜索 BFS (Breadth-First Search) —— 这一节的"菜单"
 * ===================================================================
 * 这个文件里【只有声明】。真正的代码在 gbfs.c。
 *
 * -------------------------------------------------------------------
 * 一、BFS 一句话：先走近的，再走远的
 * -------------------------------------------------------------------
 * 想象你站在一栋楼的某个房间里，想知道"到其他每个房间最少要穿过几道门"。
 * 你最笨也最聪明的走法是：
 *     第 0 步：我自己在的这个房间
 *     第 1 步：隔壁所有房间（穿 1 道门就能到的）
 *     第 2 步：再外面一圈（穿 2 道门能到的，而且第 1 步没见过的）
 *     第 3 步：再再外面一圈……
 * 像**水波纹**、像**喊一嗓子传开的回声**、像**传染病传播**：
 * 一圈一圈往外扩，同一圈的人同时被感染。
 *
 * 这个"一圈一圈"和 DFS 的"一条路走到黑"就是两种遍历的全部区别。
 *
 * -------------------------------------------------------------------
 * 二、为什么它等价于"无权图最短路"？（本节的核心，务必想通）
 * -------------------------------------------------------------------
 * 结论：在**每条边权值都算 1**的图里，BFS 第一次到达某个顶点 v 时走的步数，
 *       就是从起点到 v 的**最少步数**。dist[] 数组直接就是最短路径长度。
 *
 * 为什么？一句话：**BFS 是按"距离"排序着访问的，永远不会跳层。**
 *
 * 反证一遍就懂：
 *   假设 BFS 第一次到达 v 时是 d 步，但其实存在一条更短的路只需 d' < d 步。
 *   那条路上，起点出发第 d' 步到达 v，说明 v 的前一个点 u 在第 d'-1 步就被到达过。
 *   而 BFS 保证：所有"步数 ≤ d'-1"的点都会先于任何"步数 ≥ d"的点被处理
 *   （因为队列是先进先出，先进队的步数一定不大于后进队的 —— 这就是关键）。
 *   所以 u 早就被处理过，处理 u 时就会把 v 收进队列，v 应当在第 d' 步到达，
 *   矛盾。所以 d 就是最短。
 *
 *   反过来讲更直白：
 *     **第一次到达某个点时的步数一定最短，后面再遇到它只会是同样长或更远。**
 *     所以"已访问就不再访问"这件事在 BFS 里不是偷懒，而是**正确性的来源**：
 *     第二次走到它必然不更优，扔掉它毫无损失。
 *
 *   ⚠ 这个等价**只在无权图（或所有边权相同）成立**。
 *     一旦边有权值，"步数少"不等于"距离短"：
 *         A --100--> C      A --1--> B --1--> C
 *     BFS 只看"几步"，会选 1 步的 A→C（距离 100）；真正最短是 2 步的 A→B→C（距离 2）。
 *     带权最短路要用 dijkstra / bellman-ford / floyd，见本章后面几节。
 *
 * -------------------------------------------------------------------
 * 三、需要一个队列，而且必须是队列
 * -------------------------------------------------------------------
 * "一圈一圈"这件事怎么实现？靠**先进先出**：
 *   我这层的人先排队，我认识的新朋友排在队尾；
 *   只有把我这层所有人处理完，才轮得到下一层。
 * 如果换成栈（后进先出），就变成"最新发现的最先处理"—— 那是 DFS 的脾气，
 * 会一路钻到底，层就乱了，最短路性质立刻失效。
 *   一句话：**BFS 之所以是"广度"优先，完全是队列给的。**
 *
 * 本节在 gbfs.c 里**就地重写了一个 20 行出头的 int 队列**（叶子目录必须自包含，
 * 不能 #include 第 04 章的文件）。有意思的是：这里用的还是仓库里
 * `04-queue/array-queue/` 那个"会假满"的朴素版本 —— 为什么敢用？
 * 第四节解释。
 *
 * -------------------------------------------------------------------
 * 四、为什么这里可以用"不循环"的朴素数组队列
 * -------------------------------------------------------------------
 * `04-queue/` 那节讲过：朴素数组队列 pop 之后头指针前进，空间不回收，
 * 反复"出一版进一版"就会假装满了，要靠循环队列（取模）解决。
 *
 * BFS 这里为什么不用怕？因为：
 *   **一个顶点最多进队一次。**（入队时立刻打 visited 标记，
 *     之后所有想把同一个点推进来的边都会被 visited 拦住。）
 *   所以整场 BFS 的"进队总次数 ≤ V"，队列里"写过的格子总数 ≤ V"。
 *   只要数组开到 V+1 格，tail 单调递增也永远撞不到边界。
 *
 * 这是一个很漂亮的一般性技巧：**当你证明了一个操作最多发生 N 次，
 * 就可以用"只往前走不回绕"的简单结构，把环形缓冲区省掉。**
 * 但注意，这个结论依赖"入队即标记"。如果错误地把打标记推迟到"出队时"，
 * 同一个点会被重复入队，队列长度就可能远超 V，朴素数组就会真的溢出 ——
 * 这是本节最常见的实现 bug，见 README 的坑清单。
 *
 * -------------------------------------------------------------------
 * 五、本节用哪张图？
 * -------------------------------------------------------------------
 * 还是全章共用的**无向图 G**（8 个顶点 0..7，故意不连通）：
 *
 *        0 ───── 1                     4 ───── 5
 *         \     / \                     \     /
 *          \   /   \                     \   /
 *           2 ──────                     6          7 ← 孤零零
 *            \
 *             3
 *
 *   边 7 条：(0,1) (1,2) (0,2) (2,3) (4,5) (5,6) (4,6)
 *
 * 这张图的"不连通"是本节最重要的设计：
 *   从 0 出发做 BFS，只能碰到 0、1、2、3；4、5、6、7 一个都碰不到。
 *   于是我们必须面对"一个图可能有好几个连通分量"这件事，
 *   对每个还没访问过的点都再起一次 BFS —— 这正是下一节连通分量的入口。
 *
 * -------------------------------------------------------------------
 * 六、为什么本节的图又用邻接矩阵，而不是刚学的邻接表？
 * -------------------------------------------------------------------
 * 因为叶子目录必须自包含，本节不想把邻接表那套 malloc/free 再抄一遍，
 * 而矩阵一个栈上数组就够，全部注意力留给"遍历"本身。
 * 代价写在复杂度表里：矩阵版 BFS 是 **O(V²)**，邻接表版是 **O(V+E)**。
 * 大图上必须换邻接表（后面几节也是这么用的），这里 V=8 无所谓。
 * 扫邻居的顺序也不同：矩阵按 j = 0,1,2,... 升序扫，天生固定，
 * 所以输出可复现、可以和 README 逐行核对。
 */

/* 本节示例最多 8 个顶点 */
#define BFS_MAX_V 8

/*
 * 图的容器：无权无向邻接矩阵。
 * 和 adjacency-matrix 那节同构，但**在本目录独立声明**（叶子目录互不引用）。
 */
typedef struct {
    int edge[BFS_MAX_V][BFS_MAX_V];
    int v;
    int e;
} BfsGraph;

/* ---------- 1. 造图 ---------- */
void bfs_graph_sample(BfsGraph *g);        /* 造出共用的示例图 G（8 点 7 边，不连通） */
void bfs_graph_print(const BfsGraph *g);   /* 打出邻接矩阵，知道自己在遍历什么 */

/* ---------- 2. 一次 BFS：从一个起点往外扩 ---------- */
/*
 * 从一个点出发做完整一轮 BFS，填三张表并（可选）打印全过程：
 *   dist_out[u]   起点到 u 最少几步；到不了填 -1
 *   parent_out[u] u 是被谁发现的；起点自己填 -1，没访问到也填 -1
 *   order_out[]   访问（出队）顺序，长度写进 order_len_out
 *   verbose       非 0 就一步一打，把"出队谁、看了哪些邻居、队列长啥样"演出来
 * 返回值：这一轮真正访问到的顶点个数。
 */
int bfs_run(const BfsGraph *g, int start, int dist_out[], int parent_out[],
            int order_out[], int *order_len_out, int verbose);

/* ---------- 3. 全图 BFS：对每个还没访问过的点都起一轮 ---------- */
/*
 * 图可能有好几个连通分量，起一次 BFS 只能覆盖其中一个。
 * 这个函数把"扫完全图"补齐：外层依次看每个顶点，只要还没访问过，
 * 就以它为起点再起一轮 BFS，并打印"第 K 轮：从 u 出发"这样的分隔画面。
 * 返回值：一共起了几轮（== 连通分量的个数）。
 */
int bfs_run_all(const BfsGraph *g, int dist_out[], int parent_out[],
                int order_out[], int *order_len_out, int verbose);

/* ---------- 4. 看结果 ---------- */
void bfs_print_result(const BfsGraph *g, int start, const int dist_out[],
                      const int parent_out[], const int order_out[], int order_len);

#endif /* GBFS_H */
