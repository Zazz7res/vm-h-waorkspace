#ifndef CC_H
#define CC_H

/*
 * ===================================================================
 * 连通分量 + 判环 (Connected Components & Cycle Detection) —— 本节"菜单"
 * ===================================================================
 * 这个文件里【只有声明】。真正的代码在 cc.c。
 *
 * -------------------------------------------------------------------
 * 一、这一节要回答的三个问题
 * -------------------------------------------------------------------
 *   ① 这张图由几"块"拼成？每块里都有哪些顶点？   —— 连通分量
 *   ② 这块里有没有环？如果有，环具体是哪几个点？  —— 判环（无向图 / 有向图两套）
 *   ③ 为什么"有向图"上不能照搬①？               —— 顺手把强连通分量的问题讲清楚
 *
 * 前两问的代码都在本节，跑起来看得见；第三问只讲思路不写实现
 * （Kosaraju / Tarjan 的实现放在更后面的章节，见 README 里那节"诚实声明"）。
 *
 * -------------------------------------------------------------------
 * 二、连通分量：把上一节那句"教训"正式变成一个算法
 * -------------------------------------------------------------------
 * 上一节 DFS 里我们撞到一个事实：从 0 起一轮 DFS 只覆盖 {0,1,2,3}，
 * {4,5,6} 和 {7} 一个都没碰到，而且**程序一声不响、返回值也正常**。
 * 当时补的那句外层扫描，正式写出来就是本节的算法：
 *
 *     分量编号 comp_id[0..V-1] 全部填 -1     ← -1 = 还没归队
 *     编号 k = 0
 *     for 每个顶点 u:
 *         if comp_id[u] == -1:               ← 遇见一个没归队的点
 *             从 u 起一轮 DFS，把这一轮碰到的点全写上 comp_id[...] = k
 *             k++                            ← 一轮 = 一个分量
 *     返回 k
 *
 * 于是得到两个结论，都是白送的：
 *     **k == 连通分量的个数**
 *     **comp_id[u] == comp_id[v] ⟺ u 和 v 连通**（同一块里）
 * 判"这张图整体连通吗"就变成了 `k == 1`，判"这两点在一条链上吗"就是比一下数组。
 *
 * -------------------------------------------------------------------
 * 三、无向图判环：上一节那两条"后向边"就是答案
 * -------------------------------------------------------------------
 * 上一节递归 DFS 的画面里出现过这种行：
 *     "邻居 0：已访问，又不是我父亲 → 『后向边』，这里有环"
 * 这就不是一句解说词，而是**判环的判据本身**：
 *
 *     **做 DFS，遇到一个"已经访问过的邻居"，而它"不是我的父亲" ⇒ 有环。**
 *
 * 为什么？"已访问过"说明从我这里能走回它，"它不是我父亲"说明这条回路不是我刚来的
 * 那条路原样退回来 —— 中间还绕了别的地方，于是闭合出一个环。
 * 反过来讲：如果每次碰到的已访问邻居**都恰好是父亲**，那这条路就是纯粹的一棵树，无环。
 *
 * 两个必须记住的边界：
 *   ① **必须带"父亲"这个参数。** 无向图每条边都存了两格（u→v 和 v→u），
 *      我从 u 钻到 v，v 往回看一定能看见 u。不排掉父亲，
 *      一棵最老实的树也会被判成"处处有环"。
 *   ② **必须扫全图（外层 for）。** 环可能藏在第二个分量里 ——
 *      本节 cc.c 里专门准备了这个反例图（`cc_has_cycle_undirected_from` 只跑一轮，
 *      它会一本正经地回答"无环"，而正确答案是"第 4、5、6 三个点成环"）。
 *
 * -------------------------------------------------------------------
 * 四、有向图判环：颜色法（白 / 灰 / 黑）—— 为什么②那一套不够用
 * -------------------------------------------------------------------
 * 有向图上"已访问的邻居不是父亲"这个判据**会误判**。看这个无环的例子：
 *
 *     0 → 1，0 → 2，2 → 1        （1 有两条路可以到，但一个环都没有）
 *
 * DFS 从 0 出发：先钻 0→1，回到 0，再钻 0→2，2 看到邻居 1"已访问、又不是我父亲"，
 * 按无向图那套就会喊"有环"—— 可这图清清楚楚无环。
 * 差别在于：无向图里"能走回去"就成环；有向图里还得看**方向**，
 * 1 只是被前面那条路"顺路访问过"，从 1 出发并没有路回到 2。
 *
 * 所以要换个更精细的状态。不再只有一个"访问过 / 没访问过"两档，而是三档（颜色）：
 *
 *     白色 WHITE = 我压根还没来过
 *     灰色 GRAY  = 我来过，但**还没走完** —— 我就站在"当前这条往下钻的路"上，
 *                  也就是还压在递归栈里
 *     黑色 BLACK = 我走完了，从我出发能钻到的地方全钻完了 → 我出栈了
 *
 *     判据：**DFS 过程中碰到灰色的邻居 ⇒ 有环。**
 *     （碰到黑色的邻居完全正常：那只是"有个人比我先办完了这件事"，不构成回路。）
 *
 * 为什么灰色命中就是环？灰 = 它在我的"当前路径"上 = 我从它出发一路钻到了我；
 * 现在我又有一条边指回它 ⇒ 它 → … → 我 → 它，一个有向环。
 * 这也是本节代码在命中时会把这条链打出来的原因（沿着 parent 往上追就能追出这个环）。
 *
 * -------------------------------------------------------------------
 * 五、有向图上的"分量"这件事，为什么本节不直接给答案
 * -------------------------------------------------------------------
 * 无向图的"连通"是对称的：u 能到 v，v 就一定能到 u（路是同一条）。
 * 有向图里"u 能到 v"和"v 能到 u"是**两件事**：
 *
 *     6 → 4 → 0        有路，但 0 一步也回不到 6
 *
 * 于是"分量"在有向图上要重新定义：
 *     弱连通：把箭头全当成无向线段来看，得到的连通分量（这个用本节代码套壳就能算）
 *     **强连通**：块内任意两点**互相都能到** —— 这才是有用的那个，叫 SCC
 * 求 SCC 需要新工具（Kosaraju：第二遍在"反向图"上按后序倒序跑；Tarjan：一遍搞定，
 * 用 low-link），本质上是"把灰色状态这件事用到极致"。
 * 本节代码只做到"**用可达性把这个问题演示出来**"（`cc_reachable`），
 * 具体算法在 README 里讲清思路，并诚实标注"本节未实现"。
 *
 * -------------------------------------------------------------------
 * 六、本节用的四张图（全是硬编码固定图，输出可复现）
 * -------------------------------------------------------------------
 *   G   共用无向图（8 点 7 边，3 个分量，有环）—— 和前几节同一张
 *   T   无向树（5 点 4 边，1 个分量，无环）    —— 判环的"阴性对照"
 *   C2  无向"第二个分量里才有环"（8 点）        —— 演示"只起一轮会漏"
 *   DAG 有向无环图（7 点 8 边，拓扑排序那节同一张）/
 *   CYC 有向含环（1→2→3→1，外加孤立点 0）      —— 三色法的两个对照
 *
 * 造图时为什么多了一个 `directed` 字段：判环有两套代码，用错的后果是"把无环判成有环"。
 * 所以函数会先看这个标记，发现图类型和算法不匹配就**大声警告并拒绝**，
 * 而不是硬着头皮算出一个看着挺像样的错答案。
 */

/* 本节示例最多 8 个顶点（G 和 C2 都是 8 点） */
#define CC_MAX_V 8

/* 三色法用的三种颜色。用宏而不是裸 0/1/2，是为了让代码自己说话 */
#define CC_WHITE 0   /* 还没来过 */
#define CC_GRAY  1   /* 来过但还没走完 = 还在当前这条路上（还在递归栈上） */
#define CC_BLACK 2   /* 走完了，出栈了 */

/*
 * 图的容器：无权邻接矩阵 + 一个"有向/无向"标记。
 * 无向边仍然对称涂两格，有向边只涂 edge[a][b] 那一格。
 */
typedef struct {
    int edge[CC_MAX_V][CC_MAX_V];
    int v;
    int e;
    int directed;    /* 0 = 无向图，1 = 有向图。造图时定死，之后只读 */
} CCGraph;

/* ---------- 1. 造图（四张固定图） ---------- */
void cc_sample_undirected(CCGraph *g);   /* G：8 点 7 边，3 个分量，含环 */
void cc_sample_tree(CCGraph *g);         /* T：5 点 4 边的树，连通且无环 */
void cc_sample_split_cycle(CCGraph *g);  /* C2：分量一只有一棵树，环藏在分量二 */
void cc_sample_dag(CCGraph *g);          /* DAG：7 点 8 边有向无环图 */
void cc_sample_cyclic(CCGraph *g);       /* CYC：1→2→3→1，另有孤立点 0 */
void cc_print(const CCGraph *g);         /* 打出矩阵 + 每行的出边/邻居 */

/* ---------- 2. 连通分量（只适用于无向图） ----------
 * 返回分量个数 k；comp_id[u] = u 所属分量的编号（0..k-1）。
 * 图如果是有向的，这个函数会先打印警告再说清楚"这里算出来的东西意味着什么"。
 */
int cc_find_all(const CCGraph *g, int comp_id[], int verbose);

/* 把分量按编号分组打印：分量 0：{ 0 1 2 3 }  大小 4 */
void cc_print_components(const CCGraph *g, const int comp_id[], int comp_count);

/* 每个分量的顶点数 / 边数 / 与"树"的边数比对，用来交叉验证判环结果 */
void cc_component_stats(const CCGraph *g, const int comp_id[], int comp_count);

/* ---------- 3. 判环 ----------
 * 返回值：1 = 找到环，0 = 没环，-1 = 图类型和算法不匹配，**拒答**
 *         （拿无向判据去查有向图、或拿三色法查无向图，都会得到看似合理的错答案，
 *          所以这里宁可不答也要把原因打出来）。
 * cycle_out[] 回填找到的那个环的顶点（按成环顺序，首尾不重复），*len_out 给长度。
 */

/* 无向图：DFS 带父亲。碰到"已访问且非父亲"的邻居 → 有环。只从 start 起一轮（教学对照组） */
int cc_has_cycle_undirected_from(const CCGraph *g, int start,
                                 int cycle_out[], int *len_out, int verbose);
/* 无向图：同上，但外层扫遍每个未访问点 —— 正确写法 */
int cc_has_cycle_undirected(const CCGraph *g, int cycle_out[], int *len_out, int verbose);

/* 有向图：三色法。碰到灰色邻居 → 有环。内部一定扫全图 */
int cc_has_cycle_directed(const CCGraph *g, int cycle_out[], int *len_out, int verbose);

/* 把判环函数挖出来的那个环打成 "0 -> 1 -> 2 -> 0"（收尾重复第一个点，才看得出是圈）。
 * 判环函数只负责"找到环 + 回填数组"，怎么展示由调用方决定，所以这个打印单独公开。 */
void cc_print_cycle(const char *prefix, const int cycle[], int len);

/* ---------- 4. 有向可达：只为把"为什么需要强连通分量"演出来 ----------
 * 从 start 出发、**只能沿着边的方向**能到哪些点（含 start 自己）。
 * 返回能到的点数，reach_out[] 按访问顺序回填。
 */
int cc_reachable(const CCGraph *g, int start, int reach_out[], int verbose);

#endif /* CC_H */
