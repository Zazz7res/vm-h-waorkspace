#ifndef TOPO_H
#define TOPO_H

/*
 * ===================================================================
 * 拓扑排序 Topological Sort —— 这一节的"菜单"
 * ===================================================================
 * 这个文件里【只有声明】。真正的代码和"为什么这么写"在 topo.c。
 *
 * -------------------------------------------------------------------
 * 一、拓扑排序到底在解决什么问题？
 * -------------------------------------------------------------------
 * 有些任务天生有先后：**必须先做完 A，才能做 B**。
 * 把它画成有向图（A ──► B 读作"B 依赖 A / A 做完才能做 B"），
 * 拓扑排序就是要吐出一个顶点序列，使得：
 *
 *     **只要图里有边 u ──► v，那么 u 在序列里必须排在 v 前面。**
 *
 * 注意它排的**不是大小**，是"先后"。它不管谁先谁后都行的那部分，
 * 只要不违反任何一条边就合格 —— 所以：
 *   ★ 拓扑序通常**不唯一**（这一节第 3 幕会同一张图跑出两个不同答案，都合法）。
 *   ★ **有环的图根本没有拓扑序**（A 等 B、B 等 C、C 等 A，谁也开不了头）。
 *     于是"能不能排出一个完整序列"就等价于"图里有没有环"：
 *     **拓扑排序存在 ⇔ 图是 DAG（有向无环图）**。这句话说两遍都不过分。
 *
 * -------------------------------------------------------------------
 * 二、本节讲两种算法（互为表里，都要会）
 * -------------------------------------------------------------------
 * 【方法 A：Kahn 入度法】—— 就是"入度为 0 的 BFS"
 *   第 07-graph/bfs 那节的骨架原封不动，只是把"判断条件"换掉了：
 *
 *        BFS:                      拓扑(Kahn):
 *        起点入队                  所有 indeg==0 的顶点入队   ← 注意是"所有"
 *        while 队列非空:           while 队列非空:
 *          u = 出队                  u = 出队，把 u 写进结果表
 *          for u 的邻居 v:           for u 的邻居 v:
 *            if v 没访问过:            indeg[v]--              ← u 这条"债"还清了
 *              标记 v，入队            if indeg[v] == 0: 入队   ← 债还清才轮得到它
 *
 *   共同点：**都是"入队那一刻就把这个点定下来"**，靠容器（队列）一圈圈往外推。
 *   不同点：BFS 用"有没有被碰过"当资格，Kahn 用"入度有没有清零"当资格。
 *   附带好处：跑完看"输出个数 == 顶点总数？"，不相等就说明有环（详见第四点）。
 *
 * 【方法 B：DFS 后序逆序法】
 *   DFS 走到无路可走时（这个点的所有邻居都已经收摊）才把这个点记下来 ——
 *   这个"收尾时才记"的顺序叫**后序**。后序表**整个反转**就是拓扑序。
 *   为什么反过来？因为后序保证"我比我的所有下游**晚**被记录"，
 *   而拓扑序要求"我比我的所有下游**早**被排出"，正好差一个倒放。
 *
 * -------------------------------------------------------------------
 * 三、"用队列还是用栈"不影响正确性，只影响顺序（本节第 3 幕的实测主题）
 * -------------------------------------------------------------------
 * Kahn 的规矩只有一条：**入度清零才能上场**。至于同时有好几个点入度为 0 时
 * 先取哪一个，算法完全没规定。所以：
 *     容器用 FIFO（队列）→ 得到一份拓扑序
 *     容器用 LIFO（栈）  → 得到另一份拓扑序
 * 两份**都合法**，只是把"同层候选"的相对顺序排成了不同样子。
 * 这一点必须在代码里实测给你看（topo_kahn 的第 2 个参数 fifo：1 队列 / 0 栈），
 * 因为"拓扑序不唯一"是这一节最容易被误解、也最能体现算法自由度的地方。
 *
 * -------------------------------------------------------------------
 * 四、判环：两种方法各自怎么发现"这图有环"
 * -------------------------------------------------------------------
 * Kahn 版：**跑完之后输出个数 < 顶点总数**即为有环。
 *   环上的点互相卡着 —— 每个点的入度都至少被环里那条边占住 1，
 *   谁先都得不来"入度 0"，于是整批人永远进不了容器。
 *   ⚠ 剩下的那批点里，**坐在环上的**和**只是环的下游被连累的**混在一起，
 *     topo_report_stuck() 会把两类分开列出来（这是第 4 幕的看点）。
 *
 * DFS 三色版：白=还没碰过，灰=正在我的调用栈上（邻居还没走完），黑=收摊了。
 *   DFS 过程中如果某条边指向一个**灰色**顶点，说明"我绕回了还在栈上的自己人"
 *   —— 这条边就叫**回边（back edge）**，发现回边 = 有环。
 *   （指向黑色顶点是安全的：那是已经处理完的旁支，不是环。）
 *
 * -------------------------------------------------------------------
 * 五、本节的图怎么存？
 * -------------------------------------------------------------------
 * 用**有向邻接表**（呼应 07-graph/adjacency-list）：
 *   heads[i] 是顶点 i 的**出边**链表，节点是 `struct ENode { int dest; next; }`。
 *   为什么要出边而不是无向？因为拓扑排序只对**有向**图有意义，
 *     "A→B" 和 "B→A" 是两个完全不同的约束，无向边等于同时提了两个互相矛盾的约束
 *     （任何一条无向边都会立刻构成 2-环），所以**无向图谈不上拓扑排序**。
 *   有向图一条边只挂 **1 个节点**（无向图要挂 2 个），所以节点总数 == e。
 *   用**尾插**：邻居顺序 == 加边顺序，输出可复现，才能和 README 逐行核对。
 *
 *   代价与收益：邻接表版 Kahn/DFS 都是 **O(V+E)**（每个点出队一次、每条边看一次）。
 *     矩阵版要 O(V²)，大图上必须用邻接表 —— 这里就特意用邻接表写，
 *     好让复杂度那张表不是空口白话。
 *
 * -------------------------------------------------------------------
 * 六、内存与容量约定
 * -------------------------------------------------------------------
 * TOPO_MAX_V 是本节示例图的顶点上限（各示例图都 ≤ 8，留到 16 宽裕）。
 * topo_create() 会 malloc；**用完必须 topo_free()**，否则 ASan 会报泄漏。
 * 元素类型全部是 int：顶点编号天生就是 int，这里**不需要** void * 泛型，
 * 也不需要函数指针比较器（拓扑序不比较大小，只尊重边的方向）。
 */

/* 本节示例顶点上限；所有 order[]/indeg[] 都按这个尺寸开 */
#define TOPO_MAX_V 16

/* DFS 三色标记：用 int 常量而不是 enum，方便直接和打印出来的字符对照 */
#define TOPO_WHITE 0   /* 还没碰过 */
#define TOPO_GRAY  1   /* 在当前 DFS 调用栈上：邻居还没走完 */
#define TOPO_BLACK 2   /* 收摊：所有邻居都已处理完（后序在这一刻记录） */

/*
 * 有向边节点：一个顶点的一条出边。
 * ⚠ `struct ENode *next` 必须带 struct 关键字 —— 此刻 typedef 还没完成。
 */
typedef struct ENode {
    int dest;                 /* 这条出边的终点：我只能去往 dest */
    struct ENode *next;       /* 同一起点的下一条出边 */
} ENode;

/*
 * 有向图：
 *   heads —— V 条链表头指针的数组（malloc 来的，topo_free 负责全部释放）
 *   v     —— 顶点数（顶点编号固定为 0..v-1）
 *   e     —— 有向边条数（有向图一条边只挂一个节点，所以链表节点总数 == e）
 */
typedef struct {
    ENode **heads;
    int v;
    int e;
} TopoGraph;

/* ---------- 1. 建图 / 收摊（本节唯一的 malloc/free 责任田）---------- */
TopoGraph *topo_create(int v);                        /* v 非法或超上限返回 NULL；调用者负责 topo_free */
void       topo_free(TopoGraph *g);                   /* 逐条链 free 边节点，再 free 数组、再 free 图；传 NULL 安全 */
int        topo_add_edge(TopoGraph *g, int from, int to);  /* 有向边 from→to（to 依赖 from）；非法/越界返回 0 */

/* ---------- 2. 看清这张图 ---------- */
void topo_print(const TopoGraph *g);                  /* 打成 `0 -> 1 -> 2 -> NULL` 并附每点入度 */
void topo_indeg(const TopoGraph *g, int indeg_out[]); /* 现场重算入度表（Kahn 内部也这么算，这里给外面看） */

/* ---------- 3. 方法 A：Kahn 入度法（BFS 型）---------- */
/*
 * fifo   ：1 用队列（BFS 脾气，先入容器先出）；0 用栈（DFS 脾气，后入先出）。
 *          两者都产出合法拓扑序，只是顺序不同 —— 第 3 幕就是拿这个参数做对照实验。
 * verbose：非 0 就一步一打：容器现状 + 全部顶点的入度表 + 这一步减了哪几条入度。
 * 返回值：真正排出的顶点个数（写进 order_out 前若干格）。
 *          == g->v → 无环；< g->v → 有环，剩下的都卡在环里。
 * stuck_out / stuck_len_out：可为 NULL。非空时把"卡住的顶点"列出来（第 4 幕用）。
 */
int topo_kahn(const TopoGraph *g, int fifo, int verbose,
              int order_out[], int stuck_out[], int *stuck_len_out);

/* ---------- 4. 卡住的顶点里，谁真的坐在环上？---------- */
void topo_report_stuck(const TopoGraph *g, const int stuck[], int stuck_len);

/* ---------- 5. 方法 B：DFS 后序逆序法 ---------- */
/*
 * 不带环检测：老老实实做 DFS，只在"邻居全处理完"时记录（后序）。
 * 返回访问到的顶点数；后序表在 post_out 里，反转后才是拓扑序（用 topo_reverse）。
 */
int topo_dfs_postorder(const TopoGraph *g, int verbose, int post_out[], int *post_len_out);

/*
 * 三色标记版：同一个 DFS 顺手抓回边。
 * 返回值 1 = 发现回边（有环，此时 post_out 只填了一半，拓扑序无意义）；0 = 无环。
 */
int topo_dfs_color(const TopoGraph *g, int verbose, int post_out[], int *post_len_out);

/* ---------- 6. 工具 ---------- */
void topo_reverse(const int in[], int n, int out[]);  /* 后序表整个倒过来 —— 这一步绝不能省 */
int  topo_order_is_valid(const TopoGraph *g, const int order[], int len);  /* 逐条边验收：1 合法 / 0 违规 */
void topo_print_order(const char *label, const int order[], int len);      /* 打一行结果序列 */

/* ---------- 7. 本节示例图（前两种是教学主线，其余在 main.c 里现搭）---------- */
TopoGraph *topo_graph_dag(void);      /* 6 点演示 DAG：故意让"同层候选"出现，好做 FIFO/LIFO 对照 */
TopoGraph *topo_graph_cycle(void);    /* 7 点带环图：1→2→3→1 的环 + 干净分量 5→6 + 被连累的 4 */

#endif /* TOPO_H */
