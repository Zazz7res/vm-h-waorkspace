#ifndef GDFS_H
#define GDFS_H

/*
 * ===================================================================
 * 深度优先搜索 DFS (Depth-First Search) —— 这一节的"菜单"
 * ===================================================================
 * 这个文件里【只有声明】。真正的代码在 gdfs.c。
 *
 * -------------------------------------------------------------------
 * 一、DFS 一句话：一条路走到黑，走不通再退回来
 * -------------------------------------------------------------------
 * 把 BFS 想成"往水里丢石头的波纹"，那 DFS 就是"蒙着眼走迷宫、右手扶墙"：
 *     站到一个点上，先随便挑一个还没去过的邻居，冲过去；
 *     到了新点再挑一个邻居，再冲过去；
 *     一直冲到"所有邻居都去过了"为止 —— 然后**退回一步**，
 *     看看退回来的这个点还有没有别的邻居没试；有就再冲，没有就再退一步。
 *
 *     BFS：0 1 2 3   （一圈一圈，先近后远）
 *     DFS：0 1 2 3   但这四个数字背后的走法完全不同 ——
 *         BFS 是"0 的朋友 1、2 一起收，然后再收 3"
 *         DFS 是"0 → 1 → 2 → 3 一口气钻到底，撞墙了才回头"
 *
 * 两种遍历的代码差别只有一行：**待办用队列还是用栈**。
 * 队列 = 最早排队的先处理（BFS）；栈 = 最新发现的先处理（DFS）。
 * 一行差别，换来的是完全不同的行为和应用场景。
 *
 * -------------------------------------------------------------------
 * 二、为什么"标记已访问"在 DFS 里比在 BFS 里更要命
 * -------------------------------------------------------------------
 * 图不是树：图里有**环**。示例图 G 里 0-1-2-0 就是一个三角环。
 * 如果不记"我来过哪儿"，从 0 出发会走成
 *     0 → 1 → 2 → 0 → 1 → 2 → 0 → ...
 * 永远走不到头。递归版就是无限套娃，函数调用栈一直长，
 * 最后不是"死循环"而是**爆栈（段错误）**，程序直接没了。
 * 所以 DFS 的骨架里必须有一个 visited[]，而且每次进入顶点的第一件事就是打标记。
 *
 * 顺带一个反直觉的点：**DFS 的"标记"时机比 BFS 自由。**
 * 递归版是"进入即标记"（进函数就标），这是天然正确的；
 * 而用显式栈写"朴素版"时，标记打在"入栈时"还是"出栈时"，
 * 会得到**不一样的访问顺序和不一样的 DFS 树** —— 第五节详细说，代码里两版都给了。
 *
 * -------------------------------------------------------------------
 * 三、递归就是系统在帮你维护栈（本节主线，务必亲眼看到）
 * -------------------------------------------------------------------
 * 很多教材说"DFS 的递归版可以换成用栈手写"，但没说清"换"在哪。
 * 其实递归程序里**一直有一个栈**，只是它藏在编译器/运行时手里，你没看见：
 * 每次调用一个函数，系统就在调用栈上压一个**栈帧**，里面装着
 * 这一层独有的局部变量（u、depth、循环变量 j、parent 等）；
 * 函数返回时把这个帧弹掉。
 *
 *     dfs_go(3)  ← 栈顶：j 扫到 2，发现是父亲，扫完了 → return
 *     dfs_go(2)  ← j 停在 4（3 之后），3 回来之后我还要继续扫
 *     dfs_go(1)  ← j 停在 3（2 之后）
 *     dfs_go(0)  ← 栈底：j 停在 2（1 之后）
 *     ─────────  系统调用栈（越往下越早进入）
 *
 * 关键观察：**每个帧各自记着"我扫到第几个邻居了"。**
 * 递归从 dfs_go(3) 返回到 dfs_go(2) 时，2 的那层 for 循环
 * 是从上次停下的地方接着走的 —— 这件事是系统自动做到的。
 * 所以我们手写栈时，光存"顶点"不够，必须存**（顶点，下次该从哪个邻居接着看）**，
 * 这一对就叫"帧"。gdfs.c 里的 `dfs_stack_frames` 就是这么写的，
 * 它的访问顺序和递归版**逐个字符一模一样** —— 这就是"递归 = 系统帮你维护栈"的证据。
 *
 * 那"朴素栈版"（一发现邻居就全压进去）为什么也很多人写？
 * 因为它代码最短。但它只存了顶点、没存"扫到哪儿了"，
 * 所以它模拟的其实是"回溯时不关帧、但把兄弟全提前压好"的另一套流程：
 *     ① 压栈顺序会让邻居的**处理先后反过来**（栈是后进先出）；
 *     ② 一个点被多个点同时"抢先预约"时，parent 会被后写的那个覆盖 ——
 *        前序可能恰好相同，但 DFS 树的形状可以不同。
 * 这两版都在代码里，跑一遍就能把差别看清楚。
 *
 * -------------------------------------------------------------------
 * 四、DFS 独有的三张表：前序、后序、进出时间戳
 * -------------------------------------------------------------------
 * BFS 只有一张"访问顺序"表。DFS 多两张，因为 DFS 每个顶点被"经过"两次：
 *     **进入**它的那一刻（前序，preorder）
 *     **离开**它的那一刻（后序，postorder）—— 意思是"它连同它下面整棵子树全办完了"
 *
 *     前序 = 你签到进场的时间；后序 = 你签退离场的时间。
 *
 * 代码里用一个全局时钟 `clock` 计数：进入时 tick_in[u]=++clock，离开时 tick_out[u]=++clock。
 * 这两个值有个很有用的性质（叫"括号定理"）：
 *     v 在 u 的子树里  ⟺  tick_in[u] < tick_in[v] ≤ tick_out[v] < tick_out[u]
 * 判"谁是谁的祖先"、算 LCA、做子树区间查询都靠它。
 *
 * 后序还有个大用途：**把后序倒过来就是拓扑序**（只对无环的有向图成立）。
 * 下一节 `topological-sort/` 的 DFS 写法就是这么干的，本节先把后序打出来混个脸熟。
 *
 * -------------------------------------------------------------------
 * 五、邻居顺序必须固定，否则输出没法核对
 * -------------------------------------------------------------------
 * DFS 的结果**依赖邻居的遍历顺序**：同一个起点，先试 1 还是先试 2，
 * 会得到两条完全不同的深钻路径。这不是 bug，是 DFS 的本性（它的解一般不唯一）。
 * 为了让这一节的输出可以逐个字符和 README 对照，全节统一规矩：
 *     **邻接矩阵第 u 行，按列号 j = 0,1,2,...,v-1 升序扫，跳过 0 和 j==u。**
 * 代码里所有"扫邻居"都严格照这个顺序，一次例外都没有。
 * （邻接表版会把链表顺序带进来，插头的写法会让顺序反过来 ——
 *   见 `07-graph/adjacency-list/` 那一节里的 `glist_add_edge_front` 演示。）
 *
 * -------------------------------------------------------------------
 * 六、用哪张图？和 BFS 完全同一张，方便直接对比两者
 * -------------------------------------------------------------------
 * 共用无向图 G（8 个顶点 0..7，故意不连通）：
 *
 *        0 ───── 1                     4 ───── 5
 *         \     / \                     \     /
 *          \   /   \                     \   /
 *           2 ──────                     6          7 ← 孤零零
 *            \
 *             3
 *
 *   边 7 条：(0,1) (1,2) (0,2) (2,3) (4,5) (5,6) (4,6)
 *
 * 这张图在本节专门准备了一个"对比杀器"：**顶点 3**
 *     BFS 从 0 出发：dist[3] = 2（走 0→2→3，两步，这是真正的最短）
 *     DFS 从 0 出发：先钻 0→1→2→3，depth[3] = 3（三步）
 * 也就是说 **DFS 的 depth 绝不是最短距离**，它是"我这次运气走到"的深度。
 * 这是本节和上一节最重要的一次互相印证，代码里会把两张表并排打出来。
 *
 * -------------------------------------------------------------------
 * 七、为什么本节的图又用邻接矩阵（而不是刚学的邻接表）
 * -------------------------------------------------------------------
 * 叶子目录必须自包含，本节不想把邻接表那套 malloc/free 再抄一遍；
 * 矩阵一个栈上二维数组就够，全部注意力留给"遍历"本身。
 * 而且矩阵第 u 行天生是升序扫描，正好满足第五节"顺序必须固定"的要求。
 * 代价诚实记账：矩阵版 DFS 是 **O(V²)**（每个点扫一整行），
 * 邻接表版是 **O(V+E)**。V=8 无所谓，大图必须换邻接表。
 *
 * -------------------------------------------------------------------
 * 八、那到底该用递归版还是显式栈版？
 * -------------------------------------------------------------------
 *     递归版：代码 10 行、意图最清楚、还要维护"扫到第几个邻居"这件事完全免费。
 *              **首选。** 面试、写算法、图不太深时都用它。
 *     显式栈版：当图的**最深路径可能上万**时（一百万个点的链状图，
 *              递归深度就是一百万层帧，每层几十字节 → 几百 MB，必爆栈）。
 *              竞赛/工程里给栈设了小限额、或者要跑超深图，就换成手写帧栈。
 *     朴素栈版：代码最短，但要清楚它给出的 parent 树和前序**不保证**和递归版一致，
 *              需要后序（拓扑排序）、需要精确复刻递归行为的地方**不能**用它。
 */

/* 本节示例最多 8 个顶点 */
#define GDFS_MAX_V 8

/*
 * 图的容器：无权无向邻接矩阵。
 * 和 adjacency-matrix / bfs 那两节同构，但**在本目录独立声明**（叶子目录互不引用）。
 */
typedef struct {
    int edge[GDFS_MAX_V][GDFS_MAX_V];
    int v;
    int e;
} DfsGraph;

/*
 * 一次 DFS 的全部产出，打包成一个结构。
 *
 * 为什么打包？DFS 的产出比 BFS 多：前序、后序、父亲、深度、进/出时间戳，
 * 再加一个过程中的"当前路径"。要是全用出参传，函数签名会变成七个参数，
 * 读起来就是一道错题。用一个小结构收口，调用方只写 `DfsResult r;` 一次。
 *
 * 约定：所有按顶点索引的数组（parent/depth/tick_in/tick_out），
 *       **没被访问到的顶点一律填 -1**。因为 0 是一个合法值（起点深度就是 0、
 *       起点时间戳也是 1），只有 -1 是"天然不可能出现"的记号 ——
 *       和邻接矩阵用 -1 表示"无边"是同一个套路。
 */
typedef struct {
    /* ---- 前序：进入顶点那一刻记录的顺序 ---- */
    int order[GDFS_MAX_V];
    int order_len;

    /* ---- 后序：离开顶点那一刻（它和它整棵子树都办完了）记录的顺序 ---- */
    int post[GDFS_MAX_V];
    int post_len;

    /* ---- 每个顶点的过程记录，按顶点号索引 ---- */
    int parent[GDFS_MAX_V];   /* 我是被谁"钻"进来的；-1 = 起点或没访问到 */
    int depth[GDFS_MAX_V];    /* 我在 DFS 树里第几层。⚠ 不是最短距离！ */
    int tick_in[GDFS_MAX_V];  /* 进入的时间刻度 */
    int tick_out[GDFS_MAX_V]; /* 离开的时间刻度 */

    /* ---- 只在遍历"进行中"有意义：此刻栈上从根到当前点的路径 ---- */
    int trail[GDFS_MAX_V];
    int trail_len;

    /* ---- 朴素栈版专用小计数器：弹出来发现"已经访问过了"的次数。
     *      它不为 0 就说明同一个点被重复压栈了 —— 一个很直观的体检指标。
     *      递归版 / 帧模拟版永远是 0（因为它们在入栈前就查过标记）。 ---- */
    int dup_pops;

    /* ---- 内部计数器：全局时钟，进入和离开各占一格 ---- */
    int clock;
} DfsResult;

/* ---------- 1. 造图 ---------- */
void dfs_graph_sample(DfsGraph *g);        /* 造出共用的示例图 G（8 点 7 边，不连通） */
void dfs_graph_print(const DfsGraph *g);   /* 打出邻接矩阵，顺便列出每个点的邻居顺序 */

/* ---------- 2. 三种写法：同一个起点，各自跑一遍 ----------
 * 三个函数返回值都是"这一次真正访问到的顶点个数"。
 * 参数 verbose 非 0 就边跑边打印过程（缩进表示深度）。
 */

/* 递归版：最自然的写法，"栈"藏在系统的函数调用栈里 */
int dfs_recursive(const DfsGraph *g, int start, DfsResult *r, int verbose);

/* 显式栈·帧模拟版：自己压"（顶点，下次从哪个邻居接着看）"，
 * 行为和递归版**逐字符等价**（前序、后序、parent、depth 全一样）。
 * 这一版就是"递归就是系统在帮你维护栈"的可执行证据。 */
int dfs_stack_frames(const DfsGraph *g, int start, DfsResult *r, int verbose);

/* 显式栈·朴素版（教科书最短写法）：弹一个点，把它所有没见过的邻居一次全压进去。
 * 两个开关互相独立，组合出 4 种跑法，main.c 里各演一遍：
 *   push_ascending 非 0 → 按 j 升序压栈 → 邻居**处理顺序反过来**（降序）；
 *                        为 0 → 按 j 降序压栈 → 前序在这张图上与递归版相同。
 *   mark_on_pop 为 0    → 入栈即标记（推荐：每个点最多进栈一次，dup_pops 恒为 0）；
 *                        非 0 → 出栈才标记（演示用的"危险写法"，同一个点会被重复压栈，
 *                               parent 会被最后一个压它的人覆盖，dup_pops 会告诉你重复了几次）。
 * ⚠ 这一版**没有"离开"这一刻**，所以 post[] 是空的、tick_out[] 全 -1。
 *   需要后序的场合（拓扑排序等）必须用递归版或帧模拟版。
 * 详见 gdfs.c 里这个函数上方那一大段"为什么两版会有细微差别"。 */
int dfs_stack_naive(const DfsGraph *g, int start, int push_ascending, int mark_on_pop,
                    DfsResult *r, int verbose);

/* ---------- 3. 全图 DFS：对每个还没访问过的点都起一轮 ----------
 * 和 BFS 那节一模一样的教训：图可能有好几个连通分量，起一次只覆盖一个。
 * 外层依次看每个顶点，只要还没访问过，就以它为根再起一轮 DFS。
 * 返回值：一共起了几轮（== 连通分量的个数）。
 */
int dfs_all(const DfsGraph *g, DfsResult *r, int verbose);

/* ---------- 4. 看结果 ----------
 * 把前序 / 后序 / parent / depth / 时间戳摊成一张表，
 * 并把 DFS 的 depth 和"真·最短距离"对比，说明 DFS 深度不可当距离用。
 */
void dfs_print_result(const DfsGraph *g, const DfsResult *r);

#endif /* GDFS_H */
