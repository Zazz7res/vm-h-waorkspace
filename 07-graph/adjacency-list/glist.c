#include <stdio.h>
#include <stdlib.h>
#include "glist.h"

/*
 * ===================================================================
 * 邻接表实现。这一节的代码量比邻接矩阵大一截，原因只有一个：
 * **链表要 malloc，也要 free，还要改指针。**
 * 邻接矩阵那节一个数组走天下，这里每个邻居都是堆上一个独立小方块，
 * 你要亲手把它们串起来、拆下来、最后一个个还回去。
 *
 * 先立个规矩（也是本节最容易出事的地方）：
 *   谁 malloc，谁负责 free；什么时候 free，必须"逐顶点、逐节点"清干净。
 *   ASan 会盯着这件事，我们要求 0 泄漏。
 */

/*
 * ===================================================================
 * 0. 就地重写的极简单链表三兄弟（第 02 章的复用）
 * ===================================================================
 * 下面三个 static 函数就是"单链表"最核心的三招。写成 static 是因为
 * 它们只服务本文件，不进 .h 那份"菜单"。
 *
 * ⚠ 为什么要在这里重写一份，而不是 #include "../../02-linked-list/singly/slist.h"？
 *   因为这个仓库的 Makefile 是**按目录独立编译**的（`make one DIR=...` 只吃
 *   本目录下的 *.c），跨目录引用头文件会让这一节单独编译失败。
 *   自包含 > 复用。而且重写一遍 20 行，比记住别人的 API 更能检验你是否真会。
 */

/* 造一个节点：堆上租 16 字节，next 先置 NULL */
static Node *node_new(int dest)
{
    Node *n = malloc(sizeof(Node));   /* sizeof(Node) 而不是手写 16：换平台自动对 */
    if (n == NULL) {
        return NULL;                  /* 租不到就老实返回 NULL，让调用方决定怎么收场 */
    }
    n->dest = dest;
    n->next = NULL;                   /* ★ 新节点的 next 一定要置 NULL。
                                       *   忘了置就会指向上一次 malloc 留下的垃圾地址，
                                       *   随后遍历链表时读出野指针 —— ASan 会当场打死你，
                                       *   没 ASan 时它会安静地跑几轮再崩，最难查。 */
    return n;
}

/* 数一条链有几个节点 */
static int node_list_length(Node *head)
{
    int cnt = 0;
    for (Node *p = head; p != NULL; p = p->next) {
        cnt++;
    }
    return cnt;
}

/*
 * 在一条链的**尾部**追加节点（第 02 章的 push_back）。
 *
 * 为什么邻接表主 API 要用尾插而不是头插？
 *   头插 O(1)，但会把邻居清单**倒过来**：按 (0,1)(0,2) 的顺序加边，
 *   头插得到 `0 -> 2 -> 1`，尾插得到 `0 -> 1 -> 2`。
 *   本节为了"README 里贴的输出可复核"、并且和邻接矩阵那节的邻居清单
 *   保持一致，主 API 用尾插；头插单独留一个 add_edge_front 做对比，
 *   让你亲眼看到同一张图两种画法。
 *
 * ⚠ 尾插**保住的是"加边顺序"，不是"编号升序"**。想输出升序，
 *   要么按 glist_sample 那样把加边顺序排好，要么建完表再逐链排序。
 *   这一点在 glist_sample 的注释里有详细推导。
 *
 * 复杂度：O(链长) = O(度)，因为要先走到尾巴。
 */
static int node_push_back(Node **head, int dest)
{
    Node *fresh = node_new(dest);
    if (fresh == NULL) {
        return 0;
    }
    if (*head == NULL) {         /* 空链：新节点直接当头 */
        *head = fresh;
        return 1;
    }
    Node *tail = *head;          /* 否则走到尾巴（这就是尾插 O(度) 的代价） */
    while (tail->next != NULL) {
        tail = tail->next;
    }
    tail->next = fresh;          /* 尾巴的 next 指向新节点 */
    return 1;
}

/* 在一条链的**头部**插入节点：O(1) */
static int node_push_front(Node **head, int dest)
{
    Node *fresh = node_new(dest);
    if (fresh == NULL) {
        return 0;
    }
    fresh->next = *head;   /* ★ 顺序不能反：先让新节点抓住老头，再把头换成新节点 */
    *head = fresh;         /*   反过来的话 *head 一变，老链就整条失联（内存泄漏） */
    return 1;
}

/*
 * 从一条链里删掉第一个 dest==目标 的节点（第 02 章"按值删"的哨兵写法）。
 * 返回 1 删掉了、0 没找到。
 *
 * 为什么要用 dummy 哨兵？
 *   删头节点时，要改的是 `*head` 本身；删中间节点时，要改的是"前驱的 next"。
 *   两种情况写法不同，很容易漏一种。
 *   技巧：造一个假的前驱 dummy，让 dummy.next = *head，然后**永远只管前驱**：
 *
 *     dummy ─►[A]─►[B]─►[C]─►NULL
 *       ▲      ▲
 *       └ prev ┘        ← prev 永远站在"要删的节点"前面一格
 *
 *   要删 B 时：prev=A，`prev->next = victim->next` 就完事，头节点也走同一条路
 *   （此时 prev 就是 dummy，`dummy.next = B`，最后 `*head = dummy.next` 收尾）。
 *   于是一个循环、一套逻辑，把"删头/删中/删尾"三种情况全统一了。
 */
static int node_remove_val(Node **head, int dest)
{
    Node dummy;                     /* 栈上的假节点，不 malloc，所以也不需要 free */
    dummy.dest = -1;
    dummy.next = *head;

    Node *prev = &dummy;
    while (prev->next != NULL) {
        if (prev->next->dest == dest) {
            Node *victim = prev->next;
            prev->next = victim->next;   /* 前驱直接跨过 victim：链表接回去了 */
            free(victim);                /* ★ 先接好再 free，顺序反了就是
                                            "free 之后还在用 victim->next" = use-after-free */
            *head = dummy.next;          /* 统一写回：可能头变了（删的就是头） */
            return 1;
        }
        prev = prev->next;
    }
    *head = dummy.next;                  /* 没找到也要写回（此时值没变，但写回无害，
                                          *   这样两条路径的行为完全一致，不留特例） */
    return 0;
}

/*
 * ===================================================================
 * 1. glist_create：建一张空图
 * ===================================================================
 * 干什么： malloc 一个 GList，再 malloc 一个"能放 V 个 Node* 的数组"，
 *          把 V 个表头指针全置 NULL。
 *
 * ⚠ 这里是本节第一个关键认知：邻接表是**两级内存**。
 *
 *   第一级（一次 malloc，连续）：adj 指针数组
 *   ┌──────────┬────────┬────────┬ ... ─┐
 *   │ adj[0]=NULL│adj[1]│adj[2] │      │     每个格子是一个 Node*
 *   └──────────┴────────┴────────┴ ... ─┘        （一开始全是 NULL = 还没有邻居）
 *        ▲
 *        │ adj = 这块数组的首地址
 *        └─ 存在 g->adj 里
 *
 *   第二级（每条边各自 malloc，散落在堆上）：链表节点
 *   adj[0] ─►┌──────┬───┐─►┌──────┬───┐─►NULL
 *            │dest 1│   │  │dest 2│   │
 *            └──────┴───┘  └──────┴───┘
 *
 *   所以 free 的时候必须**倒着剥**：先剥最里面的节点，再剥数组，最后剥 GList 本身。
 *   漏剥一层就是泄漏 —— 见 glist_free。
 *
 * 为什么用 calloc 而不是 malloc + 手动置 NULL？
 *   calloc(v, sizeof(Node*)) 会把分配的内存**全部初始化为 0**，
 *   而"指针的全 0 位模式"在 C 里就是 NULL。省一个循环，也少一个漏初始化某格的 bug。
 *   （对照邻接矩阵那节：那边 int 数组必须自己清 0，因为栈上的结构体是垃圾内存；
 *     这边是堆上的指针数组，用 calloc 一步到位。）
 *
 * 边界情况：
 *   - v <= 0 或 v > GL_MAX_V：拒绝，返回 NULL。
 *   - 两次 malloc 任意一次失败：把已经拿到的那块 free 掉再返回 NULL。
 *     这个"回滚"习惯很重要 —— 只 malloc 一次时不会出问题，一旦两处 malloc，
 *     忘了回滚第一处就是**分配失败路径上的泄漏**（平时不触发，内存紧张时触发，
 *     而内存紧张时正是你最不想再漏的时候）。
 */
GList *glist_create(int v)
{
    if (v <= 0 || v > GL_MAX_V) {
        printf("      [错误] 顶点数 %d 不在 (0, %d] 范围内，建图失败\n", v, GL_MAX_V);
        return NULL;
    }

    GList *g = malloc(sizeof(GList));
    if (g == NULL) {
        printf("      [错误] 申请 GList 失败\n");
        return NULL;
    }

    g->adj = calloc((size_t)v, sizeof(Node *));   /* 注意 (size_t)v：把 int 提升成无符号再乘 */
    if (g->adj == NULL) {
        printf("      [错误] 申请 %d 个表头指针失败\n", v);
        free(g);          /* ★ 回滚：把已经拿到的 GList 还回去 */
        g = NULL;         /*     free 完立刻置 NULL，防止后面误用 */
        return NULL;
    }

    g->v = v;
    g->e = 0;
    /* 此刻每条链都是空的：adj[0]..adj[v-1] 全是 NULL，这就是"孤立点"的样子 */
    return g;
}

/*
 * ===================================================================
 * 2. glist_free：逐顶点剥干净（本节的 ASan 考点）
 * ===================================================================
 * 干什么：把图彻底还回系统，0 泄漏。
 *
 * 三层结构对应三次释放，**顺序不能乱**：
 *
 *   第 1 层：每条链的节点。必须先 free 掉，因为 free 完 adj 数组之后，
 *            你就再也找不到这些节点的地址了 —— 找不到的堆内存 = 永久泄漏。
 *            而且单条链也要"先记下 next 再 free 当前"，三步走：
 *
 *                步骤1：nxt = cur->next   先把下一格的地址抄下来
 *                步骤2：free(cur)         再还掉当前（此后 cur->next 是垃圾）
 *                步骤3：cur = nxt         跳到刚才抄下来的那一格
 *
 *            ⚠ 如果写成先 free(cur) 再 cur = cur->next —— 这是 **use-after-free**：
 *              cur 已经被还掉了，还去读它的字段。ASan 会直接报
 *              "heap-use-after-free" 并打死程序。这是链表第一大坑。
 *
 *            （顺带一个 C 语言冷知识：上面这三行我一开始写成了带行注释的真代码，
 *              结果整段大注释当场"断裂"、编译不过 —— 因为 **C 的块注释不能嵌套**：
 *              注释内部再出现一次"星号加斜杠"，就会把外层注释提前关掉，
 *              剩下的注释文字就被当成代码去编译了。
 *              所以往大段块注释里贴代码，一律用纯文本编号，别写行注释符号。
 *              这个坑我替你踩过了，别再踩第二遍。）
 *
 *   第 2 层：adj 指针数组本身（calloc 出来的那一块）。
 *   第 3 层：GList 结构体本身（malloc 出来的那一块）。
 *
 * 好习惯：全部 free 完把 g 置 NULL。调用者拿到的指针虽然是个拷贝，
 * 但我们内部先置空，至少保证同一个函数里不会再误用。
 */
void glist_free(GList *g)
{
    if (g == NULL) {
        return;                       /* free(NULL) 合法，空操作 */
    }
    if (g->adj != NULL) {
        for (int i = 0; i < g->v; i++) {          /* 逐顶点 */
            Node *cur = g->adj[i];
            while (cur != NULL) {                  /* 逐节点 */
                Node *nxt = cur->next;             /* 先抄下一格地址 */
                free(cur);                         /* 再还当前 */
                cur = nxt;
            }
            g->adj[i] = NULL;                      /* 表头也置空，避免"看着还在其实已悬空" */
        }
        free(g->adj);
        g->adj = NULL;
    }
    g->v = 0;
    g->e = 0;
    free(g);
    /* g 现在是悬空指针；调用者那边记得也置 NULL */
}

/*
 * ===================================================================
 * 3. glist_add_edge：加一条无向边（尾插版）
 * ===================================================================
 * 干什么：往 a 的链尾挂一个 dest=b 的节点，往 b 的链尾挂一个 dest=a 的节点。
 *
 * 一步步：
 *   1) 判空、判越界（a/b 必须在 [0, v) 内）
 *   2) 判自环（本节禁止）
 *   3) 判重复加边 —— 用 glist_has_edge 顺着链找一遍（O(度)）
 *   4) 两次尾插；**任何一次失败都要回滚另一次**，否则图会"半连通"：
 *      a 的链里有 b、b 的链里没有 a。这种不对称状态会让后面的遍历
 *      从不同起点得出不同结论，比崩溃更难诊断。
 *   5) 两次都成功，才 e++
 *
 * 边界情况：
 *   - 平行边：本实现**拒绝**。注意这跟矩阵不同 —— 邻接表**技术上能**表达平行边
 *     （同一条链上挂两个 dest 相同的节点），只是我们这里主动拦掉，
 *     因为示例图是无向简单图。想支持重边（比如多班次的航班），
 *     把第 3 步删掉即可，那时"边数 e"要按节点数/2 重新定义。
 *   - malloc 失败：返回 0，且图保持原样（靠第 4 步的回滚保证）。
 */
int glist_add_edge(GList *g, int a, int b)
{
    if (g == NULL || g->adj == NULL) {
        return 0;
    }
    if (a < 0 || a >= g->v || b < 0 || b >= g->v) {
        printf("      [错误] 边 (%d,%d) 有顶点越界，合法编号 0..%d\n", a, b, g->v - 1);
        return 0;
    }
    if (a == b) {
        printf("      [忽略] 边 (%d,%d) 是自环，本节不存\n", a, b);
        return 0;
    }
    if (glist_has_edge(g, a, b)) {
        return 0;   /* 已有这条边：幂等，什么都不改 */
    }

    if (!node_push_back(&g->adj[a], b)) {   /* &g->adj[a]：把"表头指针这个变量"的地址交出去，
                                             *   因为头插/换头要改的就是这个变量本身。
                                             *   00-c-foundation 那条铁律又来了：
                                             *   想改外面的指针，就得传指针的地址（二级指针）。 */
        return 0;
    }
    if (!node_push_back(&g->adj[b], a)) {
        node_remove_val(&g->adj[a], b);    /* ★ 回滚：第二次失败了，把第一次挂上那个摘掉，
                                            *   否则图就"单向连通"，成了不一致状态 */
        return 0;
    }
    g->e++;
    return 1;
}

/*
 * ===================================================================
 * 4. glist_add_edge_front：同一件事的头插版（O(1)）
 * ===================================================================
 * 干什么：跟上面一模一样，只是两次都用头插。
 * 存在的意义是让你**跑出来对比**：同一张图，尾插得到 `0 -> 1 -> 2 -> NULL`，
 * 头插得到 `0 -> 2 -> 1 -> NULL`。
 *
 * 这个差别在算法上通常无所谓（集合 {1,2} 就是 {2,1}），
 * 但有两个真实影响，值得记住：
 *   1) 输出顺序变了 → 你没法复现 README 里的结果，也没法逐行核对。
 *   2) BFS/DFS 的**访问顺序**会变。顺序不影响正确性（访问到的点集合一样、
 *      距离一样），但影响"先看到谁"，所以教材里一律固定邻居顺序，
 *      让画面可复现。
 * 头插的真正价值是 O(1)：不用走到尾巴。建大图时 E 次尾插的总代价是
 * O(sum of degree) = O(E × 平均度)，图很密时会明显变慢。
 */
int glist_add_edge_front(GList *g, int a, int b)
{
    if (g == NULL || g->adj == NULL) {
        return 0;
    }
    if (a < 0 || a >= g->v || b < 0 || b >= g->v) {
        printf("      [错误] 边 (%d,%d) 有顶点越界\n", a, b);
        return 0;
    }
    if (a == b) {
        printf("      [忽略] 边 (%d,%d) 是自环，本节不存\n", a, b);
        return 0;
    }
    if (glist_has_edge(g, a, b)) {
        return 0;
    }
    if (!node_push_front(&g->adj[a], b)) {
        return 0;
    }
    if (!node_push_front(&g->adj[b], a)) {
        node_remove_val(&g->adj[a], b);    /* 同样要回滚 */
        return 0;
    }
    g->e++;
    return 1;
}

/*
 * ===================================================================
 * 5. glist_has_edge：判边 —— 邻接表的短板项
 * ===================================================================
 * 干什么：问"a 和 b 之间有没有边"。
 *
 * 一步步：顺着 adj[a] 这条链一格一格走，比较每个节点的 dest 是不是 b；
 *         走到 NULL 就说明没有。
 *
 * 复杂度对比（这是本节最该记住的一行）：
 *     邻接矩阵：O(1)      —— 位置算得出来
 *     邻接表：  O(度(a))  —— 位置算不出来，只能一格一格问
 *   最坏情况 a 连着所有点，退化成 O(V)。
 *   所以：**算法核心是"反复判边"的（Floyd 那种三重循环），
 *   千万别用邻接表**，会把 O(V³) 拖成 O(V⁴)。
 *   反过来，算法核心是"走邻居"的（BFS/DFS/连通分量），邻接表完胜。
 *
 * 边界情况：越界返回 0，不碰内存。
 */
int glist_has_edge(const GList *g, int a, int b)
{
    if (g == NULL || g->adj == NULL) {
        return 0;
    }
    if (a < 0 || a >= g->v || b < 0 || b >= g->v) {
        return 0;
    }
    for (const Node *p = g->adj[a]; p != NULL; p = p->next) {
        if (p->dest == b) {
            return 1;
        }
    }
    return 0;
}

/*
 * ===================================================================
 * 6. glist_degree：查度
 * ===================================================================
 * 干什么：数 adj[u] 那条链有几个节点。
 *
 *     无向图：度 = 链长
 *     有向图：这条链的长度 = **出度**（它指向谁）；
 *             入度在邻接表里**很难算** —— 得把全图所有链扫一遍看谁挂着 u，O(V+E)。
 *             这就是拓扑排序要用邻接矩阵（或者额外维护 indegree[] 数组）的原因之一，
 *             也是"逆邻接表"（把边反向再建一张表）存在的理由。
 *
 * 复杂度：O(度)。比矩阵的 O(V) 好（因为链上只有真的邻居，没有一堆 0）。
 *
 * 边界情况：u 越界返回 0。
 */
int glist_degree(const GList *g, int u)
{
    if (g == NULL || g->adj == NULL || u < 0 || u >= g->v) {
        return 0;
    }
    return node_list_length(g->adj[u]);
}

/*
 * 全图链表节点总数。用来验证一条等式：
 *     节点总数 == 2 × 无向边数
 * （每条无向边在两端各挂一个节点。）不等就说明某条边只挂了一边 ——
 * 等价于邻接矩阵那节"漏了对称那一格"的 bug，只是这里得靠数节点发现。
 */
int glist_node_count(const GList *g)
{
    if (g == NULL || g->adj == NULL) {
        return 0;
    }
    int total = 0;
    for (int i = 0; i < g->v; i++) {
        total += node_list_length(g->adj[i]);
    }
    return total;
}

/*
 * ===================================================================
 * 7. glist_remove_edge：删边（本节最练指针的一段）
 * ===================================================================
 * 干什么：在 a 的链里摘掉 dest==b 那个节点，在 b 的链里摘掉 dest==a 那个节点，
 *         两个都摘成功才 e--。
 *
 * 对比矩阵：矩阵删边是"涂两格"，O(1) 且没有内存管理；
 *           邻接表删边是"找前驱 → 跨接 → free → 可能还要换头"，O(度) 且有泄漏风险。
 *           这个对比跑一遍就记住了。
 *
 * 边界情况：
 *   - 链上根本没有这个邻居：node_remove_val 返回 0。
 *   - 无向图理论上两条链都会摘成功；但只要有一条失败，我们就把边数
 *     保持不变并打印警告，因为图已经是"半截"状态，宁可大声报告
 *     也不要悄悄给出一个错的 e。
 */
int glist_remove_edge(GList *g, int a, int b)
{
    if (g == NULL || g->adj == NULL) {
        return 0;
    }
    if (a < 0 || a >= g->v || b < 0 || b >= g->v) {
        printf("      [错误] 删边 (%d,%d) 有顶点越界\n", a, b);
        return 0;
    }

    int ok1 = node_remove_val(&g->adj[a], b);
    int ok2 = node_remove_val(&g->adj[b], a);

    if (ok1 && ok2) {
        g->e--;
        return 1;
    }
    if (ok1 != ok2) {
        printf("      [警告] 删边 (%d,%d) 只摘掉一边（a侧=%d b侧=%d），"
               "图已不对称，e 保持不变\n", a, b, ok1, ok2);
    }
    return 0;
}

/*
 * ===================================================================
 * 8. glist_print：打成 0 -> 1 -> 2 -> NULL
 * ===================================================================
 * 干什么：把每个顶点的邻居清单原样画出来。
 *
 * 这一屏就是邻接表的"内存画面"本身：
 *     顶点 0：[ 1 ] -> [ 2 ] -> NULL
 * 方括号里的数字就是节点的 dest，箭头就是 next。
 * 顶点 7 那一行会是 `(空)` —— 表头直接是 NULL，这就是孤立点在邻接表里的样子
 * （在矩阵里它是"一整行 0"，在邻接表里它是"一个 NULL"：更省，也更直观）。
 *
 * 顺便打印度之和 / 节点数 / 边数 三个数字，把那条等式摊在屏幕上自检。
 */
void glist_print(const GList *g)
{
    if (g == NULL || g->adj == NULL) {
        printf("    （空图）\n");
        return;
    }
    printf("    邻接表 adj[i] = 顶点 i 的邻居清单（方括号=堆上的节点，箭头=next）：\n");
    for (int i = 0; i < g->v; i++) {
        printf("    顶点 %d：", i);
        if (g->adj[i] == NULL) {
            printf("(空)  ← 孤立点，表头就是 NULL");
        } else {
            for (const Node *p = g->adj[i]; p != NULL; p = p->next) {
                printf("[ %d ] -> ", p->dest);
            }
            printf("NULL");
        }
        printf("\n");
    }
    int deg_sum = 0;
    for (int i = 0; i < g->v; i++) {
        deg_sum += glist_degree(g, i);
    }
    printf("    度之和 = %d，链表节点总数 = %d，边数 = %d，2×边数 = %d  → %s\n",
           deg_sum, glist_node_count(g), g->e, 2 * g->e,
           (deg_sum == 2 * g->e) ? "吻合 ✅" : "不吻合 ❌（某条边只挂了一边）");
}

/*
 * ===================================================================
 * 9. glist_sample：造出共用示例图 G
 * ===================================================================
 * 和 gmatrix_sample 是**同一批边**（边集完全相同），只是容器换成链表。
 * 这样你可以把两份输出并排看：
 *     矩阵第 0 行：  0 1 1 0 0 0 0 0
 *     邻接表第 0 链：[1] -> [2] -> NULL
 * 同一件事，后者把那些 0 全丢掉了 —— 这就是"稀疏图省空间"的全部秘密。
 *
 * ★ 但这里的**加边顺序**和矩阵那节不一样，是刻意重排过的，值得说一句：
 *   尾插保住的是"加边顺序"，不是"编号升序"。
 *   如果照矩阵那节的顺序 (0,1)(1,2)(0,2)(2,3) 加，2 号点的链表会变成
 *       [1] -> [0] -> [3]        ← 1 先挂上，0 后挂上，不是升序
 *   输出就乱了，也和后几节（矩阵按 j 从 0 到 V-1 扫，天生升序）对不上。
 *   所以本节把同一批边重排成：
 *       (0,1)(0,2)(1,2)(2,3)(4,5)(4,6)(5,6)
 *   排完检查每个顶点的链表，全部自动升序：
 *       0:[1,2]  1:[0,2]  2:[0,1,3]  3:[2]  4:[5,6]  5:[4,6]  6:[4,5]  7:[]
 *   （规律：对每个顶点 u，它的所有边里"指向比 u 小的邻居"的那条要最早加。
 *     比如 2 需要 0 在 1 前面 → (0,2) 要在 (1,2) 前面。）
 *   真实工程里没人做这种排序，通常做法是"建完表后对每条链排序"或者干脆不在乎顺序。
 *   我们做这一步，只为了让**输出可复现、可逐行核对** —— 教学场景下顺序就是价值。
 *
 * ⚠ 返回值是 malloc 出来的 GList*，**调用者必须 glist_free**，否则泄漏。
 *   （对比邻接矩阵那节：那边是栈上的定长数组，压根不需要 free。
 *     "省空间"和"省操心"往往不能同时得到，这节就把这句话演示给你看。）
 */
GList *glist_sample(void)
{
    GList *g = glist_create(8);
    if (g == NULL) {
        return NULL;
    }
    glist_add_edge(g, 0, 1);
    glist_add_edge(g, 0, 2);
    glist_add_edge(g, 1, 2);
    glist_add_edge(g, 2, 3);
    glist_add_edge(g, 4, 5);
    glist_add_edge(g, 4, 6);
    glist_add_edge(g, 5, 6);
    /* 顶点 7 一条边都不加：孤立点 */
    return g;
}
