#ifndef GLIST_H
#define GLIST_H

/*
 * ===================================================================
 * 邻接表 adjacency-list —— 这一节的"菜单"
 * ===================================================================
 * 这个文件里【只有声明】。真正的代码和"为什么这么写"在 glist.c。
 *
 * -------------------------------------------------------------------
 * 一、邻接表到底是什么？
 * -------------------------------------------------------------------
 * **一个数组，每个格子里挂一条链表。**
 * 数组下标 = 顶点编号；第 i 条链表 = "i 的邻居清单"，一个一个串起来。
 *
 *   adj（指针数组，V 个格子）        每个格子往后拉出一条链表
 *   ┌────────┐
 *   │ adj[0] ├────►┌──────┬───┐   ┌──────┬───┐
 *   └────────┘     │dest 1│nex┼──►│dest 2│nex┼──►NULL
 *                  └──────┴───┘   └──────┴───┘
 *   ┌────────┐
 *   │ adj[1] ├────►┌──────┬───┐   ┌──────┬───┐
 *   └────────┘     │dest 0│nex┼──►│dest 2│nex┼──►NULL
 *                  └──────┴───┘   └──────┴───┘
 *   ...
 *   ┌────────┐
 *   │ adj[7] ├────►NULL            ← 孤立点：这一格就是 NULL，一条链都没有
 *   └────────┘
 *
 * 读法两句：
 *   - **看一条链** = 看"这个点的邻居清单" → 走几个节点就是几个邻居，
 *     遍历邻居是 O(度)，不像矩阵要扫一整行 V 格（多数是 0）。
 *   - **判两点有没有边** = 顺着 a 那条链一格一格找 dest==b → O(度)（这是它的短板）。
 *
 * 一句话记忆：**邻接矩阵是"摊平的表"，邻接表是"一串小方块"。
 *              前者用空间换判边速度，后者用指针换遍历速度和空间。**
 *
 * -------------------------------------------------------------------
 * 二、这里就是在复用第 02 章的单链表
 * -------------------------------------------------------------------
 * 每个节点是 `struct Node { int dest; struct Node *next; }` ——
 * 和 02-linked-list/singly 里的节点只差一个字段名（那边叫 val，这边叫 dest，
 * 因为这里存的不是"值"而是"邻居的编号"）。
 * 本节需要的链表操作（造节点、数长度、按值删、整条释放）都在
 * glist.c 里**就地重写了一份极简版**（每个 10~20 行）：
 *   叶子目录必须自包含，Makefile 是按目录独立编译的，
 *   所以**不能** #include "../singly/slist.h" 去借别人的代码。
 * 借不了也没关系 —— 重写一遍才是真正的复习。
 *
 * -------------------------------------------------------------------
 * 三、无向图为什么一条边要挂两个节点？
 * -------------------------------------------------------------------
 * 加边 (a,b) 时要同时做两件事：往 a 的链上挂一个 dest=b 的节点，
 * 再往 b 的链上挂一个 dest=a 的节点。因为"邻居清单"是各自记各自的。
 * 后果：
 *   - 空间是 V 个头指针 + **2E** 个节点（不是 E 个）。
 *   - 度之和 == 节点总数 == 2E，这条等式是免费的自检器（见 glist_print）。
 *   - 链表节点数会比矩阵的非 0 格子数**更多**：矩阵一条边占 2 格但格子只有 4 字节，
 *     链表一条边占 2 个节点、每个 16 字节。小图上邻接表反而更费内存 ——
 *     邻接矩阵 README 里已经算过这笔账（V=8,E=7：256B vs 288B）。
 *     邻接表真正赢在大图/稀疏图的**遍历速度**和**规模弹性**。
 *
 * -------------------------------------------------------------------
 * 四、本节用哪张图？
 * -------------------------------------------------------------------
 * 还是全章共用的**无向图 G**（8 个顶点 0..7，故意不连通）：
 *
 *        0 ───── 1                     4 ───── 5
 *         \     / \                     \     /
 *          \   /   \                     \   /
 *           2 ──────                     6          7 ← 孤零零
 *            \
 *             3
 *
 *   边 7 条：(0,1) (1,2) (0,2) (2,3) (4,5) (5,6) (4,6)
 *
 * 用同一张图是故意的：你可以把这一节的 `0 -> 1 -> 2 -> NULL`
 * 和上一节邻接矩阵的第 0 行 `0 1 1 0 0 0 0 0` 摆在一起看 ——
 * **它们记录的是同一件事，只是一个把 0 也存了、一个只存 1。**
 */

/* 本节示例最多 8 个顶点（跟邻接矩阵那节对齐，方便对照） */
#define GL_MAX_V 8

/*
 * 链表节点：邻居编号 + 指向下一个邻居。
 * ⚠ 注意 `struct Node *next` 里为什么不能写 `Node *next`：
 *   此时 typedef 还没完成，名字 Node 还不存在，必须带上 struct 关键字。
 *   （这是 00-c-foundation/struct-and-typedef 里讲过的老规矩。）
 */
typedef struct Node {
    int dest;                 /* 这条链的这一格：我的一个邻居的编号 */
    struct Node *next;        /* 下一个邻居；NULL 表示邻居数完了 */
} Node;

/*
 * 整张图：
 *   adj  —— 一个"指针数组"：adj[i] 是第 i 条链表的**头节点地址**
 *           （注意：是 V 个 Node* 的数组，不是 V 个 Node 的数组）
 *   v    —— 顶点数
 *   e    —— 无向边的条数（人类意义上的边数；链表节点数会是 2e）
 */
typedef struct {
    Node **adj;
    int v;
    int e;
} GList;

/* ---------- 1. 建图 / 收摊（本节唯一的 malloc/free 责任田）---------- */
GList *glist_create(int v);                                 /* malloc 图结构 + malloc V 个指针的数组；失败返回 NULL */
void   glist_free(GList *g);                                /* 逐顶点把链表节点全 free，再 free 数组、再 free 图 */

/* ---------- 2. 加边（两种插法对比着学）---------- */
int glist_add_edge(GList *g, int a, int b);                 /* 无向边，**尾插**：O(度)，保住"加边顺序"（示例图特意排成升序） */
int glist_add_edge_front(GList *g, int a, int b);           /* 无向边，**头插**：O(1)，但邻居清单会被倒过来 */

/* ---------- 3. 问问题 ---------- */
int glist_has_edge(const GList *g, int a, int b);           /* 顺 a 的链找 dest==b：O(度) */
int glist_degree(const GList *g, int u);                    /* 数 u 那条链有几个节点：O(度) */
int glist_node_count(const GList *g);                       /* 全图链表节点总数，用来验证 == 2×边数 */

/* ---------- 4. 删边（第 02 章"按值删节点"的实战版）---------- */
int glist_remove_edge(GList *g, int a, int b);              /* 两条链上各删一个节点，要处理"删头"和"找不到" */

/* ---------- 5. 看 ---------- */
void glist_print(const GList *g);                           /* 打成 0 -> 1 -> 2 -> NULL */

/* ---------- 6. 本节专用：造出共用示例图 G（尾插，邻居升序）---------- */
GList *glist_sample(void);                                  /* 调用者负责 glist_free */

#endif /* GLIST_H */
