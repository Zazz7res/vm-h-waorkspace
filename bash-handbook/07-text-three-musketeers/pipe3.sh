#!/usr/bin/env bash
# ============================================================================
# pipe3.sh —— grep / sed / awk 串成一条管道时，「单位错位」到底错在哪
#
# 一句话主旨：管道是一条「按换行分帧的传送带」，但带子上每一环手里拿的东西不一样
#             —— grep 拿整行、sed 拿一行、awk 拿这行里的字段；而这条管道报给
#             外壳的退出码，默认只由**最后一环**说了算。
#
# demo.sh 里这样调：bash pipe3.sh          （必须用相对文件名：见下方安全说明）
#
# 安全说明：只在本脚本当前目录下自建的一次性子目录 p3/ 里造样本做实验，
#           结尾由 trap 删掉；不碰 ~、不碰绝对 /tmp、不读写仓库既有文件、
#           不联网、不开端口、不 kill 任何不是本脚本起的进程。
#
# ★ 本机不拿什么当证据：
#   1) 上游被提前关管道时收到的退出码是**时序竞争**（seq 跑完 → 0；被掐 → 141），
#      每跑可能不同，所以第 7 格只印「拿到什么」，不印那个码；
#   2) 毫秒耗时、inode、随机名一律不印；
#   3) 反过来，第 3、4 格的退出码本机实测是确定的（不开 pipefail 时
#      grep 没命中会被最后一环洗成 0，开了才是 1），所以敢当证据。
# ============================================================================

trap 'rm -rf p3' EXIT
mkdir -p p3

cat > p3/svc.log <<'EOF'
2026-01-05 INFO  start ok
2026-01-05 WARN  disk 91%
2026-01-06 ERROR disk 95% full
2026-01-06 INFO  rotate done
2026-01-07 ERROR disk 97% full
EOF

# ---------------------------------------------------------------------------
echo "=== 1. 同一条管道，三环手里拿的根本不是同一种东西 ==="
grep 'ERROR' p3/svc.log > p3/s1
sed -n 's/^2026-01-/日 /p' p3/svc.log > p3/s2
awk '/ERROR/{print $4}' p3/svc.log > p3/s3
printf "  grep   给 %s 行，每行还是**整行**，最长 %s 字节\n" \
  "$(wc -l < p3/s1)" "$(awk 'BEGIN{m=0} {if(length($0)>m)m=length($0)} END{print m}' p3/s1)"
printf "  sed    给 %s 行，它一次手里只有**一行**，改的是这行的局部\n" "$(wc -l < p3/s2)"
printf "  awk    给 %s 行，内容依次是[%s]，它拿的是**行里的第 4 个字段**\n" \
  "$(wc -l < p3/s3)" "$(paste -sd, p3/s3)"
echo "  → 直觉以为「三个工具都在筛这个文件」，屏幕上实际是：一个给整行、一个改半行、一个只掏字段。"
echo "  ★ 记住这条，后面每一格「为什么我的命令没反应」都能自己解释。"

# ---------------------------------------------------------------------------
echo '=== 2. 换行符是传送带的分帧符：谁漏了换行，下一环就把两行当一行 ==='
grep 'ERROR' p3/svc.log | awk '{printf "%s", $4}' > p3/noframe
grep 'ERROR' p3/svc.log | awk '{print $4}' > p3/framed
printf "  awk 用 printf 不带换行 → 屏上[%s]，里面换行符个数 = %s\n" \
  "$(cat p3/noframe)" "$(tr -cd '\n' < p3/noframe | wc -c)"
printf "  awk 用 print（自带换行）→ 屏上两行，换行符个数 = %s\n" "$(tr -cd '\n' < p3/framed | wc -c)"
printf "  同一条管道后面各接一环 wc -l：不带换行数到 %s 行，带换行数到 %s 行\n" \
  "$(wc -l < p3/noframe)" "$(wc -l < p3/framed)"
echo "  → 直觉以为「我打印了两个值，下游自然当两行」，实际下游只认换行符，不认你的意图。"

# ---------------------------------------------------------------------------
echo "=== 3. ★ 管道的退出码谁说了算：默认最后那一环洗掉前面所有的失败 ==="
grep 'NOSUCH' p3/svc.log > /dev/null
printf "  ① grep 自己（没命中）的码        = %s\n" "$?"
grep 'NOSUCH' p3/svc.log | cat > /dev/null
printf "  ② grep 没命中 | cat 的码         = %s ← ★ 前面那次失败被 cat 洗成「成功」了\n" "$?"
( set -o pipefail; grep 'NOSUCH' p3/svc.log | cat > /dev/null )
printf "  ③ 同样两条命令，开了 pipefail 的码 = %s\n" "$?"
grep 'ERROR' p3/svc.log | cat > /dev/null
printf "  ④ 对照组：grep 命中时管道码      = %s（开不开都一样，差别只在中段失败时显现）\n" "$?"
echo "  → 直觉以为「管道里有人失败脚本当然知道」，实际默认只有**最后一环**的码能出来。"
echo "  ★ 所以「用 grep 当存在性检查」挂在管道尾巴上，会一路骗到底。"

# ---------------------------------------------------------------------------
echo "=== 4. 空输入时三个工具的态度完全不一样（能不能拿退出码当判据）==="
: > p3/empty
grep -q x p3/empty; printf "  grep 读空文件  → 码 %s，屏幕 %s 字节\n" "$?" "$(grep x p3/empty | wc -c)"
sed 's/a/b/' < p3/empty > /dev/null; printf "  sed  读空文件  → 码 %s，屏幕 %s 字节\n" "$?" "$(sed 's/a/b/' < p3/empty | wc -c)"
awk '{print}' < p3/empty > /dev/null; printf "  awk  读空文件  → 码 %s，屏幕 %s 字节\n" "$?" "$(awk '{print}' < p3/empty | wc -c)"
printf "  「文件是空的」和「文件有内容但没匹配」这两种 0，屏幕上分得出来吗 → %s\n" \
  "$([ "$(grep zzz p3/svc.log | wc -c)" = "$(grep x p3/empty | wc -c)" ] && echo '分不出，都是 0 字节' || echo 能分)"
echo "  → 直觉以为「sed/awk 啥也没改到会报错」，实际它们照样退 0 —— 三个工具里只有 grep 用退出码表达结果。"

# ---------------------------------------------------------------------------
echo "=== 5. 管道里的 read 一行一行拿，带子上的指针归这个进程所有 ==="
printf "  一次 read 拿到：[%s]（后面两行没人读，随进程退出丢掉）\n" \
  "$(printf 'a\nb\nc\n' | { read -r l; printf '%s' "$l"; })"
printf "  同一个 { } 里 read 两次，依次拿到：[%s]\n" \
  "$(printf 'a\nb\nc\n' | { read -r x; read -r y; printf '%s,%s' "$x" "$y"; })"
printf "  read 三次拿满：[%s]\n" \
  "$(printf 'a\nb\nc\n' | { read -r p; read -r q; read -r r; printf '%s,%s,%s' "$p" "$q" "$r"; })"
echo "  → 直觉以为「read 会自己去找下一行」，实际它只认标准输入这条带子；带子读到哪，是进程状态不是文件状态。"

# ---------------------------------------------------------------------------
echo "=== 6. 减号「-」= 从我这根管道里读；三个工具都认这个约定 ==="
printf "  grep 命中 2 行喂给 sed -n 'p' - → 收到 %s 行\n" "$(grep 'ERROR' p3/svc.log | sed -n 'p' - | wc -l)"
printf "  awk 不写文件参数，默认就读 stdin → 收到 %s 行\n" "$(grep 'ERROR' p3/svc.log | awk '{print $2}' | wc -l)"
printf "  printf 一个串喂给 cat - → [%s]（当前目录里有没有名叫 - 的文件 = %s）\n" \
  "$(printf 'dash' | cat -)" "$([ -e './-' ] && echo 有 || echo 没有)"
echo "  ★ 别把两件事混了：两个减号是「后面没有选项了」，单个减号才是「stdin」；两者都用来防坑，防的不是同一种坑。"

# ---------------------------------------------------------------------------
echo "=== 7. 下游提前收工会把上游掐掉：这一格故意不印那个码 ==="
printf "  head -1 从 5 行样本里只拿 1 行，拿到的是：[%s]\n" "$(head -1 p3/svc.log)"
printf "  seq 1 5 | head -1 拿到：[%s]，稳定那一半 = %s 行\n" \
  "$(seq 1 5 | head -1)" "$(seq 1 5 | head -1 | wc -l)"
echo "  → 直觉以为「上游被掐一定会给我一个固定的失败码」，实际本机是时序竞争："
echo "    seq 写完就退 0，没写完被 SIGPIPE 掐就 141 —— 两次跑可能不一样，所以**不拿它当证据**，"
echo "    只拿「head 确实只输出 1 行」当证据。"

# ---------------------------------------------------------------------------
echo "=== 8. 收口：三个工具各自的「单位 / 能不能就地改 / 退出码表不表结果」 ==="
printf "  grep → 单位=整行；改文件=不能（只读）；退出码 0/1/2 **表结果**（1 是没匹配，2 是真出错）\n"
printf "  sed  → 单位=一行；改文件=能（-i 就地）；退出码**不表**「有没有改到」，没改到也退 0\n"
printf "  awk  → 单位=字段；改文件=不能（要写临时文件再换）；退出码**不表**结果\n"
printf "  自证一（现场清干净）：删之前 p3 在吗 → %s\n" "$([ -d p3 ] && echo 在 || echo 不在)"
rm -rf p3
printf "  删之后在吗 → %s ｜ 当前目录里名叫 p3 的条目 = %s（trap 只是备胎）\n" \
  "$([ -d p3 ] && echo 在 || echo 不在)" "$(find . -maxdepth 1 -name p3 | wc -l)"
printf "  ★ 一句话带走：管道传的是**字节**、分帧靠**换行**、退出码默认只看**最后一环**；\n"
printf "    所以「命令跑完了」不等于「中间每一环都干对了」—— 要判对错就得自己数。\n"

exit 0
