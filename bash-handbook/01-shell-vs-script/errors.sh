#!/usr/bin/env bash
# ============================================================================
# errors.sh —— 新手最常撞的报错，原文照打
#
# 本章**故意不加** set -e：一个脚本里留好几个错，你要看到的是「报错原文 + 脚本继续往下跑」，
# 这样才能真正明白「bash 默认不会因为出错而停下」这条最要命的事实。
#
# 顺序有讲究：set -u 的未定义变量会让脚本**当场结束**，所以放在最后一段。
# 语法错误不在这个文件里 —— 它属于 broken_syntax.sh（那一类是「解析阶段」的问题）。
# ============================================================================

echo "  【报错 1】命令不存在"
echo "  敲的命令：no_such_program_abc --version"
no_such_program_abc --version
echo "  ← 报错原文见上一行。退出码 = [$?]   ← 127 = 「命令没找到」"
echo "  脚本**没有停**，还在往下跑。这就是 bash 的默认行为。"

echo
echo "  【报错 2】赋值写成了「等号两边带空格」（第一号新手手误）"
echo "  敲的命令：my_count = 5"
my_count = 5
echo "  ← 退出码 = [$?]。bash 把它读成「运行命令 my_count，参数是 = 和 5」，"
echo "    所以报的是「command not found」，**而不是**语法错误。赋值必须写 my_count=5。"

echo
echo "  【报错 3】把脚本当命令敲，但忘了写 ./"
echo "  敲的命令：pids.sh（当前目录里的文件，没加 ./）"
pids.sh
echo "  ← 退出码 = [$?]。bash **不会**在当前目录找命令（这是安全设计，"
echo "    否则你在下载目录里随手敲个 ls，就可能执行到别人放的同名脚本）。"
echo "    必须写 ./pids.sh。这也是新手最高频的困惑之一。"

echo
echo "  【报错 4】条件里把字符串丢给 -eq 做数值比较"
x=abc
if [ "$x" -eq 1 ]; then
    echo "  进了 then（不可能进）"
fi
echo "  ← 报错原文见上一行，退出码 = [$?]"
echo "    这里有两层教训：① [ ] 是个**命令**（type -a test 能看到它是内建），"
echo "    所以它的报错是运行时错误，脚本继续跑；② 但 if 整条语句的退出码是 **0**（假分支不执行"
echo "    也不算失败），所以「判定条件写错了」这种事**根本不会**被 set -e 抓到 —— 它只会静默走错路。"

echo
echo "  【报错 5】set -u 下引用未定义变量（这一段会让脚本当场结束）"
set -u
echo "  已经 set -u，现在敲「echo [\$UNDEFINED_AT_ALL]」 ——"
echo "[${UNDEFINED_AT_ALL}]"
echo "  ← 你永远看不到这一行，因为上一行就把脚本炸了。"
