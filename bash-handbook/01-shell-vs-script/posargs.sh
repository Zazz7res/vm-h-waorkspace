#!/usr/bin/env bash
# ============================================================================
# posargs.sh —— $0 $1 $# $@ $* 的真实值，以及 set -- 怎么「换掉」位置参数
#
# 这一页的输入是 demo.sh 传的：alpha "beta gamma" delta
# 关键看点：引号在**传参时**就把「beta gamma」绑成一个参数了，
#           所以 $# 是 3 而不是 4。
# ============================================================================

echo "  \$0 = [$0]        ← 脚本名（怎么被叫起来，它就写什么）"
echo "  \$1 = [$1]  \$2 = [$2]  \$3 = [$3]  \$4 = [${4-}]   ← 第 4 个根本没传"
echo "  \$# = [$#]        ← 参数个数。**不含** \$0！这是最多人记错的一条"

# $@ 和 $* 不加引号时输出看起来一模一样；加了引号才见分晓。
# 这里两种都不加引号，让你先看到「看着一样」。
echo "  \$@ = [$@]"
echo "  \$* = [$*]"

# 加引号的版本：`"$@"` 展开成多个独立词（这正是你 99% 时候想要的），
# `"$*"` 展开成一个词（用 IFS 的第一个字符连接）。
echo "  \"\$@\" 加引号，用 | 连接每个词："
for a in "$@"; do printf '    |%s' "$a"; done
printf '|\n'
echo "  \"\$*\" 加引号，是一个整词："
for a in "$*"; do printf '    |%s|\n' "$a"; done

# 逐个打印，让「第几个参数是谁」彻底没有歧义
echo "  逐个拆开看："
i=1
for a in "$@"; do
    echo "    \$[$i] = [$a]"
    i=$((i + 1))
done

echo "  ---- 下面用 set -- 把位置参数整组换掉 ----"
set -- 换进去的第一个 "第二个带 空格" 第三个
echo "  set -- 之后：\$# = [$#]"
echo "  set -- 之后：\$1 = [$1]  \$2 = [$2]  \$3 = [$3]"

# set -- 最常见的真实用途：把「解析完剩下的参数」重新装成位置参数，
# 或者在函数里把一串值临时当参数用。下面模拟「剥掉第一个参数」的写法。
set -- alpha "beta gamma" delta
echo "  shift 前：\$# = [$#]  \$1 = [$1]"
shift
echo "  shift 一次后：\$# = [$#]  \$1 = [$1]"
