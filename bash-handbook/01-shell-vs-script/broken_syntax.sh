#!/usr/bin/env bash
# ============================================================================
# broken_syntax.sh —— 故意的**语法**错误：`if` 后面少了 `then`
#
# 这是抄代码/改代码时最常见的一种手误，报错原文固定长这样：
#     syntax error near unexpected token `fi'
#
# 两个必须建立的直觉：
#   ① bash 是「读一条、解析一条、执行一条」。所以**报错之前的 echo 真的会打印出来**，
#      很多人以为整个脚本会被拒绝执行 —— 其实不是。这也是最危险的：
#      脚本可能已经跑了一半、已经往磁盘写了东西，才在这一行炸掉。
#   ② `bash -n 文件` 只解析不执行，能在真正跑之前把这种错误挑出来；
#      但它**不会**报「命令不存在」「变量未定义」那类运行时问题（见 errors.sh 的对比）。
# ============================================================================

echo "  这行在报错**之前**，所以它真的打印出来了 → 证明 bash 是边解析边执行的"

CONFIG_FILE=/etc/hostname

# 少写了 then：`if [ ... ]` 后面直接跟命令，bash 解析到 fi 才发现不对
if [ -f "$CONFIG_FILE" ]
    echo "  找到了 $CONFIG_FILE，它的第一行是：$(head -1 "$CONFIG_FILE")"
fi

echo "  这行永远执行不到（上面就解析失败了）"
