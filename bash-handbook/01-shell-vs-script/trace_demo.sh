#!/usr/bin/env bash
# ============================================================================
# trace_demo.sh —— 专门给 `bash -x` 用的最小样本
#
# 这个脚本的输出（stdout）不重要，重要的是 `bash -x` 打出来的跟踪（stderr）。
# 跟踪行的读法见本章 README「场景 8」：
#
#   + echo '第 1 轮'      ← 开头的 + 是 PS4 提示符，后面是**展开之后**的命令行
#   + [L22 add_up] ...    ← 本文件自定义了 PS4，所以还带上了行号和函数名
#
# 一个容易记错的点（本机 bash 5.3 实测）：**函数调用、( )、{ } 分组都不会让 + 变多**，
# 只有一层 `+`。真正会多出一个 + 的是**命令替换** $( )，因为它才真的 fork 了子 shell：
#
#   $ set -x; v=$(printf hi)
#   ++ printf hi        ← 两个 +：这是命令替换里的子 shell
#   + v=hi
#
# 所以读 -x 的关键是：每一行都是 bash **真正执行**的那一行，
# 变量已经替换完、通配已经展开完、引号已经剥掉 —— 它告诉你「实际发生了什么」，
# 而不是「你写了什么」。
# ============================================================================

PS4='+ [L$LINENO ${FUNCNAME[0]:-顶层}] '   # 自定义提示符：把行号和函数名也打出来

total=0

# 一个函数：看 -x 里出现 `++`（进函数＝深度 +1）
add_up() {
    local step="$1"
    total=$((total + step))
    echo "  第 $1 轮：加上 $step，total=$total"
}

for round in 1 2 3; do
    add_up "$round"
done

# 故意放一个「看起来对但其实会失败」的命令，演示 -x 里能看到退出码
# （bash -x 本身不打退出码；退出码要靠 `set -o errtrace`/`$?`，见 08 章。
#   这里的价值是：你能从跟踪里看出它到底被展开成了什么。）
missing_program_xyz --help

echo "  最后一条命令的退出码 = [$?]"

# 变量在跟踪里会以「展开后的样子」出现，这是定位中文/空格类 bug 的关键
label="带 空格 和'引号"
echo "  打印 label：[$label]"
