#!/usr/bin/env bash
# ============================================================================
# vars.sh —— 脚本内部的自动变量实测
#
#   demo.sh 里这样调它：bash vars.sh alpha "beta gamma"
#   看点有两个：
#     ① "beta gamma" 带引号 → 它是一个参数，所以 $# 是 2 而不是 3；
#     ② $0 是「你怎么被叫起来的」，不是常量（第 01 章已经验证过 ./x.sh 时它是 ./x.sh）。
#   双引号里的 \$ 是「字面美元符号」的写法（06 节那条规则在这里就用上了）。
# ============================================================================

printf "%s\n"   "\$0      = [$0]"
printf "%s\n"   "\$1      = [$1]"
printf "%s\n"   "\${2-}   = [${2-}]"
printf "%s\n"   "\$#      = [$#]"
printf "%s\n"   "\$*     = [$*]"
printf "%s\n"   "\$@     = [$(printf '%s ' "$@")]"
printf "%s\n"   "\$-      = [$-]（脚本：非交互，所以字母串里没有 i）"
printf "%s\n"   "\$\$     = [$$]  本进程 \$BASHPID = [$BASHPID]  \$PPID = [$PPID]"
printf "%s\n"   "\$LINENO 走到这里 = [$LINENO]"
printf "%s\n"   "\$BASH_VERSION = [$BASH_VERSION]"
