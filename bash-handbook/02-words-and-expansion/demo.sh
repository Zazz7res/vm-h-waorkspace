#!/usr/bin/env bash
# ============================================================================
# 第 02 章《一行命令被切成几段：引号、${}、IFS、通配》—— 整章证据一键复现
#
#   bash demo.sh            跑完自动删沙箱（默认）
#   bash demo.sh --keep     跑完保留沙箱并打印路径，进去自己接着敲
#   bash demo.sh > out.txt  重定向时自动关掉颜色，README 引用的就是这份纯文本
#
# 屏幕上出现的每一行，都是这条命令在这台机器上的真实结果 —— 没有一行是手写的。
#
# 安全说明：
#   * 所有写操作只发生在 mktemp -d 出来的沙箱里（前缀 bash02-）；
#     mkdir / touch / rm 全部只作用于沙箱内本章自己造的文件，仓库目录只读
#   * 绝不修改 ~/.bashrc、~/.profile、~/.config、/etc：本章不需要 rc，
#     要「另一种 shell 环境」时用 bash -c 或 bash --norc --noprofile -ic 起新进程
#   * 唯一的后台进程是 21 节那个 sleep，用 $! 记录、wait 收尾；不起监听端口
#   * 不联网、不装包（缺的工具如实打印，例如 shellcheck）
#   * 屏幕上不打印任何绝对路径：要列真实目录用 runc_at，命令行只留目录名 + 相对路径
#
# 为什么这个脚本**故意不加** set -e（也故意不加 set -u）：
#   本章要演示的正是「报错原文 + 后面继续跑」：${v:?} 会让脚本退出、未闭合的引号是
#   语法错误、failglob 会让整条命令不执行。加了 -e 第一段就把整个 demo 掐了。
#   set -u 的价值单独放在 22 节，用**子进程**跑 unbound.sh 演示，不污染 demo 主体。
#   （set -euo pipefail 为什么生产必加，是第 08 章的内容。）
# ============================================================================

KEEP=0
for arg in "$@"; do
    case "$arg" in
        --keep) KEEP=1 ;;
        -h|--help) echo "用法: bash demo.sh [--keep]"; exit 0 ;;
        *) echo "未知参数：$arg（本脚本只认 --keep）" >&2; exit 2 ;;
    esac
done

# 把语言环境钉死成「英文 + UTF-8」：这台机器默认 zh_CN.UTF-8，bash 的报错会是中文，
# README 就没法逐行和真实输出核对。改动只发生在本脚本和它 fork 出来的子进程里。
ORIG_LANG="${LANG-（未设）}"
ORIG_LC_ALL="${LC_ALL-（未设）}"
export LC_ALL=C.UTF-8 LANG=C.UTF-8 LANGUAGE=C

if [ -t 1 ]; then B=$'\033[1m'; C=$'\033[36m'; R=$'\033[0m'; else B=''; C=''; R=''; fi

HERE=$(cd "$(dirname "$0")" && pwd)
SB=$(mktemp -d "${TMPDIR:-/tmp}/bash02-XXXXXX")

banner() { printf '\n══════ %s %s\n' "$1" "════════════════════════════════"; }
note() { printf '%s\n' "$1"; }

# 打印命令 → 用 bash -c 真跑 → 打印退出码。
# 用 bash -c 是为了能自然地写管道、`;`、glob、各种引号；也保证每一段都在一个
# **全新的非交互 bash** 里开始，段与段之间不互相污染（变量、shopt 开关都不串味）。
runc() {
    printf '\n%s$ %s%s\n' "$C" "$1" "$R"
    bash -c "$1" 2>&1
    printf '[退出码 %d]\n' "$?"
}

# runc_at <目录> <命令>：先 cd 进那个目录再跑，屏幕上只留目录名（basename）+ 相对命令。
#   要列真实目录（比如本章目录本身）时用它：命令行里不出现绝对路径，本机登录名一个都不留。
runc_at() {
    printf '\n%s$ 〔在 %s 里〕 %s%s\n' "$C" "$(basename "$1")" "$2" "$R"
    ( cd "$1" && bash -c "$2" ) 2>&1
    printf '[退出码 %d]\n' "$?"
    return 0
}

cleanup() {
    if [ "$KEEP" -eq 1 ]; then
        printf '\n[沙箱已保留] %s\n  进去接着敲： cd "%s/work"     看完删掉： rm -rf "%s"\n' "$SB" "$SB" "$SB"
    else
        rm -rf "$SB"
        printf '\n[沙箱已删除] %s\n' "$SB"
    fi
}
trap cleanup EXIT

# 准备沙箱工作目录：把本章源文件复制进去，后面所有加工都在副本上进行。
mkdir -p "$SB/work"
cp "$HERE"/*.sh "$SB/work/"
cd "$SB/work" || exit 1

# 本脚本里需要「真的单引号 / 真的反引号」字符时用这两个变量拼，
# 免得在 demo.sh 自己的引号堆里把本脚本的语法写坏（打印出来的命令行仍是正常字符）。
SQ="'"
BT=$'\x60'

# ============================================================================
banner "00 先把这台机器的发言权确认一遍"
# ============================================================================
note '# 本章讲的是 bash 自己的展开规则，几乎不依赖外部命令；但有两件事必须先钉下来：'
note '# ① bash 的版本（关联数组、${!prefix@} 这些都是版本相关的）；② 语言环境。'
runc 'bash --version | head -1'
runc 'echo "demo 已把自己改成：LC_ALL=[$LC_ALL] LANG=[$LANG]（你原来的终端是 LANG=$ORIG_LANG，LC_ALL=$ORIG_LC_ALL）"'
note '# 报错文本跟着语言环境走。本机实测的优先级是 LANGUAGE 最先，其次 LC_ALL，最后 LANG（空值按未设算）：'
runc 'nosuchcommand02'
runc 'LANGUAGE= LC_ALL=zh_CN.UTF-8 LANG=zh_CN.UTF-8 bash -c nosuchcommand02'
runc 'LC_ALL=zh_CN.UTF-8 LANG=zh_CN.UTF-8 bash -c nosuchcommand02'
note '# ↑ 第二行就是你终端里中文报错的样子（未找到命令）。第三行看着和上一行只差一个 LANGUAGE=，'
note '#   却因为 demo 开头导出了 LANGUAGE=C 又被顶回英文：LANGUAGE 排在 LC_ALL 前面被看一眼。'
note '#   所以本章取证一律钉死在 LC_ALL=C.UTF-8 + LANGUAGE=C：报错文本固定，README 才能逐行核对。'
runc 'command -v shellcheck || echo "shellcheck: 本机没有（本章只做实跑取证，不装它）"'
note '# 默认字段分隔符 IFS 长这样（%q 是 printf 的「可重新敲回去」格式，会把控制字符显出来）：'
runc 'printf "默认 IFS = %q\n" "$IFS"'

# ============================================================================
banner "01 本章的量尺：seg.sh 把「到底几个词」直接打出来"
# ============================================================================
note '# seg.sh 里面只有两句：printf "参数个数=%d\n" "$#" 和把每一格用 [ ] 包住打印。'
note '# 它拿到几个词，完全由**调用它的那个 shell** 在把它调起来之前决定 —— 这正是我们要看的数。'
runc 'bash seg.sh a b c'
runc 'bash seg.sh "a b" c'
runc 'bash seg.sh'
runc 'v="a b c"; bash seg.sh $v'
runc 'v="a b c"; bash seg.sh "$v"'
note '# 最后两条只差一对引号：一条 3 个词、一条 1 个词。本章全部内容就是这一件事的展开。'

# ============================================================================
banner "02 展开的顺序：一行命令把六步全撞出来"
# ============================================================================
note '# 这一行里同时放了：花括号、~、变量、命令替换、通配、双引号。看输出就知道谁先谁后。'
runc 'mkdir -p dir; touch dir/one.txt dir/two.txt; v=dir; echo ~root/x {a,b} $v/*.txt $(printf CMD) *.nope "a b" $v'
note '# 读法：'
note '#   ~root/x        → 波浪线被换成 /root/x（加引号就不换了，见本节最后一行）'
note '#   {a,b}          → 变成 a、b 两个词（它们不需要是真实存在的文件）'
note '#   $v/*.txt       → 先把 $v 换成 dir，**再**拿 dir/*.txt 去匹配真实文件 → 两个文件'
note '#   $(printf CMD)  → 命令替换的结果 CMD 当普通文本贴进来'
note '#   *.nope         → 一个文件都没匹配上 → bash 默认把字面量原样留着（13 节的祸根）'
note '#   "a b" 和 $v    → 各一个词'
runc 'v=dir; echo "花括号排第一，所以能带着变量的结果走：{a,b}$v =>"; echo {a,b}$v'
runc 'b="{x,y}"; echo "但反过来不行：变量里的花括号不会被再展开一次 =>"; echo $b'
runc 'echo "命令替换出来的花括号同理："; echo $(printf "%s" "{x,y}")'
runc 'n=1; m=3; echo "序列 {n..m} 用变量造不出来：{$n..$m}"; echo {$n..$m}'
runc 'd=~root/x; echo "赋值里不加引号时 ~ 会换掉：[$d]"; d="~root/x"; echo "加了引号就不换：[$d]"'
note '# 三条结论（顺序记不住就记这三句）：'
note '#   ① 花括号只认你**写在源码里的字面文本**，它最先执行、且只执行一次；'
note '#   ② 变量/命令替换/算术的结果还要再过一遍「分词」和「通配」，所以值里有空格或 * 就会出事；'
note '#   ③ 引号是最后一道手续：引号本身被删掉，它保护的内容不再参与前面任何一步。'

# ============================================================================
banner "03 变量和命令替换的结果，还要再过一次通配（glob 来自变量 = 事故源头）"
# ============================================================================
note '# 沙箱 files/ 里放了这些名字（故意带空格和 *，全部是沙箱内本章自己造的文件）：'
runc 'mkdir -p files; touch files/aa.txt files/ab.txt files/b1.log files/A.txt files/B.txt "files/my file.txt" "files/we*ird.txt"; cd files; ls'
runc 'cd files; v="*.txt"; echo "裸用：把 v 的值当模式用"; echo $v'
runc 'cd files; v="*.txt"; echo "带引号：模式变成普通文本"; echo "$v"'
runc 'cd files; echo "命令替换的结果也一样被通配："; echo $(printf "we*")'
runc 'cd files; echo "花括号的结果也要过通配：{a,b}* =>"; echo {a,b}*'
runc 'cd files; echo "两个词都没命中就都留字面量：{zz,yy}* =>"; echo {zz,yy}*'
note '# ★ 变量的「值」里有 * ? [a-z] 时，裸用等于「把值当模式用」；想只当文本就得加引号。'
note '#   这和「值里有没有空格」是两套独立的事故（分词见 09 节，无匹配见 13 节）。'

# ============================================================================
banner "04 set -x：跟踪里那对引号是 bash 现加的，不是你写的那对"
# ============================================================================
note '# 三种完全不同的写法（双引号 / 单引号 / 反斜杠），在 set -x 里长得一模一样：'
runc 'set -x; echo "a b"; echo '"'"'a b'"'"'; echo a\ b'
note '# ↑ + 号后面那对单引号是 bash 为了「让你能照着敲回去」现加的转义格式。'
note '#   它只告诉你：这里有 1 个词，内容是 a b。你源码里用的是哪种引号，它不显示。'
runc 'set -x; v="a b"; printf "[%s]\n" "$v"'
runc 'set -x; v="a b"; printf "[%s]\n" $v'
note '# ★ 这两行是唯一能一眼看出「有没有被切」的地方：带引号那行的跟踪里 a b 被引号包住（1 个词），'
note '#   不带引号那行是两个词分开站着。调「莫名其妙少了一个参数」时先看这里。'
runc 'set -x; printf "[%s]\n" "a b" "c*d" *.nope'
note '# 你写的格式串是 "[%s]\n"（双引号），跟踪里打成单引号那版 —— 再次证明引号是重新加的。'

# ============================================================================
banner "05 单引号：进去之后什么都不发生"
# ============================================================================
runc 'v=hi; echo "$v"; echo '"'"'$v'"'"''
runc 'echo '"'"'$v 反引号也安静 "双引号" 反斜杠 \n 全部原样'"'"''
note '# 单引号里唯一不能出现的字符就是单引号本身。直接写 it'"'"'s 会当场语法错：'
runc "echo it${SQ}s 这样写会当场报错"
note '# 正解有两种（下面这个 quote_fix.sh 就是两个例子，先 cat 再跑）：'
cat > quote_fix.sh <<'QFIX'
echo "双引号包着：it's 想写几个单引号写几个"
echo '单引号出关再进关：it'\''s 也能成'
QFIX
runc 'cat quote_fix.sh'
runc 'bash quote_fix.sh'
note '# 第二种写法的读法：先用单引号包住 it，再「出关」用一个转义的单引号补上那个字符，再进关包 s。'

# ============================================================================
banner "06 双引号：只有美元符、反引号、双引号、反斜杠这几样还特殊"
# ============================================================================
runc 'v=hi; echo "反斜杠组：\" 是一个引号、\\ 是一个反斜杠、\n 和 \t 原样保留；而 $v 会展开"'
runc "echo \"双引号里的单引号就是普通字符：it${SQ}s，不用转义\""
runc 'echo 双引号外的反斜杠管住空格：a\ b   还有星号：\*'
runc 'v=hi; echo "想显示美元符号要转义：\$v；不转义就展开成值：$v；反引号照样执行：`printf BT`；但星号和空格不参与通配与分词：* a b"'
note '# 记法：双引号 = 「保命分词字符（空格 tab 换行）和通配字符，其余照旧」。'
note '# 但美元符、反引号、双引号、反斜杠这四个在双引号**里面**仍是语法字符，想当字面写就得转义；'
note '#   而反斜杠+n 这类在双引号里**不是**转义（原样两个字符）—— 要真换行用美元符加单引号那套或 printf（08 节）。'

# ============================================================================
banner "07 反引号 vs \$( )：退出码一样，嵌套和转义差很多"
# ============================================================================
runc 'echo "反引号必须成对；在单引号里它才是纯文本：'"'"'`printf HI`'"'"' 原样打印"'
runc 'x=hi; echo "双引号里的反引号还是会被执行：`echo $x`"'
runc 'echo "转义过的反引号是字面字符：\$ 和 \`，都不执行"'
runc "echo 少了一个反引号：$BT"
note '# ↑ 语法错误原文（bash 自己说它在找配对的引号），退出码 2 —— 整条命令一个字都没执行。'
runc "echo 反引号套反引号要这样转义：${BT}echo ${BT}内层${BT}${BT}"
runc 'echo $(echo "$(echo 第三层)")'
runc 'echo "同一件事，套几层写几层：$(echo 外面 $(echo 里面))"'
note '# 退出码：两种写法都是「替换里最后一条命令的退出码」，接住它的方式也一样：'
runc 'r=$(nosuchcmd02); echo "紧跟的 \$? = [$?]"'
runc "q=${BT}nosuchcmd02${BT}; echo \"反引号版紧跟的 \\\$? = [\$?]\""
runc 'r=$(printf ok); echo 隔了一条命令; echo "再读 \$? = [$?]（已经被上面那个 echo 覆盖成 0）"'
note '# ★ 所以「命令替换里失败了」只在你**立刻**读 $? 时才知道；替换结果本身只是文本。'

# ============================================================================
banner "08 美元符加单引号（ANSI-C 引用）：把反斜杠 n、t、x41 变成真字符"
# ============================================================================
runc 'echo $'"'"'a\nb'"'"''
runc 'printf "普通单引号对比：[%s]\n" '"'"'a\nb'"'"''
runc 'v=$'"'"'a\tb'"'"'; echo "长度=${#v}（一个 tab 只算 1 个字符）"; printf "%s\n" "$v" | sed -n l'
runc 'echo $'"'"'\x41\101B'"'"''
runc 'v=hi; echo $'"'"'v=$v 变量不展开，它只管反斜杠'"'"''
runc 'IFS=$'"'"'\n'"'"'; v=$(printf "a b\nc d"); for w in $v; do echo "词=[$w]"; done'
note '# 为什么它重要：IFS、sort 的分隔符、printf 的参数这些位置你需要「真一个制表符/换行」，'
note '#   而不是反斜杠加字母。sed -n l 那行把 tab 打回成反斜杠 t 给你看，就是交叉验证。'
note '# 它不认变量（上面倒数第二行），在 dash 里也不工作（第 01 章实测：dash 原样留下这一串）。'

# ============================================================================
banner "09 word splitting：不带引号的变量是被「切」的"
# ============================================================================
runc 'v="a  b   c"; bash seg.sh $v'
runc 'v="  a b  "; bash seg.sh $v'
runc 'v="a b"; bash seg.sh "$v"'
runc 'v="a b"; echo "拼接前后加字也还是两个词：前${v}后"; bash seg.sh 前${v}后'
note '# 连续的 IFS 空白算一个分隔符、首尾空白直接丢掉 —— 这两条决定了「值里有几个空格」'
note '# 和「程序拿到几个词」永远对不上，别想用空格排版。'
note '# 最阴的一种：把整条命令存进变量。变量值里的引号不再是引号，只是普通字符：'
runc 'cmd="bash seg.sh \"a b\" c"; echo "整串是：[$cmd]"; $cmd'
note '# ↑ seg.sh 收到 3 个词，第一个是 "a：引号被当成文本跟着进去了。正解是函数，不是变量。'

# ============================================================================
banner "10 IFS：切分规则本身就是个变量（空白 / 普通字符 / 空 / 未设）"
# ============================================================================
runc 'v="a:b:c"; IFS=:; set -- $v; echo "IFS 是冒号时：词数=$# 三格=[$1][$2][$3]"'
runc 'v="a::b"; IFS=:; set -- $v; echo "词数=$# 三格=[$1][$2][$3] ← 中间那个空字段保住了"'
runc 'v="  a  b  "; IFS=x; set -- $v; echo "IFS=x（不含空格）词数=$# 第一格=[$1]"'
runc 'IFS=; v="a b c"; bash seg.sh $v'
runc 'unset IFS; v="a b c"; bash seg.sh $v'
runc 'p="/usr/bin:/bin:/usr/local/bin"; IFS=:; for d in $p; do echo "[$d]"; done'
note '# 四条本机实测的规则：'
note '#   ① IFS 里的空白字符（空格 tab 换行）：连续的算一个分隔符、首尾丢弃；'
note '#   ② 非空白字符（冒号逗号之类）：一个字符切一次，相邻两个切出一个空字段，首尾不丢弃；'
note '#   ③ IFS 设成空字符串＝ 完全不切；unset IFS ＝ 回到默认三个空白 —— 这两件事不一样；'
note '#   ④ 前缀赋值（IFS=x 命令 …）**不影响这一条命令自己的分词**（下面实测）：'
runc 'v="a b c"; IFS=: bash seg.sh $v'
runc 'v="a b c"; IFS= bash seg.sh $v'
note '# ↑ 两条都还是按默认的空格切成 3 个词：前缀的 IFS 只对「被调命令的环境」生效，'
note '#   而分词发生在把它调起来**之前**的当前 shell 里。要改分词就得单独一句 IFS= 。'

# ============================================================================
banner '11 "$*" 和 "$@"：四格矩阵逐项实测（本书最容易写错的一格）'
# ============================================================================
runc 'bash args_matrix.sh "a b" c "" d'
note '# 一句话记住："$@" = 一格不少地原样转发（包括空的那格）；'
note '#   "$*" = 用 IFS 的第一个字符把它们粘成一格；裸用的 $@ 和 $* 都还会被再切一刀（空的那格掉地上）。'
runc 'f() { printf "词数=%d：" $#; printf "[%s]" "$@"; printf "\n"; }; v="a b c"; echo "传给函数时："; f $v; f "$v"; f "${v% *}" "${v#* }"'
note '# 再往下一层：把「已经收到的参数」转发给函数时，四种写法的词数（forward.sh 就是这四句）：'
cat > forward.sh <<'FWD'
f() { printf '收到词数=%d：' $#; printf '[%s]' "$@"; printf '\n'; }
set -- "a b" "c d"
printf '%s\n' '转发 "$@" 时：'
f "$@"
printf '%s\n' '转发 "$*" 时：'
f "$*"
printf '%s\n' '裸转发 $@ 时：'
f $@
printf '%s\n' '裸转发 $* 时：'
f $*
FWD
runc 'cat forward.sh'
runc 'bash forward.sh'

# ============================================================================
banner "12 真实事故：文件名带空格、带 * 的时候会发生什么"
# ============================================================================
note '# 还是 03 节那个 files/ 目录（my file.txt / we*ird.txt / aa.txt / ab.txt / A.txt / B.txt / b1.log）：'
