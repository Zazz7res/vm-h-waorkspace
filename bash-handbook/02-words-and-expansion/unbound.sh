#!/usr/bin/env bash
# ============================================================================
# unbound.sh —— 变量名拼错时的两种世界：默认「安静地当成空字符串」，
#               set -u 之后「当场报错并退出」。
#
#   本脚本**自己** set -u，所以它只会跑到出错那一行就退出。
#   demo.sh 的主体没有 set -u（第 01 章同款约定，要能继续演示下一节），
#   这里的 -u 只作用于这个被 bash 重新起的进程，不会传染给 demo 其余部分。
# ============================================================================

set -u

TARGET_DIR=data            # 一个「正确的」变量：后面拼错的就是它的名字
printf '设过的变量读得到：[%s]\n' "${TARGET_DIR}"

# 下一行故意把名字拼错（TARGET_DIR 少写一个 R → TARGET_DI），
# 这正是新手最常见的 bug：脚本里出现两个长得几乎一样的名字。
printf '拼错的变量：[%s]\n' "${TARGET_DI}"

printf '如果你看到这一行，说明上一行没炸（本次运行里不会出现这句）\n'
