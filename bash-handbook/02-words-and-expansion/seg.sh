#!/usr/bin/env bash
# ============================================================================
# seg.sh —— 本章的核心取证工具：把「展开并分词之后到底剩几个词」打印出来。
#
#   你在 README 里看到的每一句 bash seg.sh ...，屏幕上第一行「参数个数=N」
#   就是 N 个词。为什么它能当尺子？因为它内部只做两件事：
#     1) 用 "$#" 数「bash 递给我的 argv 有几格」
#     2) 用 "$@" 逐格打印（"$@" 是「原样转发所有参数」，一格不多一格不少）
#   所以「括号里是空的」和「根本没有这个括号」是两件不同的事，这里看得清清楚楚。
#
#   用法：bash seg.sh 你的写法
#   注意：调用方写的是 bash seg.sh $v，$v 已经被调用方那个 shell 切过一刀了，
#         seg.sh 只能看见切完的结果 —— 这正是我们要观测的东西。
# ============================================================================

printf '参数个数=%d\n' "$#"

i=1
for a in "$@"; do
    # %s 不解释反斜杠；两边加 [ ] 是为了让「空参数」也现形（显示成 []）
    printf '  %d: [%s]\n' "$i" "$a"
    i=$((i + 1))
done
