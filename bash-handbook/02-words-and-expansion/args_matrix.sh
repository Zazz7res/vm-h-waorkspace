#!/usr/bin/env bash
# ============================================================================
# args_matrix.sh —— $* 与 $@ 的「四格矩阵」逐项实测
#
#   bash args_matrix.sh "a b" c "" d
#
#   为什么全写在脚本主体里、不包成函数？
#   因为函数会重新切一遍参数（f() { ... $@ ... } 里的 $@ 是函数自己的参数），
#   传进函数的那一刻就已经分好词了，观测不到「$@ 裸用会被切成几个」这件事。
#
#   数词的办法：( set -- <某种写法> ; 打印 $# 和每一格 )
#   子 shell 里重新 set --，$# 就是「这种写法在 IFS 作用下变成了几个词」。
# ============================================================================

printf '传进来的参数个数=%d（前两个是 "a b" 和 c，看调用方怎么写）\n' "$#"
printf '当前 IFS 是：%q\n' "$IFS"

printf '\n== IFS 为默认（空格 tab 换行）时 ==\n'
( set -- "$@"; printf '  %-6s 词数=%s：%s\n' '"$@"' "$#" "$(printf '[%s]' "$@")" )
( set -- "$*"; printf '  %-6s 词数=%s：%s\n' '"$*"' "$#" "$(printf '[%s]' "$@")" )
( set -- $@;   printf '  %-6s 词数=%s：%s\n' '$@'   "$#" "$(printf '[%s]' "$@")" )
( set -- $*;   printf '  %-6s 词数=%s：%s\n' '$*'   "$#" "$(printf '[%s]' "$@")" )

printf '\n== 换成 IFS=: 之后（同一次调用，只是 IFS 变了）==\n'
IFS=:
( set -- "$@"; printf '  %-6s 词数=%s：%s\n' '"$@"' "$#" "$(printf '[%s]' "$@")" )
( set -- "$*"; printf '  %-6s 词数=%s：%s\n' '"$*"' "$#" "$(printf '[%s]' "$@")" )
( set -- $@;   printf '  %-6s 词数=%s：%s\n' '$@'   "$#" "$(printf '[%s]' "$@")" )
( set -- $*;   printf '  %-6s 词数=%s：%s\n' '$*'   "$#" "$(printf '[%s]' "$@")" )

printf '\n== IFS=（空字符串）：四格全测一遍，看带引号的两格动不动 ==\n'
IFS=
( set -- "$@"; printf '  %-6s 词数=%s：%s\n' '"$@"' "$#" "$(printf '[%s]' "$@")" )
( set -- "$*"; printf '  %-6s 词数=%s：%s\n' '"$*"' "$#" "$(printf '[%s]' "$@")" )
( set -- $@;   printf '  %-6s 词数=%s：%s\n' '$@'   "$#" "$(printf '[%s]' "$@")" )
( set -- $*;   printf '  %-6s 词数=%s：%s\n' '$*'   "$#" "$(printf '[%s]' "$@")" )
