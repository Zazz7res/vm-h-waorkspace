#!/usr/bin/env bash
# ============================================================================
# qmark.sh —— ${v:?提示语} 在**脚本里**到底会发生什么（报错原文 + 当场结束）
#
#   和 bash -c 里跑的区别是：这里报错会带上**文件名和行号**，
#   而且脚本从这一行起一行都不再执行（退出码 1）。
#   生产脚本里有人用它做「必填参数」检查，看的就是这两件事。
# ============================================================================

printf '这行能打印出来（说明报错之前的代码已经执行了）\n'

v=""                       # 设过，但是空 —— 对 :? 来说「空」等同于「没设」
printf '这行也能打印出来，紧接着下一行就要炸\n'

echo "取值：${v:?v 必须有值，否则这里不能跑}"

printf '这一行永远看不到（脚本已经在上面退出了）\n'
