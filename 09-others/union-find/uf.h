#ifndef UF_H
#define UF_H

/*
 * ============================================================================
 * 并查集 Union-Find（也叫 Disjoint Set Union，简称 DSU）—— 本文件的"菜单"
 * ============================================================================
 *
 * 【它解决什么问题】
 *   有一堆东西，我们只知道"谁和谁是一伙的"，不知道具体分成了几伙。
 *   两种操作反复交替出现：
 *     1) union(a, b)：把 a 和 b 所在的两个集合合成一个
 *     2) find(a)    ：问"a 到底属于哪个集合"（拿一个编号当代表）
 *   并查集就是把这两件事都做到"几乎常数时间"的唯一结构。
 *
 * 【它长什么样 —— 一句话】
 *   两个 int 数组：parent[] 和 rank[]。没有链表、没有树节点、没有 malloc 一堆小块。
 *   每个集合用"一棵树"表示，树的根节点那个下标，就是这个集合的"名字"。
 *
 *      parent[i] = i 的父亲是谁；如果 parent[i] == i，说明 i 就是根。
 *
 *      0 ← 1        意思：1 的父亲是 0，根是 0，所以 0 和 1 是同一个集合
 *      集合的编号 = 根的下标 = 0
 *
 * 【为什么"根"能当集合编号】
 *   同一个集合里的所有点，沿 parent 往上爬，最后都会停在同一个根上。
 *   所以"是不是一个集合"就等价于"爬到的根是不是同一个"，一次比较就判完了。
 *
 * 【两个让它飞起来的关键优化】
 *   A. 路径压缩 path compression：find 的时候，把这一路爬过的点全部直接挂到根上。
 *      → 树被压扁成两层，下次再爬一步就到顶。
 *   B. 按秩合并 union by rank：合并时让"矮树"挂到"高树"下面。
 *      → 树根本长不高，深度最多 log n。
 *   两个一起用，复杂度是 O(α(n))。α 是反阿克曼函数，增长慢到离谱：
 *   n 大到宇宙原子总数，α(n) 还是 5。**工程上直接当常数用，别去纠结它的数学**。
 *
 * 【注意】本文件所有元素都是 int，下标从 0 开始，0 .. n-1。
 *   并查集本身不在乎元素"叫什么"，只要能把元素映射成 0..n-1 的下标就行
 *   （例如题目给的是城市编号 1001/2005，就自己开一个 map 转成 0/1，这里不讲泛型）。
 */

/* 演示时最多用多少个元素。真实项目里由 n 决定，这里只是为了打印排版整齐。 */
#define UF_MAX_N 12

/*
 * 一个并查集 = 这两条数组 + 两个记账用的数字。
 * 用结构体捆起来，是为了防止"传了 parent 忘了传 n"这种经典事故。
 */
typedef struct {
    int *parent;      /* parent[i]：i 的父亲的下标；parent[i]==i 表示 i 是根 */
    int *rank;        /* rank[i]：只在"根"上有意义 —— 以 i 为根的这棵树的高度估计 */
    int n;            /* 一共有几个元素，合法下标是 0 .. n-1 */
    int components;   /* 当前还剩几个集合（连通分量）。每成功合并一次就 -1 */
    long long walks;  /* 统计用：上一次 find 一共顺着 parent 爬了几条边 */
} UF;

/* ---------- 生命周期 ---------- */

/* 造一个 n 个元素的并查集：每个人各自一个集合，parent[i]=i，rank[i]=0
 * 返回 0 表示成功，-1 表示内存申请失败。 */
int  uf_init(UF *uf, int n);

/* 还内存。申请了就必须还，这是本仓库的铁律。 */
void uf_free(UF *uf);

/* 推倒重来：全部恢复成"每个点各自成一棵树"，但不再重新 malloc */
void uf_reset(UF *uf);

/* ---------- 核心两件事 ---------- */

/* 【朴素 find，不压缩】沿着 parent 一路爬到根，顺便把爬过的整条路抄到 path_out 里。
 * 存在的唯一目的：让你"看见"路径长什么样。
 *   path_out     ：长度为 path_cap 的数组，用来接收路径（path_out[0]=起点，最后是根）
 *   path_cap     ：那个数组能装几个
 *   path_len_out ：出来时告诉你实际抄了几个点；不想要就传 NULL
 * 返回值：根的下标 */
int uf_find_naive(UF *uf, int x, int path_out[], int path_cap, int *path_len_out);

/* 【带路径压缩的 find】递归版，爬的同时把每个点直接挂到根上。正式代码用这个。 */
int uf_find(UF *uf, int x);

/* 【带优化】按秩合并：矮树挂到高树下面，一样高时任选一边挂并把 rank +1。
 * 返回 1 = 真的合并了两个集合（components 减 1）
 * 返回 0 = a、b 本来就在一个集合里，什么也没改（这个 0 在很多应用里非常有用！）
 * 返回 -1 = 下标非法 */
int uf_union(UF *uf, int a, int b);

/* 【无优化】故意把 a 的根挂到 b 的根下面，不看高度 —— 专门用来演示"会退化成一条链" */
int uf_union_naive(UF *uf, int a, int b);

/* 判 a、b 是否在同一集合。内部就是比一下两个根。 */
int uf_connected(UF *uf, int a, int b);

/* 还剩几个集合。O(1)，因为合并时一直在记账。 */
int uf_component_count(const UF *uf);

/* ---------- 辅助 / 打印 ---------- */

/* 真实树高（递归算每个根下面最深几层），用来对比"有没有优化"的差别 */
int uf_tree_height(const UF *uf, int root);

/* 打印整个 parent 数组和 rank 数组 —— 每次 union/find 之后都调它，森林变化看得见 */
void uf_print_parent_array(const UF *uf, const char *tag);

/* 把森林画出来（缩进表示父子关系），根用 <根> 标出 */
void uf_print_forest(const UF *uf);

#endif /* UF_H */
