#ifndef SEGTREE_H
#define SEGTREE_H

/*
 * ============================================================================
 * 线段树 segment tree（带懒标记 lazy propagation）—— 本文件的"菜单"
 * ============================================================================
 *
 * 【它解决什么问题】
 *   一个 int 数组，反复做两件事，而且两件都很多：
 *     1) 查询任意区间的和：a[2] + a[3] + a[5] + a[8]
 *     2) 修改任意区间：a[3..7] 每个数都 + 5
 *   树状数组（BIT）只擅长"单点改 + 前缀查"。一旦"改的也是区间"，BIT 就别扭了：
 *   老老实实逐个 update 就是 O((R-L+1) log n)，区间一大就等于退化。
 *   线段树：**区间查询 O(log n)，区间修改也 O(log n)**。
 *
 * 【它的想法就一句话】
 *   把"区间"当成节点。叶子 = 长度为 1 的区间（就是单个元素），
 *   内部节点 = 左孩子的区间 + 右孩子的区间，所以节点的值 = 两个孩子相加。
 *   任何一段区间都能被拆成"树上不多于 O(log n) 个完整节点" —— 查询就只加这几个，别进去。
 *
 *      [1,8]
 *      /    \
 *   [1,4]   [5,8]
 *   /  \     /   \
 * [1,2][3,4][5,6][7,8]     ← 每一层的区间长度减半 ⇒ 树高 log n
 *  /\  /\  ...
 *
 * 【为什么用数组存树、为什么开 4n】
 *   节点 i 的左孩子是 2i、右孩子是 2i+1（下标从 1 开始）。这样不用一个指针，纯数组当树。
 *   2n 不够！只有 n 正好是 2 的幂时 tree 才"满"，此时最后一层从 n+1 到 2n，2n 刚好。
 *   n 不是 2 的幂时树不满但编号会往两边歪，最大编号能冲到 4n 附近。
 *   保险起开 4n —— 实测最大编号能远超 2n（n=6 时要 13 格，比 2n=12 还多 1 格；n=10 要 25 格，
 *   而 2n 只给 20 格），4n+5 是公认安全上界。多花点内存，换来"永远不会越界写坏别人的内存"。
 *   本节 main.c 里会把每个 n 的实际最大编号打出来，眼见为实。
 *
 * 【懒标记 lazy —— 全章最难，先给结论】
 *   区间修改时，如果这段正好被某个节点完整盖住，就**只改这个节点**，
 *   并把这个"欠着没往下传的操作"记在 lazy[node] 里。孩子暂时不动。
 *   等到以后**真的要用到孩子**时（查询往下走 / 修改往下走），才把欠账补给孩子 —— 这叫 pushdown。
 *   一句话：lazy[node] = "我自己已经改好了，但我这些儿子孙子还不知道"。
 *
 *   为什么查询和更新的路上都要 pushdown？segtree.c 里 pushdown 上方画了"还账前 / 还账后"的对比图。
 *
 * 【本文件元素一律 int，数组下标 1..n】
 */

typedef struct {
    int *sum;         /* sum[node]：这个节点代表的区间的和（已经算上了挂在自己身上的 lazy） */
    int *lazy;        /* lazy[node]：欠给孩子们的"每人该加多少"。0 = 没欠账 */
    int *a;           /* 原数组副本（1..n）。**只给朴素版用**：线段树相关的函数一律不碰它 */
    int  n;           /* 原数组长度 */
    int  trace;       /* 1 = 把递归走向、pushdown 过程打印出来；0 = 安静。默认 0 */
    long long visits; /* 本次操作访问了多少个节点（和朴素版比谁干的活少，用它说话） */
} SegTree;

/* ---------- 生命周期 ---------- */

/* 用 src[0..n-1] 建树（内部会挪成 1 起点存进 a[]）。返回 0 成功，-1 失败。 */
int  st_init(SegTree *t, const int *src, int n);
void st_free(SegTree *t);

/* ---------- 线段树的三个操作 ---------- */

/* 区间加：a[L..R] 每个数 +v。O(log n) 个节点被真正改动，剩下的欠在 lazy 里。 */
void st_range_add(SegTree *t, int L, int R, int v);

/* 区间和查询：返回 a[L..R] 的和。沿途该 pushdown 的都会 pushdown。 */
int  st_range_sum(SegTree *t, int L, int R);

/* 单点加：a[i] += delta。本质就是"区间 [i,i] 加 delta"，只是把区间缩成一个点。
 * 想做"把 a[i] 改成 v"？先问出当前值再算差：
 *   int cur = st_range_sum(t, i, i);   st_point_add(t, i, v - cur);
 * （别忘了朴素副本 a[] 也要同步：st_naive_range_add(t, i, i, v - cur)） */
void st_point_add(SegTree *t, int i, int delta);

/* ---------- 朴素版（对拍用，故意写得笨） ---------- */

/* 朴素区间和：for 循环把 a[L..R] 加起来，O(n)。*adds_out 带回"加了几次"。 */
int  st_naive_range_sum(const SegTree *t, int L, int R, int *adds_out);

/* 朴素区间加：for 循环把 a[L..R] 每个都 +v，O(n)。
 * ⚠ 它和 st_range_add 是**两套互不知情的实现**，都只动自己的数据：
 *   st_range_add 只动 sum[]/lazy[]，st_naive_range_add 只动 a[]。
 *   两个都调、再比结果，才是真正在给实现挑错。 */
void st_naive_range_add(SegTree *t, int L, int R, int v);

/* ---------- 打印 / 辅助 ---------- */

/* 缩进打印整棵树：每个节点显示"我管哪段区间、当前的和、还欠多少（lazy）"。
 * 区间被切成一段一段、lazy 挂在哪个节点上，全都能看见。 */
void st_print_tree(const SegTree *t);

/* 只打印那些"挂着欠账"的节点，树很大时用它快速定位 lazy 在哪。 */
void st_print_lazy(const SegTree *t);

/* 【为什么是 4n 不是 2n】给定 n，返回建这棵树时**实际用到的最大数组下标**。
 * 纯算下标递推关系，不申请任何内存。拿它和 2n、4n 一比就懂了。 */
int  st_max_node_index(int n);

#endif /* SEGTREE_H */
