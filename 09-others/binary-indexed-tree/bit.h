#ifndef BIT_H
#define BIT_H

/*
 * ============================================================================
 * 树状数组 Binary Indexed Tree / Fenwick Tree —— 本文件的"菜单"
 * ============================================================================
 *
 * 【它解决什么问题】
 *   一个 int 数组，反复做两件事：
 *     1) 改一个数：a[3] += 5
 *     2) 查前缀和：a[1] + a[2] + ... + a[i]（有了前缀和就能算任意区间和）
 *   两个"笨办法"都只快一头：
 *     存原数组    ⇒ 改 O(1)，但查前缀和要把 i 个数全加一遍 O(n)
 *     提前存前缀和 ⇒ 查 O(1)，但改一个数要把后面所有前缀和都重算 O(n)
 *   树状数组：**两个方向都是 O(log n)**，而且代码只有 6 行、常数极小、好写好查。
 *
 * 【它凭什么两个都快 —— 一句话】
 *   再开一条数组 tree[]，让 tree[i] 负责存"一小段连续的原数组元素之和"，
 *   这段的长度刚好等于 lowbit(i) = i & (-i)，也就是 i 的二进制里最低那个 1 代表的值。
 *   于是任何一个前缀 [1..i] 都能被**不超过 log n 段**这样的小区间拼出来 ——
 *   拼的过程就是 `i -= i & (-i)`，也就是不断跳到"上一个覆盖点"。
 *   反过来，一个 a[i] 被哪些格子记着，就是 `i += i & (-i)` 一路跳上去 —— 修改时沿这条链加一下就行。
 *
 * 【覆盖图 —— 整个结构的灵魂，先记住这张图】（n = 8，▓ 的右端一定对齐到自己的下标）
 *
 *     原始下标 :   1     2     3     4     5     6     7     8
 *                 ─────────────────────────────────────────────
 *     tree[1]  :   ▓                                         盖 a[1..1]  长 1
 *     tree[2]  :   ▓     ▓                                   盖 a[1..2]  长 2
 *     tree[3]  :         ▓                                   盖 a[3..3]  长 1
 *     tree[4]  :   ▓     ▓     ▓     ▓                       盖 a[1..4]  长 4
 *     tree[5]  :               ▓                             盖 a[5..5]  长 1
 *     tree[6]  :               ▓     ▓                       盖 a[5..6]  长 2
 *     tree[7]  :                     ▓                       盖 a[7..7]  长 1
 *     tree[8]  :   ▓     ▓     ▓     ▓     ▓     ▓     ▓     ▓  盖 a[1..8] 长 8
 *
 *   看三件事：
 *     · 每个格子负责的**右端点就是自己的下标 i**，左端点是 i - lowbit(i) + 1，长度 = lowbit(i)。
 *     · 想凑出前缀 [1..7]：7 → 6 → 4 → 0，正好 tree[7]+tree[6]+tree[4] = a[7] + a[5..6] + a[1..4]，
 *       一步不漏一步不重。这个 `i -= i & (-i)` 叫"跳到上一个覆盖点"（parent 方向）。
 *     · 反过来 a[3] 被 tree[3]、tree[4]、tree[8] 三格记着，靠 `i += i & (-i)` 一路跳上去
 *       （next 方向），修改时沿这条链加一下就完事。
 *
 * 【下标必须从 1 开始！】
 *   lowbit(0) = 0 & (-0) = 0 ⇒ `i += i & -i` 会永远停在 0，`i -= i & -i` 也停在 0，**死循环**。
 *   所以 tree[0] 这一格是空的、永远不用；a[0] 也不用。原始数组若从 0 编号，进来时先 +1。
 *
 * 【本文件所有元素都是 int，下标约定 1..n】
 */

typedef struct {
    int *tree;            /* tree[1..n] 在用，tree[0] 空着不用（见上面那条死循环警告） */
    int *a;               /* 原始数组的副本，也按 1..n 存。只干两件事：打印 + 给朴素版对拍 */
    int  n;               /* 元素个数 */
    int  trace;           /* 1 = 打印每次操作跳过了哪些格子；0 = 安静模式。默认 0 */
    long long touches;    /* 【累计】访问过几个 tree 格子；用 bit_reset_touches 归零。
                             一次 range_query 会走两趟前缀查，所以这个数会把两趟都算进去 */
} BIT;

/* ---------- 生命周期 ---------- */

/* 用 src[0..n-1]（C 的 0 起点数组！内部会自动挪到 1..n）建树。
 * src 传 NULL 表示"全 0 起步"。返回 0 成功，-1 失败。 */
int  bit_init(BIT *b, const int *src, int n);
void bit_free(BIT *b);

/* 把访问计数归零，开始新一轮统计（和朴素版比"谁碰的格子少"时用） */
void bit_reset_touches(BIT *b);

/* ---------- 核心两件事 ---------- */

/* 单点加：a[i] += delta，并把受影响的格子一路更新。i 从 1 开始。
 * 注意是"加 delta"不是"设成某个值"。要设值就自己算差：
 *   bit_update(b, i, new_value - bit_get(b, i)); */
void bit_update(BIT *b, int i, int delta);

/* 读某个位置当前存的值（读内部那份普通数组副本，O(1)）。
 * 不想存副本的话，等价的纯树状数组写法是 bit_range_query(b, i, i)。 */
int  bit_get(const BIT *b, int i);

/* 前缀和：返回 a[1] + ... + a[i]。i = 0 时返回 0（这是递归的"空地"，也是正确性关键）。 */
int  bit_query(BIT *b, int i);

/* 区间和：a[l] + ... + a[r] = query(r) - query(l-1)。 */
int  bit_range_query(BIT *b, int l, int r);

/* ---------- 对拍 / 教学辅助 ---------- */

/* 朴素版区间和：老老实实 for 循环把 a[l..r] 加起来，用来验证上面的实现是对的。
 * 顺手把"自己加了几次"写进 *adds_out，方便对比访问格子数。 */
int  bit_naive_range_sum(const BIT *b, int l, int r, int *adds_out);

/* lowbit(i) = i & (-i)。i = 0 时返回 0 —— 这就是下标不能从 0 用的原因。 */
int  bit_lowbit(int i);

/* 打印当前状态：a[] 和 tree[] 两行，外加每个 tree 格子负责的区间 */
void bit_print_cells(const BIT *b, const char *tag);

/* 画那张"每个格子负责覆盖哪几个原始元素"的经典条形图（不需要 BIT 实例，纯按下标算） */
void bit_print_coverage_chart(int n);

/* ---------- 应用：逆序对个数 ---------- */

/* 用树状数组数逆序对：统计所有"i 在 j 左边，但 a[i] > a[j]"的下标对。
 * 做法是从右往左扫，把 BIT 的下标当"值"用（频率树）：
 *     query(a[i]-1) ⇒ 已经扫过的（也就是当前元素右边的）、比 a[i] 小的有几个
 *     update(a[i], +1) ⇒ 把这个值登记一次
 * freq 由调用者准备好：bit_init(freq, NULL, max_value)，用完自己 bit_free。
 * src[0..n-1] 里的值必须是 1..max_value（因为要把值直接当 BIT 下标）。
 * 把 freq->trace 设成 1，就能看见每一步的累计过程。
 * 返回逆序对总数（用 long long 防 n 大时溢出 int）。 */
long long bit_count_inversions(BIT *freq, const int *src, int n, int max_value);

#endif /* BIT_H */
