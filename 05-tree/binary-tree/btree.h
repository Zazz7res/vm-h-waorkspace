#ifndef BTREE_H
#define BTREE_H

/*
 * ===================================================================
 * 这个头文件是"菜单"：只写有哪些操作，不写怎么做。
 * 具体实现全在 btree.c 里，每个函数上方都有大段人话解释。
 * ===================================================================
 *
 * 【本节研究的对象：普通二叉树（不带任何顺序规则）】
 *
 *   "二叉"就一句话：每个节点最多只有两个孩子，分别起名叫 left 和 right。
 *   注意这里"普通"两个字：我们**不要求**左边的值比根小、右边的值比根大。
 *   值怎么摆完全随意 —— 它只是一堆用指针连起来的盒子。
 *   （加上"左 < 根 < 右"这条规矩，就是下一节的 BST 二叉搜索树。）
 *
 * 【一个节点长这样】
 *
 *        ┌──────────┬───────────┬───────────┐
 *   Node │ val: 2   │ left: ────┼──► 左子树  │
 *        │          │ right: ───┼──► 右子树  │
 *        └──────────┴───────────┴───────────┘
 *   两个指针就是两张"纸条"，上面写着孩子的地址；孩子为空就写 NULL(0)。
 *
 * 【为什么"没有顺序"的二叉树还值得学？】
 *   1) 它是所有树结构的地基：BST、AVL、红黑树、堆、Trie、线段树，
 *      节点定义和"递归地处理左右子树"这套思路全都一样。
 *   2) 遍历（前/中/后/层序）是二叉树唯一"读它"的方式，也是面试重灾区。
 *   3) 文件系统目录、表达式求值 a+b*c、HTML DOM 树、编辑历史，
 *      本质都是"不带顺序规则的二叉树/多叉树"。
 *
 * 【本文件刻意不跨目录引用任何东西】
 *   层序遍历需要一个队列，前/中/后序的迭代版需要一个栈，
 *   它们都以 static 小工具的形式写在 btree.c 里，**只存 Node ***，
 *   不去 #include ../04-queue 或 ../03-stack 的代码。
 *   原因：Makefile 是按目录独立编译的，跨目录 include 会直接编译失败。
 */

/* -------------------------------------------------------------------
 * 节点定义：整个数据结构就只有这 12 个字节左右的三个字段
 *
 * 为什么要写成 `struct Node { struct Node *left; ... }` 这种自引用？
 *   因为在定义 Node 的时候 Node 这个名字还不存在，不能用 Node *left;
 *   但 struct Node * 是"指针"，指针大小固定（本机 8 字节），
 *   编译器不需要知道 Node 内部长什么样就能放行 —— 这是 C 的规矩。
 *
 * 末尾的 `} Node;` 是 typedef 的简写：以后写 Node 就等于写 struct Node。
 * ------------------------------------------------------------------- */
typedef struct Node {
    int val;             /* 存的元素：本项目统一 int，不搞 void* 泛型 */
    struct Node *left;   /* 左孩子的地址；没有左孩子就是 NULL */
    struct Node *right;  /* 右孩子的地址；没有右孩子就是 NULL */
} Node;

/* build_tree_from_marks 用的"空位记号"：数组里写 -1 表示这个位置是空孩子 */
#define MARK_EMPTY (-1)

/* 迭代版遍历、层序遍历内部数组的容量。
 * 教学用的树都很小（几十个节点顶天了），写死容量最直观；
 * 越界时函数会打印错误并停下，而不是悄悄踩内存。 */
#define TREE_HELPER_CAP 128

/* ===================================================================
 * 1. 造节点 / 建树（两种做法都会演示）
 * =================================================================== */

/* 造一个孤零零的新节点：值 = val，左右孩子都置 NULL。
 * 只 malloc 一次，失败就返回 NULL（调用者必须判空）。 */
Node *node_new(int val);

/* 做法 A「手工连指针」：把一棵写死的固定树一根根指针接出来。
 *
 *          1
 *        /   \
 *       2     3
 *      / \     \
 *     4   5     6
 *
 * 返回值是根节点地址（就是 1 那个盒子）。 */
Node *build_fixed_tree(void);

/* 做法 B「递归建树」：按"前序 + 空位记号"的整数序列造出一模一样的树。
 * 例如上面这棵树写成序列就是：
 *   1, 2, 4, -1, -1, 5, -1, -1, 3, -1, 6, -1, -1
 * 读进去的顺序 = 递归展开的顺序，所以能唯一还原出树形。
 * n 是数组长度；调用者负责 free 返回的树。 */
Node *build_tree_from_marks(const int marks[], int n);

/* ===================================================================
 * 2. 四种遍历
 *
 * 约定：前/中/后序把访问到的值【依次追加】到调用者给的数组 out 里，
 *      *n_out 既是"已经写了几个"也是"下次从哪个下标写"。
 *      这样 main.c 能把递归版和迭代版的结果直接对比，一眼看出对不对。
 *      调用前把 *n_out 置 0，out 至少要有 tree_count(root) 格。
 * =================================================================== */

/* 递归三兄弟：差别只有一行 —— printf/写入自己那一步放在递归的哪一侧 */
void preorder(const Node *root, int out[], int *n_out);   /* 根 → 左 → 右 */
void inorder(const Node *root, int out[], int *n_out);    /* 左 → 根 → 右 */
void postorder(const Node *root, int out[], int *n_out);  /* 左 → 右 → 根 */

/* 迭代三兄弟：用 btree.c 里自带的显式栈，结果和递归版完全相同 */
void preorder_iter(const Node *root, int out[], int *n_out);
void inorder_iter(const Node *root, int out[], int *n_out);
void postorder_iter(const Node *root, int out[], int *n_out);

/* 层序遍历（BFS）：用 btree.c 里自带的队列，一层一行打印出来。
 * 上面那棵树的输出是：
 *   第 1 层: 1
 *   第 2 层: 2 3
 *   第 3 层: 4 5 6                                       */
void level_order(const Node *root);

/* ===================================================================
 * 3. 统计与查询（全是"递归地问左右子树要答案，再合并"）
 * =================================================================== */

/* 树的高度/深度：空树算 0，只有一个根点算 1。
 * 公式：height = 1 + max(height(左), height(右)) —— 一行递归。 */
int tree_height(const Node *root);

/* 节点总数：空树 0，否则 1 + 左边的数量 + 右边的数量 */
int tree_count(const Node *root);

/* 叶子数：左右孩子都为 NULL 才算叶子；空树算 0 片叶子 */
int tree_leaf_count(const Node *root);

/* 找值 val：找到就返回那个节点的地址，全树都没有就返回 NULL。
 * 普通二叉树没有顺序，所以只能所有节点都问一遍（最坏 O(n)）。 */
const Node *tree_find(const Node *root, int val);

/* 是否"平衡"：每个节点的左右子树高度差都不超过 1，就返回 1，否则 0。
 * 平衡是"查找快"的前提，也是下一节 AVL/红黑树存在的理由。 */
int tree_is_balanced(const Node *root);

/* 两棵树是否完全相同：形状一样 + 对应位置的值也一样，才返回 1 */
int tree_is_same(const Node *a, const Node *b);

/* ===================================================================
 * 4. 打印与销毁
 * =================================================================== */

/* 把树"横着"打印出来，方框连线看清父子关系：
 *   1
 *   ├─2
 *   │ ├─4
 *   │ └─5
 *   └─3
 *     └─6
 * 为什么是这个方向？因为终端一行是横的、往下走的，
 * 把树顺时针转 90° 正好能让"从上到下"对应"从根到叶子"。 */
void print_tree(const Node *root);

/* 销毁整棵树：后序 —— 先删光左子树、再删光右子树、最后 free 自己。
 * 顺序绝对不能换：前序释放会先 free 掉父节点，
 * 而它的左右孩子地址就存在父节点里 —— 那是在读已归还的内存（use-after-free）。 */
void free_tree(Node *root);

#endif /* BTREE_H */
