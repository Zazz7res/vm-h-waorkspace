#ifndef B_TREE_H
#define B_TREE_H

/*
 * ===================================================================
 * btree.h —— B 树（order 可配，demo 用 m=3）的「菜单」
 * ===================================================================
 * 这个文件【只有声明和图，没有实现】。先看它知道"能点哪些菜"，
 * 想知道"怎么炒的"去翻 btree.c，想看"为什么这么设计"去翻 README.md。
 *
 * -------------------------------------------------------------------
 * 一句话：B 树就是"一个节点能装好几个键、能有好几个孩子"的二叉搜索树
 * -------------------------------------------------------------------
 * 二叉搜索树（BST）每个节点只有 1 个键、2 个孩子；B 树把节点"变宽"：
 * 每个节点最多装 m-1 个键、最多有 m 个孩子（m 叫"阶"，order）。
 *
 *   m=3（本节 demo 用的）就是：一个节点最多 2 个键、最多 3 个孩子。
 *
 * 节点内部长这样（竖线 | 是键，方框外的缝就是"孩子空隙"）：
 *
 *          空隙0      空隙1
 *            │          │
 *            ▼          ▼
 *        ┌───────┬───────┐
 *      ◄─┤  10   │   20  ├─►
 *        └───────┴───────┘
 *          左边都比 10 小   10~20 之间   右边都比 20 大
 *
 *   一个有 k 个键的节点，一定有 k+1 个孩子空隙（包括最左、最右两条边）。
 *   上面这个节点 k=2，所以 3 个空隙：
 *     空隙0 → 子树里所有键 < 10
 *     空隙1 → 子树里所有键在 10 和 20 之间
 *     空隙2 → 子树里所有键 > 20
 *   ⚠ 找"该往哪个空隙钻"的方法：从左到右第一个【严格大于】目标值的键
 *      的下标 i，就钻 child[i]。（README 里有逐步图解）
 *
 * -------------------------------------------------------------------
 * 为什么它是"胖"的？—— 因为磁盘一次只读一整页
 * -------------------------------------------------------------------
 * 内存里的树（红黑树、AVL）追求"每个节点尽量小、树尽量矮"，
 * 但磁盘不给你这个机会：读 1 字节和读 4096 字节，花的钱（寻道+旋转）
 * 几乎一样。所以正确的姿势是【一次读一页，一页要装满有用的键】：
 *
 *   红黑树：1 个 4KB 页里能塞 ~128 个节点，但你一次只用到 1 个
 *   B 树  ：1 个 4KB 页 = 1 个节点，节点扇出 ~300，树高只有 3 层
 *
 *   查 100 万个键里的 1 个：
 *     红黑树 ≈ 20 次随机磁盘读   （每次只用 32 字节，血亏）
 *     B  树  ≈  3 次磁盘读        （README「为什么数据库用 B 树」有完整算式）
 *
 * 这就是 MySQL / PostgreSQL / NTFS / ext4 全部用 B 树家族做索引的根本原因。
 *
 * -------------------------------------------------------------------
 * 本节 B 树的规矩（不变量 invariant）—— 破坏任何一条就不是 B 树了
 * -------------------------------------------------------------------
 *   1. 键在节点内【从小到大】排好，且整棵树中序读出来是全局有序的。
 *   2. 每个节点的键数范围：MIN_KEYS ≤ num_keys ≤ MAX_KEYS
 *      （根节点例外：根可以少到只有 1 个键，甚至空树时 0 个）
 *      非叶子节点的孩子数 = 键数 + 1，且至少 2 个孩子。
 *   3. 所有叶子都在【同一层】—— 这是 B 树"矮"的关键，
 *      也是它和红黑树最大的结构差别（红黑树允许同一层的叶子深浅不一）。
 *   4. 本节实现【不允许重复键】（真数据库里要带 record id 才行，见 README 坑）。
 *
 * -------------------------------------------------------------------
 * 插入的核心一句话（本节最大考点）：满了就劈成三块，中间那块上推
 * -------------------------------------------------------------------
 *   ① 像 BST 一样往下钻，找到一个叶子，把键塞进去（数组中间插要整体右移）。
 *   ② 塞完发现 num_keys = MAX_KEYS + 1（超载一格）→ 分裂：
 *        取中间那个键 X，左半自己留着，右半新建一个节点装，
 *        X 【上推给父亲】，塞进父亲对应的空隙里，成为父亲的键。
 *   ③ 父亲被塞了键之后可能也超载 → 再分裂、再上推……
 *   ④ 一直推到根还是超载 → 造一个新根，树【原地长高一层】。
 *   注意顺序：分裂是"从下往上"发生的（先塞满再劈），跟"预先分裂"写法
 *   方向相反，但结果一模一样。btree.c 的 bt_insert 上方有全过程 ASCII 图。
 *
 * -------------------------------------------------------------------
 * 删除的核心一句话：缺键就找兄弟借，借不到就跟兄弟合并
 * -------------------------------------------------------------------
 *   本节是实现了的（README「删除」小节有借键 / 合并的图）。三条规矩：
 *   ① 删内部节点的键 → 用"左子树最大的键（前驱）"顶替它，
 *      然后去左子树里把前驱删掉 —— 这样就保证真正动手删的永远是叶子。
 *   ② 删完孩子欠键了 → 先看左兄弟能不能借一个（父亲的键当"中转站"下移），
 *      再看右兄弟，都不给 → 父亲键下移当桥，把孩子和兄弟焊成一个节点，
 *      父亲自己少一个键（于是父亲可能又欠键，继续往上传）。
 *   ③ 根被合并到只剩 0 个键 → 根退化成它的唯一孩子，树【矮一层】。
 *
 * -------------------------------------------------------------------
 * 关于"阶 m 可配"
 * -------------------------------------------------------------------
 * 改下面 BTREE_ORDER 一个数字就能换阶（≥3 即可，3 最适合看分裂）。
 * MAX_KEYS / MAX_CHILDREN / MIN_KEYS 都会自动跟着算，数组大小也跟着算，
 * 但 BTREE_ORDER 变大后 demo 输出会很宽，建议只在 3~5 之间试。
 */

/* 阶 m：一个节点最多 m 个孩子、m-1 个键。demo 用 3，分裂看得最清楚。 */
#define BTREE_ORDER 3

/* 一个节点"合法状态下"最多能装几个键（= m-1）。m=3 时是 2。 */
#define BTREE_MAX_KEYS (BTREE_ORDER - 1)

/* 最多几个孩子（= 键数 + 1 的上限 = m）。 */
#define BTREE_MAX_CHILDREN BTREE_ORDER

/* 最少几个键（= ceil(m/2) - 1；用整数写法避免浮点：m/2 向上取整）。
 * m=3 → 1，m=4 → 1，m=5 → 2。低于这个数就叫"欠键（underflow）"。 */
#define BTREE_MIN_KEYS ((BTREE_ORDER + 1) / 2 - 1)

/*
 * B 树节点：全部用数组，一个指针都不套娃（除了指向孩子的指针数组）。
 *
 * ⚠ 两个数组都【故意多开了一格】，这是"先塞满再分裂"写法的必要代价：
 *   key[MAX_KEYS + 1]   ：超载那一瞬间会有 MAX_KEYS+1 个键，
 *                         多开一格才能把溢出的那个先收下，再分裂。
 *   child[MAX_KEYS + 2] ：键最多 MAX_KEYS+1 个时，空隙就是 MAX_KEYS+2 个。
 *   分裂完马上又回到 ≤ MAX_KEYS 个键，多出来的格子空着，不浪费。
 *   （另一种"边往下钻边分裂"的写法能避免超载，见 README 坑 #3。）
 */
typedef struct BTreeNode {
    int key[BTREE_MAX_KEYS + 1];              /* 键，从小到大排好 */
    struct BTreeNode *child[BTREE_MAX_KEYS + 2]; /* 孩子空隙：child[i] 在 key[i-1] 和 key[i] 之间 */
    int num_keys;                             /* 当前有效键个数；孩子个数永远 = num_keys + 1 */
    int is_leaf;                              /* 1 = 叶子（孩子数组全 NULL），0 = 内部节点 */
} BTreeNode;

/* ---------- 1. 建与拆 ---------- */
BTreeNode *btree_new(void);                  /* 建一棵空树：只有一个"0 键的叶子"当根 */
void       btree_free(BTreeNode *node);      /* 后序释放整棵树（谁 malloc 谁 free） */

/* ---------- 2. 查找 ---------- */
/*
 * 查找：probe_out 带回来"访问了几个节点"，在磁盘语境下就等于"读了几次盘"。
 * 这是本节最能体现 B 树价值的数字，main.c 里会专门打印它做对比。
 * 返回 1 = 找到，0 = 没找到。
 */
int btree_search(BTreeNode *root, int key, int *probe_out);

/* ---------- 3. 插入（会打印分裂过程） ---------- */
/* 返回 1 = 插进去了，0 = 键已存在（重复键被忽略），-1 = 内存申请失败 */
int btree_insert(BTreeNode **root, int key);

/* ---------- 4. 删除（会打印借键 / 合并过程） ---------- */
/* 返回 1 = 删掉了，0 = 键不存在，-1 = 内部错误 */
int btree_remove(BTreeNode **root, int key);

/* ---------- 5. 三种视图：把树"打印出来给人看" ---------- */
void btree_print_levels(BTreeNode *root);   /* 按层：第 1 层 [6] / 第 2 层 [2|4] [8|10] ... */
void btree_print_tree(BTreeNode *root);     /* 缩进树形：明确标出每个"孩子空隙" */
void btree_print_inorder(BTreeNode *root);  /* 中序（从小到大）：用来验证"还是有序的" */

/* ---------- 6. 小查询 ---------- */
int  btree_height(BTreeNode *root);         /* 树高（层数），空树返回 0 */
int  btree_count(BTreeNode *root);          /* 树里一共有几个键 */

#endif /* B_TREE_H */
