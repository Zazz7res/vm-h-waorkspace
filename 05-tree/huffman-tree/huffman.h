#ifndef HUFFMAN_TREE_H
#define HUFFMAN_TREE_H

/*
 * ===================================================================
 * huffman.h —— 哈夫曼树 + 哈夫曼编码 的「菜单」
 * ===================================================================
 * 这个文件只有声明和图。实现全在 huffman.c，"为什么这么设计"在 README.md。
 *
 * -------------------------------------------------------------------
 * 本节要解决的那个具体问题
 * -------------------------------------------------------------------
 * 一段文本要存成 0/1。怎么存？
 *
 * 【办法一：定长编码】每个字符都用同样多的比特。
 *   ASCII 就是定长 8 位。若文本里只出现 6 种字符，也仍要 3 位（2^3=8 ≥ 6）。
 *   浪费在哪：出现 1 万次的空格和出现 1 次的 z，付一样多的比特。
 *
 * 【办法二：变长编码】常见的字符用短码，少见的用长码。
 *   直觉上一定省。但如果乱着给，会出问题 —— 这就是全章最重要的一个词：
 *
 *      【前缀冲突】
 *
 *   假设给三个字符编：A=0，B=01，C=10。比特流 "010" 有两种切法：
 *        0 | 10        → A C
 *        01 | 0        → B A
 *   解码器从左往右读，读到 "0" 时【不知道该不该停】—— 因为它可能是 A，
 *   也可能是 B 的开头。同一段比特能解出两句话，压缩就完全白做了。
 *   （加分隔符？分隔符本身也要比特，反而更亏。）
 *
 * 【哈夫曼编码 = 自动生成一种"前缀码"的建树算法】
 *   前缀码（prefix code）定义：**任何一个字符的编码，都不是另一个字符编码的前缀。**
 *   只要把每个字符放在树的【叶子】上，从根到叶子走过的 0/1 串就是它的编码，
 *   那么"一个字符的编码"是从根到某叶子的完整路径，
 *   而"另一个字符的编码"必然在某一叉岔开 —— 谁也包含不了谁。
 *   解码器于是可以闭着眼睛一路读：走到叶子就吐一个字符，然后回根，继续读。
 *   不需要分隔符，不需要停顿，唯一可解。
 *
 *        A ── 0        根
 *        B ── 01      /  \
 *        C ── 1     A     \        ← A 在左叶子：编码就是 "0"
 *                        /   \      B、C 在下一层：编码 "01"、"00"...
 *                       B     C    任意一个都不是另一个的开头 ✓
 *
 * -------------------------------------------------------------------
 * 建树规则（哈夫曼算法，一句话：贪心地把最少的两个先合并）
 * -------------------------------------------------------------------
 *   1. 统计每个字符的出现次数 → 每个字符是一个"权重=次数"的叶子，全部丢进**最小堆**。
 *   2. 从堆里取出【权重最小的两个】节点 a、b，造一个新内部节点：
 *        新节点权重 = a.weight + b.weight，左孩子 = a，右孩子 = b，放回堆里。
 *      （这一步叫"合并"，a、b 的深度各 +1，代价就是它们的权重各多付 1 比特。）
 *   3. 重复第 2 步，直到堆里只剩 1 个节点 —— 那就是根。
 *
 *   为什么"最小堆"是必需的？
 *     第 2 步每轮都要"取两个最小的"。如果每次全表扫描找最小，一轮 O(n)、
 *     总共 O(n²)；用最小堆是 O(log n) 一轮，总共 O(n log n)。
 *     而且"取两个最小的"这种需求，堆就是标准答案（对照 06-heap 的 Top-K）。
 *     ⚠ 本目录必须自包含，所以这里【自己写了一个极简最小堆】
 *        （huffman.c 第 0 组），不去 #include 06-heap —— Makefile 是按目录独立编译的。
 *
 * -------------------------------------------------------------------
 * 带权路径长度 WPL（Weighted Path Length）：衡量这棵树好不好
 * -------------------------------------------------------------------
 *   WPL = Σ(每个叶子的权重 × 该叶子到根的路径长度)
 *       = 编码后这段文本的总比特数（叶子权重 = 该字符出现次数，路径长度 = 码长）
 *   哈夫曼树的性质：在所有前缀码里，哈夫曼树的 WPL **最小**。
 *
 *   两个等价算法（本节都算出来，互相验证）：
 *     ① 定义法：遍历叶子累加 weight × depth。
 *     ② 合并法：把每一次"合并产生的新节点权重"全加起来 —— 结果一模一样。
 *        直觉：合并一次，就意味着这个子树里所有叶子深度都 +1，
 *        贡献的 WPL 正好是它们的权重和 = 新节点权重。
 *
 * -------------------------------------------------------------------
 * 本节的数据结构
 * -------------------------------------------------------------------
 *   HuffNode    —— 树节点：权重 + 叶子字符 + 左右孩子。内部节点的 ch 没有意义。
 *   HuffCodeEntry —— 编码表里的一行：某个字符的频次、码串、码长。用 256 格数组，
 *                    下标就是字符的 ASCII 码，查码 O(1)（不用哈希不用树）。
 *   HuffMinHeap —— 建树用的最小堆，存的是 HuffNode*，比较就是 weight 比大小
 *                    （本仓库硬约定：不写函数指针比较器）。
 */

#define HUFF_CHAR_SET 256      /* 覆盖全部 unsigned char，输入什么字符都不怕 */
#define HUFF_HEAP_CAP 512      /* 堆容量：不同字符最多 256 个，堆里只减不增，512 绰绰有余 */
#define HUFF_MAX_CODE_LEN 64   /* 单个字符的码串上限（256 个字符时最深也就 255，这里给 64 够用）*/
#define HUFF_MAX_BITS 8192     /* demo 的比特流缓冲区容量，超了会报错而不是越界 */

/* ---------- 树节点 ---------- */
typedef struct HuffNode {
    int weight;                 /* 权重：叶子=字符频次，内部节点=左右孩子频次之和 */
    unsigned char ch;           /* 叶子代表的字符；内部节点不用（置 0）*/
    int is_leaf;                /* 1 = 叶子（左右孩子都是 NULL）*/
    struct HuffNode *left;
    struct HuffNode *right;
} HuffNode;

/* ---------- 编码表的一行 ---------- */
typedef struct {
    int  freq;                       /* 出现次数，0 = 这个字符在本段文本里没出现 */
    int  code_len;                   /* 编码长度（比特数）*/
    char code[HUFF_MAX_CODE_LEN];    /* 编码本身，存的是 '0' 和 '1' 这两个字符 */
} HuffCodeEntry;

/* ---------- 本目录自带的极简最小堆（只比 weight，不写比较器）---------- */
typedef struct {
    HuffNode *item[HUFF_HEAP_CAP];
    int size;                        /* 当前节点个数；空堆 size = 0 */
} HuffMinHeap;

/* ---------- 1. 堆：建树的工具 ---------- */
void      huff_heap_init(HuffMinHeap *h);
int       huff_heap_push(HuffMinHeap *h, HuffNode *node);  /* 1 成功，0 堆满了 */
HuffNode *huff_heap_pop(HuffMinHeap *h);                  /* 弹出最小；空堆返回 NULL */
void      huff_heap_dump(const HuffMinHeap *h);           /* 打印堆里现在有哪些权重 */

/* ---------- 2. 建树 + 生成编码表 ---------- */
/*
 * 一步到位：统计频次 → 全部入堆 → 反复合并 → 剩下一个就是根 → 走一遍树填编码表。
 * 全过程打印出来给你看（每轮取走哪两个、合并成多大、堆里还剩什么）。
 *
 * text          : 要压缩的原文（\0 结尾）
 * table         : 调用者给一个 HuffCodeEntry[HUFF_CHAR_SET]，函数填好
 * distinct_out  : 不同字符的个数（算定长编码需要几位要用它）
 * merge_sum_out : 所有"合并产生的新节点权重"之和，它应当 == WPL（经典考点）
 * 返回根节点；调用者负责 huff_free_tree。空文本返回 NULL。
 */
HuffNode *huff_build(const char *text, HuffCodeEntry table[],
                     int *distinct_out, long *merge_sum_out);

/* ---------- 3. 生成/查看树的产物 ---------- */
void huff_print_table(const HuffCodeEntry table[]);   /* 字符 / 频次 / 编码 / 码长 */
void huff_print_tree(HuffNode *root);                 /* 树形，横着画，标权重和字符 */
int  huff_wpl(HuffNode *root);                        /* WPL：定义法，Σ 权重×深度 */

/* 检查这张表是不是真的前缀码：1 = 是，0 = 存在某条编码是另一条的前缀 */
int huff_check_prefix_free(const HuffCodeEntry table[]);

/* ---------- 4. 编码 / 解码：闭环的两个半边 ---------- */
/* 把原文写成 '0'/'1' 字符组成的比特流；*bit_count_out 带回一共多少比特。返回 1 成功 0 溢出 */
int huff_encode(const char *text, const HuffCodeEntry table[],
                char *bits_out, int cap, int *bit_count_out);

/* 拿比特流 + 哈夫曼树，一路走树还原原文（走到叶子就吐字符、回根）。返回还原出的字符数，-1 = 溢出 */
int huff_decode(const char *bits, int bit_count, HuffNode *root,
                char *out, int cap);

/* ---------- 5. 统计小工具 ---------- */
int huff_count_chars(const char *text, int freq_out[HUFF_CHAR_SET]);  /* 统计频次，返回不同字符数 */

/* ---------- 6. 销毁 ---------- */
void huff_free_tree(HuffNode *root);

#endif /* HUFFMAN_TREE_H */
