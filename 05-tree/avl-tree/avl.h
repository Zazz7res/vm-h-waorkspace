#ifndef AVL_TREE_H
#define AVL_TREE_H

/*
 * ===================================================================
 * AVL 树 · 头文件（只是"菜单"，实现全在 avl.c）
 * ===================================================================
 *
 * 【这个文件存在的意义】
 *   你不用在这里读懂 AVL，只需要从这里看清"AVL 一共提供哪几件事"。
 *   真正的大白话讲解、指针怎么动、边界情况，全在 avl.c 的函数上方注释里。
 *   叶子目录是各自独立的：本目录只 include 自己目录里的 .h 和标准库，
 *   所以这里不依赖 05-tree/bst/ 里的任何东西（对比用的朴素 BST 在
 *   同目录的 mini_bst.h 里自己写了一份）。
 *
 * 【AVL 树一句话】
 *   AVL = 会自己做操的二叉搜索树（BST）。
 *   BST 的毛病：数据如果是有序的（1、2、3、4…一个个插进来），树会长成一条
 *   "右斜的链表"，查找从 O(log n) 退化成 O(n)。
 *   AVL 的对策：每插一个节点，就从下往上检查每个节点的"左右子树高度差"，
 *   一旦差到 2，就用一次或两次"旋转"把高度压回去。
 *   代价：每次插入最多 2 次旋转，换来"永远不超过 1.44·log2(n+2) 高"。
 *
 * 【什么叫"高度差最多 1"】
 *   对树里【任何一个】节点：  |左子树高度 - 右子树高度| <= 1
 *   这个差值叫"平衡因子 balance factor"，记作 bf。
 *   bf = +2 或 -2 就说明这个节点已经"塌了"，必须旋转修好。
 *
 * 【为什么节点里要存 height 这个字段】
 *   算平衡因子需要左右子树的高度。有两种办法：
 *     A) 不存，每次现算：h(节点) = 1 + max(h(左), h(右))，递归下去 → 单点 O(n)
 *        插入路径上有 O(log n) 个祖先都要算，总共退化成 O(n log n)。
 *     B) 存：子节点的高度就写在那块内存里，读一下 O(1)。
 *        更新只需在递归"回头"的路上改一行 → 整棵树的修正 O(log n)。
 *   这就是典型的"用 4 字节空间换时间"。注意存的必须是【子树高度】，
 *   不是"深度"：深度要从根往下数（一改一大片），高度只依赖亲孩子（局部可更新）。
 *
 * 【四种旋转为什么刚好是四种】
 *   一个节点失衡，必然是"某一侧被压高了 2"。压高的路径有两条分支：
 *     左孩子的左边变高了   → LL → 一次右旋
 *     左孩子的右边变高了   → LR → 先左旋左孩子，变成 LL，再右旋
 *     右孩子的右边变高了   → RR → 一次左旋
 *     右孩子的左边变高了   → RL → 先右旋右孩子，变成 RR，再左旋
 *   名字里的第一个字母 = 从失衡点出发第一步走哪边，第二个字母 = 第二步走哪边。
 * ===================================================================
 */

/* -------------------------------------------------------------------
 * 节点定义
 *
 * 内存里一个节点长这样（left / right 都是 8 字节的地址，不是盒子）：
 *
 *        ┌───────────────────────────────┐
 *   p ──▶│ value │ left │ right │ height │
 *        └───┬───└──┬───┴───┬───┴────────┘
 *            │      │       │
 *            15     ↓       ↓     ↓ = NULL 表示"这个位置没有孩子"
 *                 左子树  右子树
 * ------------------------------------------------------------------- */
typedef struct AVLNode {
    int             value;   /* 存的元素：本项目约定全部是 int，不搞 void* 泛型 */
    struct AVLNode *left;    /* 左子树根节点地址；比 value 小的都在这边 */
    struct AVLNode *right;   /* 右子树根节点地址；比 value 大的都在这边 */
    int             height;  /* 以【我自己】为根的子树高度：空 = 0，叶子 = 1 */
} AVLNode;

/* ===================================================================
 * 第一组：小工具（不改变树的结构，只读或只更新 height）
 * =================================================================== */

/* 取高度。传 NULL 返回 0 —— 这样"空树高度 0"这条约定不用到处写 if。 */
int avl_height(const AVLNode *node);

/* 平衡因子 bf = 左子树高度 - 右子树高度。
 * 正常范围 -1 / 0 / +1；出现 ±2 就说明这里塌了，该旋转了。 */
int avl_balance(const AVLNode *node);

/* 把自己 height 重算成 1 + max(左高, 右高)。旋转和插入后都要调它。 */
void avl_update_height(AVLNode *node);

/* 数一数树里有多少个节点（打印报告、验证插入个数用）。 */
int avl_count(const AVLNode *node);

/* 事后自检：整棵树是不是仍然满足 |bf| <= 1 且每个节点 height 存得对。
 * 返回 1 = 合法，0 = 有问题。每次操作之后都可以调一次，用来证明实现没错。 */
int avl_is_valid(const AVLNode *root);

/* 控制是否把"旋转现场"打印出来：1 = 打印过程，0 = 安静。
 * 学习阶段打开它，能直接看到是哪一种情况触发了哪一次旋转。 */
void avl_set_verbose(int on);

/* ===================================================================
 * 第二组：四种旋转 —— 本章的核心，每个都单独一个函数
 *
 * 约定：函数参数是"失衡的那个节点"，返回值是"旋转之后这棵子树的新根"。
 * 因为旋转后根会换人，调用者必须写 `root = avl_rotate_right(root);`
 * 把新根接回去。忘记接返回值是 AVL 第一大坑。
 * =================================================================== */

/* LL 型：失衡点是 y，y 的【左孩子的左边】被压高了 → 一次【右旋】。
 * 直观记法：把左孩子 x 提上来当根，y 降下去当 x 的右孩子。 */
AVLNode *avl_rotate_right(AVLNode *y);

/* RR 型：失衡点是 x，x 的【右孩子的右边】被压高了 → 一次【左旋】。
 * 直观记法：把右孩子 y 提上来当根，x 降下去当 y 的左孩子。 */
AVLNode *avl_rotate_left(AVLNode *x);

/* LR 型：失衡点是 y，y 的【左孩子的右边】被压高了。
 * 先对左孩子做【左旋】把它掰成 LL，再做一次【右旋】。共两次旋转。 */
AVLNode *avl_rotate_lr(AVLNode *y);

/* RL 型：失衡点是 x，x 的【右孩子的左边】被压高了。
 * 先对右孩子做【右旋】把它掰成 RR，再做一次【左旋】。共两次旋转。 */
AVLNode *avl_rotate_rl(AVLNode *x);

/* ===================================================================
 * 第三组：增删查遍销（对外主接口）
 * =================================================================== */

/* 造一个孤立节点：height = 1，两个孩子都是 NULL。malloc 失败返回 NULL。 */
AVLNode *avl_new(int value);

/* 插入。返回【这棵子树的新根】。
 * 用法永远是： root = avl_insert(root, 15);
 * 重复值不插入（教学里明确取"忽略"策略），所以树里没有重复元素。 */
AVLNode *avl_insert(AVLNode *root, int value);

/* 删除。返回【这棵子树的新根】。用法同样是 root = avl_remove(root, 值);
 * 值不存在就原样返回，不会误删别的节点。 */
AVLNode *avl_remove(AVLNode *root, int value);

/* 查找：返回那个节点的地址；找不到返回 NULL。因为是有序的，O(log n)。 */
const AVLNode *avl_search(const AVLNode *root, int value);

/* 中序遍历（左→根→右）打印成一排数字。用来"证明这棵树真的是有序的"。 */
void avl_print_inorder(const AVLNode *root);

/* 把整棵树"横着"打印出来，每个节点写成  8(h=4,bf=1)  这种形式：
 * h = 存的高度，bf = 平衡因子。看形状、看高度、看是否平衡，一眼搞定。 */
void avl_print_tree(const AVLNode *root);

/* 销毁整棵树：后序释放（先拆孩子，再拆自己），否则会有悬空指针。 */
void avl_destroy(AVLNode *root);

#endif /* AVL_TREE_H */
