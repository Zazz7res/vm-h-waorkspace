#ifndef RED_BLACK_TREE_H
#define RED_BLACK_TREE_H

/*
 * ===================================================================
 * 红黑树 · 头文件（"菜单"，实现和全部大白话讲解在 rbtree.c）
 * ===================================================================
 *
 * 【红黑树一句话】
 *   也是一棵二叉搜索树，但它不量"高度差"，而是给每个节点染一个颜色
 *   （红 / 黑），然后死守五条规则。规则守住了，树就自动不会长太高。
 *
 * 【五条性质（大白话版，详细推导在 README 和 rbtree.c 顶部）】
 *   1. 每个节点不是红的就是黑的，没有第三种颜色。
 *   2. 根节点必须是黑的。
 *   3. 所有"叶子"（也就是空位 NULL）都算黑的 —— 本实现里它们不是 NULL，
 *      而是同一个共享哨兵节点 t->nil，它天生是黑的。
 *   4. 红节点的两个孩子必须都是黑的（等价于：不能有两个红节点父子相连）。
 *   5. 从任意一个节点出发，走到它的所有后代叶子，路上数到的黑节点个数相同。
 *
 * 【为什么这五条能保证平衡（精髓）】
 *   性质 4 说"红节点不能相连"，所以同一条路上最短的可能全是黑（长度 = 黑高 bh），
 *   最长的只能"黑红黑红"交错（长度 <= 2·bh）。
 *   即：最长路径 <= 2 × 最短路径 → 树高 <= 2·log2(n+1) → 查找插入删除都是 O(log n)。
 *   AVL 要求左右高度差 <= 1（严格平衡），红黑只要求"不超过两倍"（大致平衡）。
 *   换来的好处是：调整时颜色变动能上移、旋转次数少（插入最多 2 次，删除最多 3 次）。
 *
 * 【为什么用共享哨兵而不是到处判 NULL】
 *   如果不设哨兵，代码里到处都是：
 *     if (z->parent != NULL && z->parent->color == RB_RED) ...
 *     if (uncle == NULL) 黑 else 看 uncle->color ...
 *   有了哨兵，"空孩子"也是一个真实的黑节点，有 color、有 parent，
 *   于是 uncle->color 直接就能读（哨兵是黑的，正好等于"NULL 视为黑"这条约定），
 *   判断少一半，还顺手解决了 double-black 往上冒泡时的边界。
 *   Linux 内核的 rb_tree、大多数工程实现都是这么干的。
 *
 * 【这个实现做到什么程度（诚实声明）】
 *   插入：完整（BST 插入 + 情况 1/2/3 修复，左右镜像都写了）。
 *   删除：完整（三种情况 + transplant + 双黑修复 case1~case4 及镜像），
 *         而且每次删除后都用 rbtree_check() 验证五条性质。
 *   没有做：no-recursive 版本、迭代遍历（本教学版本用递归，好读）。
 * ===================================================================
 */

/* 颜色就两个值。故意让 BLACK = 1，判"是不是黑"时写 == RB_BLACK，别靠 0/1 猜。 */
typedef enum {
    RB_RED   = 0,
    RB_BLACK = 1
} RBColor;

/* -------------------------------------------------------------------
 * 节点：比 AVL 节点多了 parent 和 color
 *
 *      ┌───────────────────────────────────────────────────┐
 *  p ─▶│ value │ color │ parent │ left │ right │
 *      └───┬───┴───────┴───┬────┴──┬───┴───┬───┘
 *          │              │       │       │
 *          15             ↓       ↓       ↓
 *                  回指爸爸   左孩子  右孩子（没有孩子时指向 nil 哨兵！）
 * ------------------------------------------------------------------- */
typedef struct RBNode {
    int              value;
    RBColor          color;
    struct RBNode   *parent;   /* 谁是我爸 —— 删除和修复要往上走，必须有这个 */
    struct RBNode   *left;
    struct RBNode   *right;
} RBNode;

/* -------------------------------------------------------------------
 * 树本体：不叫 root 就完了，还要带上那个共享哨兵
 *
 *   t->root ──▶ 真正的根节点（黑）
 *   t->nil  ──▶ 全世界只有一个的"空叶子"哨兵：黑色，所有空位都指它
 *               这样代码里永远不用写 if (x == NULL)
 * ------------------------------------------------------------------- */
typedef struct RBTree {
    RBNode *root;
    RBNode *nil;
    int     verbose;   /* 1 = 把修复过程的每一步打印出来 */
} RBTree;

/* ===================================================================
 * 生命周期
 * =================================================================== */

/* 建一棵空树：malloc 出哨兵 nil，染黑，root 就指向 nil。 */
void rbtree_init(RBTree *t);

/* 销毁：后序释放所有真实节点，最后释放唯一的 nil。 */
void rbtree_destroy(RBTree *t);

/* 打开/关闭修复过程打印。 */
void rbtree_set_verbose(RBTree *t, int on);

/* ===================================================================
 * 增删查
 * =================================================================== */

/* 插入：先当普通 BST 插成【红】的，再调 rb_insert_fixup 修补五条性质。
 * 返回新节点的地址；值重复或内存不足返回 NULL。 */
RBNode *rbtree_insert(RBTree *t, int value);

/* 删除值为 value 的节点。删掉返回 1，值不存在返回 0。
 * 内部就是 BST 那三种情况 + CLRS 的双黑修复（CASE 1~4 及其左右镜像）。 */
int rbtree_remove(RBTree *t, int value);

/* 查找，返回节点地址；找不到返回 NULL。 */
const RBNode *rbtree_search(const RBTree *t, int value);

/* ===================================================================
 * 旋转（对外暴露是为了能在 main.c 里单独演示"旋转前 / 旋转后"）
 * 注意和红黑树的旋转不同：AVL 旋转要顺手改 height，这里不用，
 * 但要维护 parent 指针 —— parent 指错，删除时往上走就走到别人家了。
 * =================================================================== */
void rbtree_rotate_left(RBTree *t, RBNode *x);   /* x 的右孩子上位，x 降级 */
void rbtree_rotate_right(RBTree *t, RBNode *y);  /* x 的左孩子上位，y 降级 */

/* ===================================================================
 * 打印与校验
 * =================================================================== */

/* 中序遍历（左→根→右）打印，用来证明"颜色再怎么折腾，顺序不会坏"。 */
void rbtree_print_inorder(const RBTree *t);

/* 横着打印整棵树，每个节点写成  11[R] bh=2 ：颜色标 + 该子树的黑色高度。 */
void rbtree_print_tree(const RBTree *t);

/* ★ 让学习者信服的关键设施：把五条性质【全部检查一遍】
 *   返回 0 = 全通过；返回 n>0 = 发现了 n 处破坏，并且已经打印出
 *   "破坏的是第几条、在哪个节点、当时的颜色是什么"。
 *   顺带额外检查父子指针是否互相指认（工程里最容易写错的地方）。 */
int rbtree_check(const RBTree *t);

/* 和 rbtree_check 一样查，但通过时【什么都不打印】，只在真破环时打印详情。
 * 压力测试里每一步都要校验，用这个才不刷屏。返回 0 = 全部成立。 */
int rbtree_check_quiet(const RBTree *t);

/* 树里真实节点个数（不含哨兵）。 */
int rbtree_count(const RBTree *t);

/* 颜色名给人类看：RB_RED → "红"，RB_BLACK → "黑"。演示打印用。 */
const char *rb_color_name_of(RBColor color);

/* 树高（不含哨兵叶子，空树为 0）。红黑树没有存高度，这里现算，仅用于演示。 */
int rbtree_height(const RBTree *t);

#endif /* RED_BLACK_TREE_H */
