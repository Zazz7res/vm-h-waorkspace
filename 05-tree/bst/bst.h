#ifndef BST_H
#define BST_H

/*
 * ===================================================================
 * 二叉搜索树 BST（Binary Search Tree）—— 本文件的"菜单"
 * ===================================================================
 *
 * 【一句话定义】
 *   它还是一棵普通二叉树（每个节点最多两个孩子），但多了一条铁律：
 *
 *        左子树里所有的值  <  根的值  <  右子树里所有的值
 *
 *   而且这条规矩【对每一个节点都要成立】，不只是根。
 *   只要守住它，"中序遍历"出来的序列自动就是升序 —— 白送的有序表。
 *
 * 【为什么守住它就能少看一半数据】
 *   要找一个值，先跟根比一下：
 *     比根小 → 答案只可能在左边，右边整片都不用看了
 *     比根大 → 答案只可能在右边，左边整片都不用看了
 *   每往下走一层，候选范围大约砍掉一半 → O(log n)。
 *   （普通二叉树没这条规矩，只能一个个问，O(n)。）
 *
 * 【代价：它会退化】
 *   如果来的顺序本身就是升序（1,2,3,4,5,6,7），每个新值都比所有已有值大，
 *   于是永远挂在最右边的右孩子上，树就长成了一条链表：
 *
 *     1                      高度 7 = 节点数 7
 *      \       看起来          查找退化成 O(n)
 *       2      就是链表
 *        \
 *         3 …
 *
 *   本文件末尾会现场演示这个退化，并说清"这就是 AVL / 红黑树存在的唯一理由"。
 *
 * 【本文件不跨目录引用任何东西】
 *   每个叶子目录独立编译，所以节点定义、树形打印、释放函数在 bst.c 里
 *   各自重写了一份（和 binary-tree 目录里的那份逻辑相同）。
 */

/* 节点定义：和普通二叉树一模一样 —— 变的是"规矩"，不是"结构" */
typedef struct Node {
    int val;
    struct Node *left;
    struct Node *right;
} Node;

/* main.c 里放遍历结果的数组容量上限，也是 bst_is_valid 之类的安全检查线 */
#define BST_CAP 64

/* ===================================================================
 * 1. 造节点 / 批量建树
 * =================================================================== */

/* 造一个孤立节点（left/right 一定置 NULL，不写就是垃圾值） */
Node *node_new(int val);

/* 按数组顺序逐个插入，造出一棵 BST（数组顺序 = 插入顺序，会决定树形！） */
Node *bst_build_from_array(const int arr[], int n);

/* 从"已经升序排好"的数组造一棵高度尽量矮的平衡 BST：
 * 每次取中间那个当根，左边一半建左子树，右边一半建右子树。
 * 用它和第 1 组数据对比，就能直观看到"平衡 vs 退化"查同样的值差几步。 */
Node *bst_build_balanced(const int sorted[], int n);

/* ===================================================================
 * 2. 插入：两个版本，务必都看懂
 * ===================================================================
 * 版本 A（二级指针版）：void bst_insert_pp(Node **root, int val)
 *   跟 00-c-foundation 里"想改外面的变量就得传地址"是同一件事：
 *   插入可能需要【改掉 root 这个指针本身】（原来树是空的，现在要有根了），
 *   所以要改"root 指针"，就得传"root 指针的地址"，即 Node **。
 *
 * 版本 B（返回新根版）：Node *bst_insert(Node *root, int val)
 *   把"这一层处理完之后，这棵子树的根是谁"当成返回值交回给上一层，
 *   调用方写成 root = bst_insert(root, v) —— 一级指针就够用，
 *   这也是绝大多数教材/代码库采用的写法。
 *
 * 本节约定：值已经存在就不再插入（重复值忽略），保证树里元素互不相同。
 * =================================================================== */
void  bst_insert_pp(Node **root_in_out, int val);   /* 版本 A */
Node *bst_insert(Node *root, int val);              /* 版本 B（更常用） */

/* ===================================================================
 * 3. 查找 / 最大最小
 * =================================================================== */

/* 递归版查找：命中返回节点地址，没命中返回 NULL */
const Node *bst_find(const Node *root, int val);

/* 迭代版查找：while 循环版，逻辑完全一样，不用递归 */
const Node *bst_find_iter(const Node *root, int val);

/* 带计数的查找：除了返回节点，还通过 steps_out 告诉你"比了几次"。
 * 演示退化时全靠它 —— 步数 == 走过的节点数 == 树高。 */
const Node *bst_find_counted(const Node *root, int val, int *steps_out);

/* 最小/最大：一直往左走到底 / 一直往右走到底。
 * 返回节点地址方便删除时取"后继"；空树返回 NULL。 */
const Node *bst_min_node(const Node *root);
const Node *bst_max_node(const Node *root);
int bst_min(const Node *root, int *out);   /* 便捷版：有值返回 1 并写 *out，空树返回 0 */
int bst_max(const Node *root, int *out);

/* ===================================================================
 * 4. 删除（本节最难点：三种情况）
 * ===================================================================
 * Node *bst_delete(Node *root, int val) —— 同样用"返回新根"的写法。
 *
 *   情况 1：要删的是叶子            → 直接 free，让父亲的孩子指针变 NULL
 *   情况 2：要删的只有一个孩子      → 把孩子提到它的位置上（链表摘节点一样）
 *   情况 3：要删的左右孩子都有      → 【不能真删！】
 *       拿"右子树里最小的那个值"（叫后继）顶上来，
 *       然后去右子树里递归删掉那个后继 —— 后继最多只有一个（右）孩子，
 *       于是又落回情况 1 或 2，问题就递归地解决了。
 *
 *   为什么后继能顶？因为后继 = 右子树最小 = 比被删者大、比左子树所有值都大，
 *   放到被删者的位置上，"左 < 根 < 右"这条铁律依然成立。
 * =================================================================== */
Node *bst_delete(Node *root, int val);

/* ===================================================================
 * 5. 遍历 / 校验 / 统计
 * =================================================================== */

/* 中序遍历（递归）：BST 的招牌性质 —— 输出一定是升序 */
void bst_inorder(const Node *root, int out[], int *n_out);

/* 校验是否合法 BST。正确做法：中序遍历必须【严格升序】。
 * 内部用"上一个访问到的节点"当指针传来传去，不额外开数组，O(n) 时间。 */
int bst_is_valid(const Node *root);

/* 故意写的【错误示范】：只检查"每个节点和自己亲生孩子"的大小关系。
 * 它会被一棵非法树骗过去（bst.c 里有具体反例和图）。留着它就是为了对比。 */
int bst_is_valid_local_only(const Node *root);

/* 树高：空树 0。退化时 == 节点数，平衡时 ≈ log2(n)+1，是"快不快"的晴雨表 */
int bst_height(const Node *root);

/* ===================================================================
 * 6. 打印 / 销毁
 * =================================================================== */

/* 横着打印树形（和 binary-tree 目录同一套算法，本目录自带一份） */
void print_tree(const Node *root);

/* 后序释放整棵树：先删左子树 → 再删右子树 → 最后 free 自己。
 * 顺序不能换：孩子的地址存在父亲身体里，先 free 父亲就是 use-after-free。 */
void free_tree(Node *root);

#endif /* BST_H */
