#ifndef TOPK_H
#define TOPK_H

/*
 * ===================================================================
 * Top-K 问题 topk —— 这一节的"菜单"
 * ===================================================================
 * 问题：给 n 个数，要出其中【最大的 K 个】（K 远小于 n，比如 100 万条日志里的前 10）。
 *
 * 这一节把三种做法【全写出来、全跑一遍】，并且用 clock() 打真实耗时：
 *
 *   ① 全排序取前 K       —— 最直觉，但为了一瓢水把整缸水搅了
 *   ② 维护大小为 K 的【最小堆】 —— 标准答案，O(n log K) 时间 + O(K) 空间
 *   ③ 快速选择 Quickselect     —— 理论最优（平均 O(n)），但代码最难写、最坏 O(n²)
 *
 * -------------------------------------------------------------------
 * 本节的反直觉重点：求【最大】的 K 个，为什么要用【最小】堆？
 * -------------------------------------------------------------------
 * 因为堆顶放的是"候选里【最差】的那个"，而我们要判断的恰恰是
 * "新来的这个数够不够格挤掉一个"。判断只需和堆顶比一次：
 *
 *     新数 > 堆顶（候选里最差的）  →  它有资格，踢掉堆顶，自己进来
 *     新数 <= 堆顶                →  它连最差的候选都不如，直接忽略
 *
 * 如果用最大堆，堆顶是"候选里最好的"，新数来了你根本不知道该踢谁 ——
 * 得把整个堆扫一遍才能找到最小的那个踢掉，O(K)，全白干。
 *
 * 一句话背下来：**要留"最大的 K 个"，就用最小堆当"守门员"，门里最差的那个在门口，
 * 新来的能不能进，看一眼门口就知道。**（反过来：要"最小的 K 个"就用最大堆守门。）
 *
 * -------------------------------------------------------------------
 * 为什么这个目录里又重写了一遍堆？
 * -------------------------------------------------------------------
 * 项目硬约定：叶子目录必须自包含，不能 #include 兄弟目录的文件。
 * 而且这里要用的堆【规模固定为 K、不需要扩容、只用到堆顶】，
 * 和 06-heap/binary-heap 那个通用堆不完全是一个东西，重写反而更清楚。
 */

/* 对外三个函数：输入同样的 data/n/k，输出最大的 K 个到 out（out 长度至少 K）。
 * 三者【不会】修改调用者的 input —— 内部各自拷一份，这一点必须保证，
 * 否则"全排序"会把用户的数据打乱，Top-K 通常是不能接受这个副作用的。
 *
 * cmp_out 可以为 NULL；传地址就会返回"这个算法一共做了多少次比较"。
 * 比较次数是【确定性】的数字，比耗时更适合用来讲复杂度；
 * 耗时会受系统调度影响，所以两种都打，互相印证。 */

/* ① 全排序：内部堆排序（O(n log n) 时间、O(n) 拷贝），排完从尾巴上取 K 个 */
void topk_by_sort(const int *data, int n, int k, int *out, long *cmp_out);

/* ② 固定大小的最小堆：O(n log K) 时间、O(K) 空间 */
void topk_by_heap(const int *data, int n, int k, int *out, long *cmp_out);

/* ③ 快速选择（简版，完整版在 11-searching/kth-smallest）：平均 O(n)、最坏 O(n²) */
void topk_by_quickselect(const int *data, int n, int k, int *out, long *cmp_out);

/* 把快速选择【每一轮切掉多少】打出来（前 6 轮 + 命中那一轮）。
 * 用途：亲眼看看"平均 O(n)"依赖的 pivot 位置在不同输入下有多不稳定。 */
void topk_quickselect_trace(const int *data, int n, int k);

/* 把堆守门的过程【一步一步】打出来：每个新元素进来时，
 * 堆里现在有哪几个候选、堆顶（最差候选）是谁、这个元素进不进。
 * 只在演示用的小数组上调用（大数组会刷屏）。 */
void topk_heap_trace(const int *data, int n, int k);

/* 工具：打印一段数组 */
void topk_print_array(const char *name, const int *a, int n);

/* 工具：把 out 里的 K 个数排成【降序】再返回，用来比较三种算法结果是否一致。
 * （Top-K 本身不保证顺序，所以比较前必须归一化 —— 这是个真坑，见 README） */
void topk_normalize_desc(int *out, int k);

#endif /* TOPK_H */
