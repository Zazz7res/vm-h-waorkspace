#ifndef PQUEUE_H
#define PQUEUE_H

/*
 * ===================================================================
 * 优先队列 priority-queue —— 这一节的"菜单"
 * ===================================================================
 * 一句话：**优先队列 = 堆 + 一个薄壳接口。**
 * 外面只暴露 4 件事：enqueue（入队）、dequeue（出队最优先）、peek（看一眼）、size（几个人）。
 * 里面那棵"压扁成数组的完全二叉树"是本目录自带的极简二叉堆
 * （见 pqueue.c 顶部 —— 按本项目的"叶子目录必须自包含"约定，
 *   这里【不】去 #include 隔壁 06-heap/binary-heap 的头文件，
 *   而是把上浮/下沉那几十行重写一份。重写一遍才是真的学会了。）
 *
 * -------------------------------------------------------------------
 * 它和普通队列差在哪？
 * -------------------------------------------------------------------
 *   普通队列 queue：  先来后到（FIFO）。  来的顺序 = 处理的顺序。
 *   优先队列 pqueue： 优先级小的先走。    来的顺序【不算数】。
 *
 *   到达顺序:  A(p=5)  B(p=1)  C(p=3)  D(p=2)
 *   普通队列出队: A B C D        ← 谁先到谁先服务
 *   优先队列出队: B D C A        ← 谁优先级高谁先服务（数字越小越紧急）
 *
 * 这就是"急诊室分诊"模型：救护车送来的重伤员插到最前面，
 * 不管他是不是最后一个挂号的。
 *
 * -------------------------------------------------------------------
 * 元素长什么样？为什么不是 int 而是一对小整数？
 * -------------------------------------------------------------------
 * 堆本身只关心"谁优先级高"，但队列还得说得出"这个任务是谁"。
 * 所以我们把两个 int 捆在一个 struct 里当元素：
 *
 *     typedef struct { int priority; int id; } Task;
 *          ▲             ▲            ▲
 *        比大小时只用它；id 只跟着走，堆从不看它
 *
 * ⚠ 这【不是】泛型：Task 是写死的具体类型，没有 void *，没有函数指针比较器。
 *   比较逻辑就一句话"priority 小的赢"，硬编码在 pqueue.c 里。
 *
 * -------------------------------------------------------------------
 * 本节最大看点：优先级相同怎么办？（本项目【不】实现稳定，但要把坑讲透）
 * -------------------------------------------------------------------
 * 直觉上"一样紧急就先来的先服务"（FIFO / 稳定性）。但堆【没有】这个保证：
 * 比较只看 priority，两个任务 priority 相等时，谁在上面对堆来说是"无所谓"的，
 * 而 pop 时"末尾元素补到堆顶再下沉"这一刀会把相等元素的相对顺序彻底洗乱。
 * 见 main.c 第 5 幕：依次入队 prio=1 的 101、102、103，
 * 出队顺序很可能是 101 103 102 —— 一个都不报错，只是悄悄不公平。
 * 工程解法（README 里详细讲）：给每个任务加一个自增序号 seq，
 * 比较时按 (priority, seq) 双键 —— 代码只改 2 行，稳定性立刻就有。
 */

/* 队列里的元素：优先级 + 任务号。priority 越小越紧急。 */
typedef struct {
    int priority;   /* 堆只认这个字段来排大小 */
    int id;         /* 任务号，纯粹跟着搬来搬去，比较时【不】看 */
} Task;

/* 优先队列本体：一块连续的 Task 数组 = 一棵压扁的完全二叉树。 */
typedef struct PQueue {
    Task *data;      /* 唯一的存储 */
    int   size;      /* 队列里现在几个人 */
    int   capacity;  /* 数组能装几个人（满了翻倍扩） */
    int   verbose;   /* 1 = 每次上浮/下沉都把队列当前状态打印出来 */
    long  enqueued;  /* 累计入队过多少个任务（用来数"一共搬了几次"） */
    long  swaps;     /* 累计发生过多少次交换：让"O(log n)"变成能看见的数字 */
} PQueue;

/* ---------- 生 / 死 ---------- */
PQueue *pq_new(int initial_capacity);
void    pq_free(PQueue *q);

/* ---------- 4 个对外操作（这就是"优先队列"的全部能力） ---------- */

/* 入队：接到尾部 + 上浮。O(log n)。
 * 返回 0 成功，-1 失败（内存不够）。 */
int pq_enqueue(PQueue *q, int priority, int id);

/* 出队：拿走最优先的那个（priority 最小）。O(log n)。
 * priority_out / id_out 都可以传 NULL，表示"这个结果我不要"。
 * 返回 0 成功，-1 表示队列已空。 */
int pq_dequeue(PQueue *q, int *priority_out, int *id_out);

/* 看一眼最优先是谁，不删。O(1)。空队列返回 -1。 */
int pq_peek(const PQueue *q, int *priority_out, int *id_out);

/* 队列里还有几个人。q 为 NULL 时返回 0，方便打印。 */
int pq_size(const PQueue *q);
int pq_empty(const PQueue *q);      /* 1 空 0 不空 */

/* ---------- 观察用 ---------- */
void pq_print(const PQueue *q);             /* 树形 + 数组对照（元素打成 p优先级(#任务号)） */
void pq_set_verbose(PQueue *q, int on);
long pq_swaps(const PQueue *q);             /* 累计交换次数 */
void pq_reset_swaps(PQueue *q);

#endif /* PQUEUE_H */
