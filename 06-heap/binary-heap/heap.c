/*
 * ===================================================================
 * 0. 一个内部小工具：谁该待在更上面？
 * ===================================================================
 * 整个堆文件里"比大小"这件事【只在这一处发生】。
 * 这是本代码最重要的一个设计决定：
 *
 *   最小堆：a 比 b 小 → a 该在上面
 *   最大堆：a 比 b 大 → a 该在上面
 *
 * 所以想从最小堆变成最大堆，只要把 kind 一翻，其他所有代码（上浮、下沉、
 * 建堆、pop）一行都不用改。这就是"最大堆只是把比较号反过来"的字面体现。
 *
 * ⚠ 这里【没有】函数指针比较器：只读 h->kind 这个枚举字段做 if 判断。
 *   初学者最容易在这里想复杂，其实一个 int 标记就够了。
 *
 * cmp_count 顺手 +1：main.c 第 7 幕要用它实测"建堆到底做了多少次比较"，
 * 用真实数字证明 heapify 是 O(n) 而不是 O(n log n)。
 */
static int better_than(Heap *h, int a, int b)
{
    h->cmp_count++;   /* 统计比较次数（不是"次数"的字段是 long，够大） */

    if (h->kind == HEAP_MAX) {
        return a > b;      /* 最大堆：大的往上走 */
    }
    return a < b;          /* 最小堆：小的往上走 */
}

/*
 * ===================================================================
 * 1. 三个下标公式：整个堆的命根子
 * ===================================================================
 * 为什么数组能当二叉树用？靠的就是这三行。
 *
 * 设某个节点下标是 i（本项目一律 0 起下标）：
 *
 *    左孩子 = 2i + 1
 *    右孩子 = 2i + 2
 *    父亲   = (i - 1) / 2      ← 注意是【整数除法】
 *
 * -------------------------------------------------------------------
 * 先证"左 = 2i+1 / 右 = 2i+2"为什么对
 * -------------------------------------------------------------------
 * 完全二叉树每一层的节点数是 1, 2, 4, 8, ...（第 d 层有 2^d 个），
 * 所以第 0 层到第 d-1 层加起来一共占掉 2^d - 1 个下标（0 .. 2^d-2），
 * 第 d 层的下标从 2^d - 1 开始连续排。
 * 那么第 d 层的第 i 个节点（在这一层里排第 k = i - (2^d - 1) 位），
 * 它的两个孩子就在第 d+1 层，从该层第 2k 位开始，即：
 *     2^(d+1) - 1 + 2k = 2^(d+1) - 1 + 2(i - 2^d + 1) = 2i + 1
 * 右孩子再往后一格 = 2i + 2。得证。
 *
 * 不用公式推导也能直觉理解：把下标写成二进制，规律特别漂亮 ——
 *     i      = 1 b_{k} ... b_0    （二进制）
 *     左孩子 = b_{k} ... b_0 0    = 2i（再 +1 因为 0 号下标要挪位）
 *     父亲   = 把最后一位砍掉     = i / 2
 * 这就是"堆是数组里一棵树"最本质的原因。
 *
 * -------------------------------------------------------------------
 * 再证"父 = (i-1)/2"为什么【天然成立】（这是最容易含糊的地方）
 * -------------------------------------------------------------------
 * 我们要的是"孩子下标反推父亲"。分两种情况，都用 C 的整数除法（小数部分直接砍掉）：
 *
 *   情况 A：i 是左孩子，即 i = 2p + 1（p 是真父亲）
 *          (i - 1) / 2 = (2p + 1 - 1) / 2 = 2p / 2 = p              ✅
 *   情况 B：i 是右孩子，即 i = 2p + 2
 *          (i - 1) / 2 = (2p + 2 - 1) / 2 = (2p + 1) / 2 = p.5 → 砍掉小数 = p   ✅
 *
 * 两种情况都落到 p，所以公式对任何 i >= 1 都对。
 *
 * ⚠ 关键点在"砍掉小数"这四个字上。情况 B 里 (2p+1)/2 是 .5 结尾，
 *   必须向下取整才能得到 p。C 语言的整数除法是【向零截断】：
 *   正数时向零截断 == 向下取整，负数时不等（-3/2 在 C 里是 -1，向下取整是 -2）。
 *   而孩子下标 i 永远 >= 1，所以 i-1 >= 0，分子不可能为负 ——
 *   于是"正数截断 = 向下取整"，公式安全落地。
 *   一句话：**这个公式不是巧合，但它能成立是靠了"下标非负"这个前提。**
 *   如果你写 (i/2 - 1) 当父亲，i=1、i=2 时就会算错（这也是初学者常犯的错）。
 *
 * 0 号是根，它没有父亲，返回 -1 表示"没有"。
 */
int heap_parent(int i)
{
    if (i <= 0) {
        return -1;   /* 根节点没有父亲。用 -1 当"无"的哨兵，调用方必须判 */
    }
    return (i - 1) / 2;   /* 上面证明过的公式 */
}

int heap_left(int i)
{
    return 2 * i + 1;
}

int heap_right(int i)
{
    return 2 * i + 2;
}

/*
 * ===================================================================
 * 2. 打印：只画数组那一行
 * ===================================================================
 * 为什么要把数组反复打印出来？因为堆的所有操作本质就是"交换数组里两个格子"。
 * 你能肉眼看到数组一步步变化，就说明你真看懂上浮/下沉在干什么了。
 *
 * note 是这一行的标题，可以是 NULL。
 */
void heap_dump(const Heap *h, const char *note)
{
    if (h == NULL || !h->verbose) {
        return;   /* 安静模式：跑 1000 个元素的大数据时不刷屏 */
    }

    if (note != NULL) {
        printf("      %s: ", note);
    } else {
        printf("      当前数组: ");
    }

    printf("[");
    for (int k = 0; k < h->size; k++) {
        printf(" %d", h->data[k]);   /* 用不定宽，数组短的时候最好读 */
    }
    printf(" ]\n");
}

/* 把数组带上标尺打印两行：一行下标、一行值。用于 heap_print 的"数组形式"部分。 */
static void heap_dump_with_ruler(const Heap *h)
{
    printf("  数组形式（同一批数据，摊平看）\n");
    printf("    下标:");
    for (int k = 0; k < h->size; k++) {
        printf("%4d", k);
    }
    printf("\n    值  :");
    for (int k = 0; k < h->size; k++) {
        printf("%4d", h->data[k]);
    }
    printf("\n");
}

/*
 * ===================================================================
 * 3. heap_print：树形 + 数组，两者对照
 * ===================================================================
 * 这是本节最该多看几眼的函数。它把"上面是树、下面是数组"画在同一个输出里：
 *
 *   d=0  [ 0.. 0] |        1(0)
 *   d=1  [ 1.. 2] |   3(1)      2(2)
 *   d=2  [ 3.. 6] | 7(3) 9(4)  5(5) 6(6)
 *   下标:  0   1   2   3   4   5   6
 *   值  :  1   3   2   7   9   5   6
 *
 * 三个观察点：
 *   ① 每一层占的正好是数组里【一段连续区间】（左边 [start..end] 就是这段区间），
 *      这就是"完全二叉树"和"紧凑数组"能一一对上的原因。
 *   ② 最后一层可以不满，但一定是从左往右连着长（区间里不会跳号）。
 *   ③ 树里越往深节点越多（1、2、4、8…），而数组里它们占的格子也越多 ——
 *      这个事实正是"自底向上建堆是 O(n)"的几何原因（见 heap_build 的注释）。
 */
void heap_print(const Heap *h)
{
    if (h == NULL) {
        printf("  (堆指针是 NULL)\n");
        return;
    }
    if (h->size == 0) {
        printf("  (空堆：size=0，树里一个节点都没有)\n");
        return;
    }

    int total = h->size;

    /* 树太深画不下（每层宽度指数增长），退化成只给数组 */
    if (total > 31) {
        printf("  元素 %d 个，树形图会超过 5 层太宽，只给数组前 40 个：\n   ", total);
        int show = total < 40 ? total : 40;
        for (int k = 0; k < show; k++) {
            printf(" %d", h->data[k]);
        }
        if (show < total) {
            printf(" ...");
        }
        printf("\n");
        return;
    }

    /* 层数 levels：满足 2^0 + 2^1 + ... + 2^(levels-1) >= total 的最小层数。
     * 用移位数的方法：只要 2^d <= total，说明第 d 层还有节点。 */
    int levels = 0;
    while ((1 << levels) <= total) {
        levels++;
    }

    printf("  树形（每层一行，值后面括号里是数组下标）\n");
    for (int d = 0; d < levels; d++) {
        int start = (1 << d) - 1;                       /* 本层第一个下标 */
        int end = (1 << (d + 1)) - 2;                   /* 本层理论最后下标：2^(d+1)-2 */
        if (end > total - 1) {
            end = total - 1;                            /* 最后一层可能不满 */
        }

        /* 左侧 gutter 宽度固定，才不会把各层的居中对齐挤歪 */
        char gutter[48];
        snprintf(gutter, sizeof gutter, "  d=%d  [%3d..%3d] |", d, start, end);
        printf("%-24s", gutter);

        /* 本层节点要放在哪个字符列上：
         * 半格宽 half = 3 * 2^(levels-1-d)，越深格子越密。
         * 第 p 个节点的"中心列" = (2p+1) * half。
         * 这样父节点正好落在两个孩子中间，画出来自然是一棵对称的树。 */
        int half = 3 * (1 << (levels - 1 - d));
        int cur_col = 0;
        for (int idx = start; idx <= end; idx++) {
            int p = idx - start;                        /* 本层内排第几个 */
            char label[32];
            snprintf(label, sizeof label, "%d(%d)", h->data[idx], idx);
            int len = (int)strlen(label);
            int target = (2 * p + 1) * half - len / 2;  /* 让标签中心对齐 */
            if (target < cur_col) {
                target = cur_col;                       /* 万一挤了也别倒着打字 */
            }
            for (int s = cur_col; s < target; s++) {
                putchar(' ');
            }
            fputs(label, stdout);
            cur_col = target + len;
        }
        printf("\n");
    }

    printf("  读图：左边的 [start..end] 就是这一层占用的数组区间；"
           "父(i)=(i-1)/2，左=2i+1，右=2i+2\n");
    heap_dump_with_ruler(h);
}

/* 把一个小整数按二进制打出来（不够 5 位补前导 0），用来看下标的位移规律 */
static void print_binary5(int v)
{
    for (int bit = 4; bit >= 0; bit--) {
        putchar('0' + ((v >> bit) & 1));
    }
}

/*
 * ===================================================================
 * 13. heap_print_relations：把"下标公式"变成看得见的表格
 * ===================================================================
 * 光说 父=(i-1)/2、左=2i+1、右=2i+2 是没什么感觉的，所以这里把每个下标的
 * 父 / 左 / 右全列出来，并且做两件事：
 *   ① 反着验一遍：把 i 当成孩子，算出父亲 p，再验证 left(p) 或 right(p) 能算回 i。
 *      公式对每一个 i 都能自洽，读者自己就能复核。
 *   ② 顺手把下标写成二进制。你会看到非常漂亮的事实：
 *        左孩子 = (i 的二进制后面添一个 0) 再 +1
 *        父亲   = (i 的二进制砍掉最后一位) 再 +1 的逆运算
 *      实际上"1 起下标"的版本才是纯位移（i 的孩子是 2i 和 2i+1，父亲是 i/2），
 *      我们全项目用 0 起下标，所以要带那个 ±1。这也是很多教材把两种写法混在
 *      一起、初学者看得一头雾水的根源 —— 看清自己用的是哪种就行。
 */
void heap_print_relations(int n)
{
    if (n < 1) {
        printf("  heap_print_relations: n 要 >= 1\n");
        return;
    }
    if (n > 16) {
        n = 16;      /* 表格画太长就没法读了 */
        printf("  （表太宽，只看前 16 个下标）\n");
    }

    printf("  下标 i | 二进制 |   父 (i-1)/2  |   左 2i+1   |   右 2i+2   | 反推验证\n");
    printf("  -------+--------+---------------+-------------+-------------+---------\n");
    for (int i = 0; i < n; i++) {
        int p = heap_parent(i);
        int l = heap_left(i);
        int r = heap_right(i);

        char pbuf[16];
        if (p < 0) {
            snprintf(pbuf, sizeof pbuf, "无(根)");
        } else {
            snprintf(pbuf, sizeof pbuf, "%d", p);
        }

        /* 反推验证：i 若不是根，那么 parent(i) 的左孩子或右孩子必须正好是 i */
        char verify[48];
        if (i == 0) {
            snprintf(verify, sizeof verify, "（根无需验证）");
        } else if (heap_left(p) == i || heap_right(p) == i) {
            snprintf(verify, sizeof verify, "✅ %s 的孩子是 %d",
                     heap_left(p) == i ? "left" : "right", i);
        } else {
            snprintf(verify, sizeof verify, "❌ 公式错了");
        }

        printf("  %6d | ", i);
        print_binary5(i);
        printf(" | %13s | %11d | %11d | %s\n", pbuf, l, r, verify);
    }

    printf("\n  注意右孩子那一列：i=0 右=2，(2-1)/2 = 1/2 = 0（C 里小数被砍掉）→ 正好回到 0。\n");
    printf("  这个「砍掉小数」就是整件事的关键，见 heap.c 顶部 heap_parent 上方的证明。\n");
}

/*
 * ===================================================================
 * 4. 建 / 销毁
 * ===================================================================
 * 堆的全部家当只有一块 int 数组，所以 heap_free 只需 free 一处。
 * （如果你哪天往结构体里加了第二个指针字段，记得这里也要加 —— 漏一个就是泄漏。）
 */
Heap *heap_new(int initial_capacity, HeapKind kind)
{
    if (initial_capacity < 1) {
        initial_capacity = 1;   /* 别让 0 或负数进来，否则 malloc(0) 行为不统一 */
    }

    Heap *hh = malloc(sizeof(Heap));
    if (hh == NULL) {
        return NULL;
    }

    hh->data = malloc((size_t)initial_capacity * sizeof(int));
    if (hh->data == NULL) {
        free(hh);          /* 第二个 malloc 失败时，第一个要还掉，否则泄漏 */
        return NULL;
    }

    hh->size = 0;
    hh->capacity = initial_capacity;
    hh->kind = kind;
    hh->verbose = 1;       /* 学习期默认开着，每一步都打印 */
    hh->cmp_count = 0;
    return hh;
}

void heap_free(Heap *h)
{
    if (h == NULL) {
        return;
    }
    free(h->data);   /* free(NULL) 合法，所以这里不用判 */
    free(h);
    /* ⚠ 调用者拿到的是地址的拷贝，这里没法把外面的指针置 NULL。
     *   所以约定：heap_free(h); h = NULL;  两行必须连着写。 */
}

void heap_set_verbose(Heap *h, int on)
{
    if (h != NULL) {
        h->verbose = on ? 1 : 0;
    }
}

int heap_size(const Heap *h)     { return h == NULL ? 0 : h->size; }
int heap_empty(const Heap *h)    { return (h == NULL || h->size == 0) ? 1 : 0; }
int heap_capacity(const Heap *h) { return h == NULL ? 0 : h->capacity; }

void heap_reset_stats(Heap *h)
{
    if (h != NULL) {
        h->cmp_count = 0;
    }
}

long heap_cmp_count(const Heap *h)
{
    return h == NULL ? 0 : h->cmp_count;
}

/*
 * ===================================================================
 * 5. 扩容（数组装满了）
 * ===================================================================
 * 数组是定长的，装满了必须换一块更大的、把老数据搬过去。
 * 为什么是"翻倍"而不是"+1"：摊还分析。翻倍的话，n 次插入总共只搬 1+2+4+…+n
 * < 2n 个元素，平均每次 O(1)；每次只加 1 格就变成 O(n) 一次、整体 O(n²)。
 *
 * 返回 0 成功，-1 失败。失败时原数组内容完全不变（realloc 失败会返回 NULL
 * 并且不动老内存，这是它和 malloc+copy+free 的好处）。
 */
static int heap_grow(Heap *h)
{
    int new_cap = h->capacity * 2;
    if (new_cap < 1) {
        new_cap = 1;
    }

    int *fresh = realloc(h->data, (size_t)new_cap * sizeof(int));
    if (fresh == NULL) {
        return -1;
    }

    h->data = fresh;      /* 一定要用返回值接！realloc 可能把内存搬到别处 */
    h->capacity = new_cap;

    if (h->verbose) {
        printf("      [扩容] 数组从 %d 格扩到 %d 格（翻倍扩，摊还 O(1)）\n",
               new_cap / 2, new_cap);
    }
    return 0;
}

/*
 * ===================================================================
 * 6. 交换 + 打印每一步
 * ===================================================================
 * 堆里所有的"结构变化"其实只有一种：交换数组里两个格子。
 * 上浮是一连串向上交换，下沉是一连串向下交换。把它单独抽出来，
 * 顺便在这里打印数组，就能做到"堆化过程看得见"。
 */
static void heap_swap(Heap *h, int a, int b, const char *why)
{
    int tmp = h->data[a];
    h->data[a] = h->data[b];
    h->data[b] = tmp;

    if (h->verbose) {
        /* why 可能传 NULL（pop 那一步不需要说动机），所以先兜个底 */
        printf("      %s：交换下标 %d <-> %d，值 %d <-> %d\n",
               why != NULL ? why : "交换", a, b, h->data[a], h->data[b]);
        heap_dump(h, "交换后数组");
    }
}

/*
 * ===================================================================
 * 7. sift_up：上浮（插入时用）
 * ===================================================================
 * 要解决的问题：数组末尾刚放了一个新值，除了它自己以外堆序性全成立。
 *          （叫"局部有序、只有一个位置可能不对"，这是堆操作的通用套路：
 *            每次操作只制造【一个】违例点，然后修那一个点。）
 *
 * 修法：拿它跟父亲比。如果它比父亲还该在上面（最小堆里就是更小），就交换，
 *      然后继续拿新位置跟新的父亲比。一直比到 ①不比父亲小了，或 ②撞到根了，停。
 *
 * 每一轮 i 变成 parent(i)，i 至少砍掉一半（(i-1)/2 <= i/2），
 * 所以最多走 log2(n) 步 —— 这就是"插入 O(log n)"的来源。
 *
 * 边界情况：
 *   - i == 0：已经是根，没有父亲，直接返回。
 *   - 相等时【不换】（better_than 用的是严格 < / >）。这让堆的"稳定"性
 *     有了确定行为；也保证不会在两个相等值之间来回死循环。
 */
static void sift_up(Heap *h, int i)
{
    while (i > 0) {                        /* i > 0 就是"还有父亲" */
        int p = heap_parent(i);            /* 父亲下标 */
        if (!better_than(h, h->data[i], h->data[p])) {
            if (h->verbose) {
                printf("        停：值 %d 不比父亲 %d 更该在上面，位置就位\n",
                       h->data[i], h->data[p]);
            }
            return;
        }
        heap_swap(h, i, p, "上浮");
        i = p;                             /* 接着从新位置继续往上比 */
    }
    if (h->verbose) {
        printf("        停：已经到堆顶（下标 0），没有父亲了\n");
    }
}

/*
 * ===================================================================
 * 8. sift_down：下沉（删除堆顶、建堆时用）
 * ===================================================================
 * 要解决的问题：下标 i 处这个值"太大了/压不住场"，但它【两个孩子为根的子树
 *              已经各自是合法的堆】。也就是又一次"只有一个违例点"。
 *
 * 修法：把 i 和【两个孩子中更该在上面的那个】比较；需要就交换下去。
 *      为什么必须跟"更小的孩子"（最小堆）交换，而不是随便挑一个孩子？
 *      看这个例子：父 5、左 1、右 2。若跟右孩子换 → 变成 父 2、左 1 → 2 > 1 违规，
 *      堆还是坏的。跟左孩子换 → 父 1、左 5、右 2 → 这一层合法，继续往下修。
 *      一句话：只有把最小的提到上面，才能保证"提完之后父亲 <= 两个孩子"。
 *
 * 边界情况：
 *   - 没有孩子（2i+1 >= size）：叶子，天然合法，直接停。
 *   - 只有左孩子（2i+2 >= size）：完全二叉树里"有右必有左"，所以这种情况
 *     要单独处理 —— 只跟左孩子比。代码里就体现在"先假设 best=左，再看右有没有更优"。
 *   - i 就是最优点：立刻停，这一步一次交换都不做（下沉的平均长度远小于 log n）。
 */
static void sift_down(Heap *h, int i)
{
    int total = h->size;

    for (;;) {
        int l = heap_left(i);
        int r = heap_right(i);

        if (l >= total) {
            return;                 /* 叶子：2i+1 已经越界，没有孩子可换 */
        }

        int best = l;               /* 先假设左孩子是该在上面的那个 */
        if (r < total && better_than(h, h->data[r], h->data[l])) {
            best = r;               /* 右孩子存在且更优 → 换成右 */
        }

        if (!better_than(h, h->data[best], h->data[i])) {
            if (h->verbose) {
                printf("        停：%d 已经是自己和孩子里最该在上面的，这一带合法\n",
                       h->data[i]);
            }
            return;                 /* 自己也该在上面 → 整棵子树合法，收工 */
        }

        heap_swap(h, i, best, "下沉");
        i = best;                   /* 违例点跟着这个值往下挪 */
    }
}

/*
 * ===================================================================
 * 9. heap_push：插入
 * ===================================================================
 * 两步走，顺序【不能反】：
 *   第 1 步：把新值放到 data[size]，然后 size++。
 *            这一步为什么放末尾？因为数组末尾对应完全二叉树【最后一层最右边】，
 *            在那儿挂一个节点，完全二叉树的形状刚好还是保持的（结构性不破）。
 *            如果放中间，就得整体搬移 → O(n)，白学。
 *   第 2 步：只有这个新位置可能违反堆序性 → sift_up 修它。O(log n)。
 *
 * 边界：容量满了先扩容；扩容失败返回 -1，堆保持原样。
 */
int heap_push(Heap *h, int value)
{
    if (h == NULL) {
        return -1;
    }
    if (h->size == h->capacity && heap_grow(h) != 0) {
        return -1;
    }

    int at = h->size;              /* 新节点的位置：数组尾巴 */
    h->data[at] = value;
    h->size++;                     /* ⚠ 必须 size++ 之后 sift 才看得见这个值 */

    if (h->verbose) {
        printf("    push(%d)：先挂到下标 %d（完全二叉树只能从尾巴往后长）\n", value, at);
        heap_dump(h, "挂上后数组");
    }
    sift_up(h, at);
    if (h->verbose) {
        heap_dump(h, "上浮结束");
    }
    return 0;
}

/*
 * ===================================================================
 * 10. heap_pop：取走堆顶 —— 本节最需要讲透的操作
 * ===================================================================
 * 正确做法（三步，顺序不能换）：
 *   ① 记下 data[0] 的值，这就是要返回的最小值（先抄下来，否则下一步就覆盖了）
 *   ② 把【最后一个元素】 data[size-1] 和堆顶 data[0] 交换，然后 size--
 *   ③ 新堆顶大概压不住场 → sift_down(0)
 *
 * -------------------------------------------------------------------
 * 为什么必须换末尾元素？（初学者的三大困惑之一）
 * -------------------------------------------------------------------
 * 我们要同时满足两件事：
 *   (a) 数组下标必须连续 0..size-1，中间【不能有洞】—— 因为父子关系全靠下标算，
 *       一旦中间空了一格，data[k] 是"谁的孩子"就说不清了，"压扁的树"就散了。
 *   (b) 删掉堆顶之后，堆顶这个位置必须有值填上（不能空着）。
 *
 * 能同时满足 (a)(b) 的元素只有一个：末尾那个。理由：
 *   - 完全二叉树删掉"最后一层最右边"那个节点之后，剩下的还是完全二叉树；
 *     数组表现为长度少 1，其他元素的下标一个都不用动。
 *   - 末尾元素一定是【叶子】（它不可能有孩子，否则它就该排在更后面），
 *     所以把它搬走不会让任何节点失去父亲。
 *   - 搬来搬去只需要 1 次交换（O(1)），代价最低。
 *
 * 那"直接删堆顶、后面整体往前挪一格"行不行？
 *   结构上【居然】还行：形状还是完全二叉树，只是所有下标错位了。
 *   但复杂度上不行：每次 pop 都要搬 size-1 个元素 = O(n)，
 *   n 次 pop 就退化成 O(n²)，比冒泡还难看，堆就白用了。
 *   正确做法是 O(1) 搬移 + O(log n) 下沉。
 *
 * 还有第三种直觉："把堆顶换成最小的那个孩子，让空位往下传"（像下拉菜单）。
 *   这个思路其实可以做（叫 hole punching，工业实现里偶尔见），但它一路向下
 *   要在每个位置挑最小孩子、最后仍然必须找一个叶子来填空，收益不比"交换+下沉"高，
 *   代码还更绕。教学实现一律用交换法。
 *
 * 边界：空堆返回 -1，out 不被写；out 传 NULL 表示"我不关心值，只想删堆顶"。
 */
int heap_pop(Heap *h, int *out)
{
    if (h == NULL || h->size == 0) {
        if (h != NULL && h->verbose) {
            printf("    pop 失败：堆是空的，没有堆顶可取\n");
        }
        return -1;
    }

    int top_value = h->data[0];     /* ① 先把答案抄下来 */
    int last = h->size - 1;         /* 末尾元素的下标 */

    if (h->verbose) {
        if (last == 0) {
            printf("    pop 堆顶：答案=%d，堆里只有它一个，size 直接归 0（不用交换也不用下沉）\n",
                   top_value);
        } else {
            printf("    pop 堆顶：答案=%d（下标 0）。它要和末尾 data[%d]=%d 交换\n",
                   top_value, last, h->data[last]);
        }
    }

    /* ② 交换堆顶和末尾，然后把数组"缩短一格"。
     *    这个操作等价于：把那个要删的最小值挤到数组尾巴，再把尾巴剪掉。
     *    注意此时 size 还没变，所以 heap_dump 还能看见它。
     *    （只剩一个元素时 0 和 last 是同一格，交换是白做的，跳过更清楚。） */
    if (last > 0) {
        heap_swap(h, 0, last, "pop 第一步");
    }

    h->size--;                       /* 剪掉尾巴：被删的那个最小值就"消失"了 */
    if (h->verbose) {
        printf("        size-- => %d（尾巴上那个 %d 已经不属于堆了）\n", h->size, top_value);
        heap_dump(h, "缩容后数组");
    }

    /* 堆里可能已经空了（原来只有 1 个元素），此时不用下沉 */
    if (h->size > 0) {
        sift_down(h, 0);            /* ③ 修唯一的那个违例点 */
    }

    if (out != NULL) {
        *out = top_value;
    }
    if (h->verbose) {
        heap_dump(h, "下沉结束");
    }
    return 0;
}

/*
 * ===================================================================
 * 11. heap_peek：只看不动，O(1)
 * ===================================================================
 * 堆对外提供的全部"信息"就是堆顶这一个格子。想看第二小的？
 * 对不起，得 pop 出来（或者干脆堆排序）。这是堆的能力边界，
 * 也是它为什么能做得这么简单、这么快。
 */
int heap_peek(const Heap *h, int *out)
{
    if (h == NULL || h->size == 0) {
        return -1;
    }
    if (out != NULL) {
        *out = h->data[0];
    }
    return 0;
}

/*
 * ===================================================================
 * 12. heap_build：把一整段现成数据变成堆（heapify）—— O(n)
 * ===================================================================
 * 做法：从最后一个"有孩子"的节点开始，一路往前，逐个 sift_down。
 *
 * -------------------------------------------------------------------
 * 为什么起点是 n/2 - 1 ？
 * -------------------------------------------------------------------
 * 下标 i 是叶子 ⟺ 2i+1 >= n ⟺ i >= (n-1)/2。
 * 也就是说数组后半段（大约 n/2 个）全是叶子。叶子没有孩子，堆序性自动成立，
 * 对它 sift_down 一步就返回（纯浪费），所以只需要处理 0 .. n/2-1。
 * 取 n/2 - 1 是从"i >= n/2 全是叶子"这个事实反推的第一个非叶子下标，
 * 保守且一定不漏（个别 n 为偶数的情况会多处理一个叶子，无妨）。
 *
 * -------------------------------------------------------------------
 * 为什么从后往前，而不是从前往后？
 * -------------------------------------------------------------------
 * sift_down 的前提是"它的两个孩子子树【已经】是合法堆"。
 * 下标大的节点在树里更深，先处理深节点，等处理到浅节点时，它的子树刚好已经修好。
 * 反过来（从 i=0 开始往前）前提不成立，修了也白修。
 *
 * -------------------------------------------------------------------
 * 为什么总代价是 O(n) 而不是 O(n log n)？（本节必考的复杂度题）
 * -------------------------------------------------------------------
 * 表面上看：n/2 个节点，每个最多下沉 log n 层 → O(n log n)。错在哪？
 * 错在"每个都下沉 log n 层"这个假设。真相是【下沉距离和层数成反比地集中】：
 *
 *   层 d            该层节点数      最坏下沉距离      该层总功上界
 *   第 0 层（根）        1              log n             1 * log n
 *   第 1 层              2              log n - 1         2 * (log n - 1)
 *   ...
 *   倒数第 2 层        n/4               2                 n/4 * 2
 *   最后一层          n/2               0                 0        ← 一半的人白拿
 *
 * 也就是说：一半节点根本不用动，四分之一节点最多动 1 步，八分之一最多 2 步…
 * 总功 = n * Σ d / 2^(d+1) = n * 1 = O(n)。（那个级数收敛到 1，大学高数里
 * 叫"差比级数求和"，这里当结论记住就行。）
 *
 * 直觉版：**树是个金字塔，绝大多数砖头压在最深的那几层，而最深的那几层
 * 到地面的距离最短。** 所以自底向上修，每人挪一点点，总量线性。
 *
 * 反过来"逐个 push 建堆"是 O(n log n) —— 因为 push 是【上浮】，新元素总是
 * 被加到最深的地方，它要往上爬的距离平均就是 log n 级别，跑不掉。
 * main.c 第 7 幕会用 cmp_count 把这两个数字实测出来，一比就懂。
 *
 * 边界：n == 0 → 空堆；n 大于容量 → 先扩容。原数组 arr 一个字节都不改
 * （我们用 memcpy 拷进堆里），因为参数是 const int *，这是承诺也是约束。
 */
int heap_build(Heap *h, const int *arr, int n)
{
    if (h == NULL || n < 0) {
        return -1;
    }
    if (n == 0) {
        h->size = 0;
        return 0;
    }

    /* 需要多少容量就扩到多少（一次到位，比 push 的翻倍更直接） */
    if (h->capacity < n) {
        int *fresh = realloc(h->data, (size_t)n * sizeof(int));
        if (fresh == NULL) {
            return -1;
        }
        h->data = fresh;
        h->capacity = n;
    }

    memcpy(h->data, arr, (size_t)n * sizeof(int));
    h->size = n;                     /* 先当成"一棵形状正确的树"，堆序性还不保证 */

    if (h->verbose) {
        printf("    build：先把 %d 个原样拷进数组（形状对了，堆序还没对）\n", n);
        heap_dump_with_ruler(h);
    }

    for (int i = n / 2 - 1; i >= 0; i--) {
        if (h->verbose) {
            printf("    自底向上下沉下标 %d（值 %d，它的子树已就绪）\n", i, h->data[i]);
        }
        sift_down(h, i);
    }

    if (h->verbose) {
        printf("    build 完成，堆序性成立：\n");
        heap_dump_with_ruler(h);
    }
    return 0;
}
