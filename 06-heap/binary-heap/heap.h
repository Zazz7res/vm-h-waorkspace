#ifndef HEAP_H
#define HEAP_H

/*
 * ===================================================================
 * 二叉堆 binary-heap —— 这一节的"菜单"
 * ===================================================================
 * 这个文件里【只有声明，没有实现】。它只回答一个问题：
 *   "堆一共能幹哪几件事，每件事的输入输出长什么样"。
 * 真正的代码在 heap.c 里，每个函数上方都有大块人话解释。
 *
 * -------------------------------------------------------------------
 * 先说清楚：堆到底是个什么东西
 * -------------------------------------------------------------------
 * 一句话：**堆就是一颗被压扁成数组的完全二叉树。**
 *
 * 树形（人眼看的样子）：          数组（内存里真实的样子）：
 *            1                        [ 1  3  2  7  9  5  6 ]
 *         /     \                      下标 0  1  2  3  4  5  6
 *       3         2
 *     /   \     /   \              三条公式（本项目全部用 0 起下标）：
 *   7     9   5     6                父(i)   = (i - 1) / 2
 *                                    左(i)   = 2*i + 1
 *                                    右(i)   = 2*i + 2
 *
 * 数组里【没有任何指针】。父子关系完全靠下标算出来 —— 这就是堆省内存、
 * 又对 CPU 缓存友好的根本原因（连续内存，一路顺序读）。
 *
 * -------------------------------------------------------------------
 * 堆的两条铁律（也叫"三个不变量"，任何一次操作前后都必须成立）
 * -------------------------------------------------------------------
 *   ① 结构性：它必须是【完全二叉树】—— 除了最后一层，每层都塞满；
 *      最后一层从左往右连续排，中间不能有洞。
 *      （数组下标是连续的 0,1,2,...,size-1，天生就没有洞，所以结构性是
 *        被数组这个载体"免费"保证的。你要主动破坏它只有一种办法：
 *        删掉一个中间的节点却把后面的元素整体搬走 —— 见 heap_pop 的注释。）
 *   ② 堆序性（最小堆）：**任何父亲 <= 它的孩子**。
 *
 *   ③ 由 ①+② 推出：堆顶 data[0] 一定是全局最小值。
 *
 * ⚠⚠ 最大误区，先在这里打一针预防针 ⚠⚠
 *   堆【只保证堆顶是全局最小】，它【不保证整体有序】。
 *   上面那个数组里 data[1]=3、data[3]=7，可 data[2]=2 比 data[1] 小 —— 数组
 *   根本不是升序的。想拿到有序序列，只有两条路：反复 heap_pop（这就是堆排序），
 *   或者对树做中序遍历（但堆不是二叉搜索树，中序也不保证有序）。
 *   详见 README 的"堆不是排序"一节，main.c 第 5 幕会把这个反例打印出来。
 *
 * -------------------------------------------------------------------
 * 为什么本文件不出现函数指针 / 不出现 void *
 * -------------------------------------------------------------------
 * 全项目元素类型固定 int。"最小堆还是最大堆"只用一个枚举字段 kind 记在结构体里，
 * 所有比较都走一个内部小函数 better()。想看 qsort 那种通用写法，等把这里
 * 彻底吃透了再去看不迟。
 */

#include <stddef.h>   /* size_t */

/* 堆的种类。
 * 只有两个取值，最大堆 = 把最小堆所有比较号反过来，代码一行都不用多写
 * （README"最大堆"一节详细讲这个事实，以及 std::priority_queue 默认是【最大堆】
 *   这个让无数初学者踩坑的反直觉设定）。 */
typedef enum {
    HEAP_MIN = 0,   /* 最小堆：父亲 <= 孩子，堆顶全局最小 */
    HEAP_MAX = 1    /* 最大堆：父亲 >= 孩子，堆顶全局最大 */
} HeapKind;

/* 堆的全部家当就这四个数组 + 三个数字。
 * 注意 data 是"堆里唯一的内存"，所以 heap_free 只需要 free(data) 一处。 */
typedef struct Heap {
    int      *data;      /* 真正的存储：一块连续的 int 数组，被压扁的完全二叉树 */
    int       size;      /* 当前有几个元素（树有多少个节点） */
    int       capacity;  /* data 这块数组现在能装多少个（>= size） */
    HeapKind  kind;      /* 最小堆还是最大堆 */
    int       verbose;   /* 开关：1 = 每次上浮/下沉都把数组打印出来（学习期开着） */
    long      cmp_count; /* 统计：一共做过多少次父子比较。用来实测"建堆为什么是 O(n)" */
} Heap;

/* ---------- 1. 生 / 死 ---------- */

/* 造一个堆。initial_capacity 是初始容量（装满了会自动翻倍扩容）。
 * kind 传 HEAP_MIN 或 HEAP_MAX。失败返回 NULL（内存不够）。 */
Heap *heap_new(int initial_capacity, HeapKind kind);

/* 释放堆。之后指针要自己置 NULL（00-c-foundation 里的铁律）。 */
void heap_free(Heap *h);

/* ---------- 2. 三个核心操作 ---------- */

/* 插入：放到数组末尾（保住完全二叉树），再"上浮"到该待的位置。O(log n)。
 * 返回 0 = 成功，-1 = 失败（内存不够）。 */
int heap_push(Heap *h, int value);

/* 取走堆顶（最小堆里是最小值）。
 * 做法是【堆顶和最后一个元素交换 → size 缩 1 → 新堆顶下沉】，
 * 绝对不能"删掉堆顶再把后面整体往前搬"。为什么？heap.c 里写了整整一块注释。
 * 取不到值时返回 -1（堆空）。out 可以传 NULL 表示"我只要它把堆顶扔掉，值我不关心"。 */
int heap_pop(Heap *h, int *out);

/* 只看堆顶、不删。O(1)。空堆返回 -1。 */
int heap_peek(const Heap *h, int *out);

/* ---------- 3. 建堆：把一整堆现成数据变成堆 ---------- */

/* 经典 heapify：从最后一个"有孩子的节点"（下标 size/2 - 1）开始，
 * 自底向上逐个下沉。总代价 O(n)，不是 O(n log n)。
 * 为什么是 O(n)：绝大多数节点待在最后一两层，下沉距离几乎为 0。
 * 本函数结束后 size = n，堆序性成立；数组里就是原数据（被就地重排）。
 * 返回 0 成功，-1 失败。 */
int heap_build(Heap *h, const int *arr, int n);

/* ---------- 4. 查状态 ---------- */
int  heap_size(const Heap *h);            /* 元素个数（h 为 NULL 时返回 0，方便打印） */
int  heap_empty(const Heap *h);           /* 1 空 0 不空 */
int  heap_capacity(const Heap *h);        /* 当前数组能装多少 */
void heap_reset_stats(Heap *h);           /* cmp_count 归零，用来做复杂度实测 */
long heap_cmp_count(const Heap *h);       /* 读比较次数 */

/* ---------- 5. 打印：让"堆化"过程看得见 ---------- */

/* 只打印数组这一行，带上下标刻度。verbose 关掉时不打印。 */
void heap_dump(const Heap *h, const char *note);

/* 完整版打印：先按【树形逐层】打印（每层一行、标出数组下标），
 * 再打印【数组形式】，两者上下对照 —— 这是理解"压扁成数组"最重要的一张图。 */
void heap_print(const Heap *h);

/* 打印一张"下标关系表"：每个下标的 父 / 左 / 右 是谁，
 * 并现场验证 (i-1)/2、2i+1、2i+2 三条公式。传 n 就想看前 n 个下标。 */
void heap_print_relations(int n);

/* ---------- 6. 开关 ---------- */
void heap_set_verbose(Heap *h, int on);   /* 0 = 安静（跑大数据时用） */

/* ---------- 7. 三个下标公式：暴露出来给 main.c 做演示用 ---------- */
int heap_parent(int i);   /* i 的父亲下标；i==0 时返回 -1（根没爹） */
int heap_left(int i);     /* 左孩子下标（可能越界，调用方自己判断 < size） */
int heap_right(int i);    /* 右孩子下标 */

#endif /* HEAP_H */
